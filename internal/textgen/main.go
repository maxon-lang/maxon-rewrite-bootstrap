// Command textgen generates, from the Unicode data files in ucd/, the table that the text operations of the runtime
// (runtime/textops.maxon) read to cut a string into grapheme clusters (UAX #29): the class of every code point that is
// not Other. `go generate ./internal/textgen` runs it.
package main

//go:generate go run .

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"strconv"
	"strings"
)

const header = "Code generated by internal/textgen from internal/textgen/ucd; DO NOT EDIT."

// The files that the table is made from: Unicode 16.0.0.
const (
	graphemeBreakFile = "ucd/GraphemeBreakProperty.txt"
	emojiDataFile     = "ucd/emoji-data.txt"
)

// outputs are the generated files: the runtime's, the interpreter's, which runs the same text operations, and the parser's,
// which holds a character literal to one grapheme cluster.
var outputs = []string{
	"../../runtime/unicode_gen.maxon",
	"../../self/interp/unicode_gen.maxon",
	"../../self/syntax/unicode_gen.maxon",
}

const (
	codePointCount  = 0x110000
	pictographic    = "Extended_Pictographic"
	hangulFirst     = 0xAC00
	hangulLast      = 0xD7A3
	hangulTailCount = 28
	// The table is a string of entries of tableDigits digits, each of tableDigitBits bits: the first code point of a
	// run of one class, shifted up by tableClassBits, and the class.
	tableDigits    = 5
	tableDigitBits = 6
	tableClassBits = 4
	// The digits are the characters from '0', but for the backslash, which a string literal would read as an escape.
	digitFirst  = '0'
	digitEscape = '\\'
)

// classes are the grapheme cluster classes, in the order of their numbers in the table. LV and LVT are not in the table:
// a Hangul syllable is one or the other by its position in the block, which the runtime computes.
var classes = []struct{ name, property string }{
	{"classOther", ""},
	{"classCarriageReturn", "CR"},
	{"classLineFeed", "LF"},
	{"classControl", "Control"},
	{"classExtend", "Extend"},
	{"classZeroWidthJoiner", "ZWJ"},
	{"classRegionalIndicator", "Regional_Indicator"},
	{"classSpacingMark", "SpacingMark"},
	{"classHangulL", "L"},
	{"classHangulV", "V"},
	{"classHangulT", "T"},
	{"classHangulLV", "LV"},
	{"classHangulLVT", "LVT"},
	{"classPrepend", "Prepend"},
	{"classPictographic", pictographic},
}

func main() {
	text, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "textgen:", err)
		os.Exit(1)
	}
	for _, path := range outputs {
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "textgen:", err)
			os.Exit(1)
		}
	}
}

// classOf is the number of a property's class.
func classOf(property string) (int, bool) {
	for i, c := range classes {
		if c.property == property && property != "" {
			return i, true
		}
	}
	return 0, false
}

// readProperties sets the class of each code point that a data file gives a property of a class, in the order of the file.
func readProperties(path string, class []byte) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		fields := strings.Split(line, ";")
		if len(fields) != 2 {
			continue
		}
		c, ok := classOf(strings.TrimSpace(fields[1]))
		if !ok {
			continue
		}
		first, last, err := parseRange(strings.TrimSpace(fields[0]))
		if err != nil {
			return fmt.Errorf("%s: %v", path, err)
		}
		for cp := first; cp <= last; cp++ {
			class[cp] = byte(c)
		}
	}
	return sc.Err()
}

func parseRange(text string) (first, last int, err error) {
	lo, hi, _ := strings.Cut(text, "..")
	a, err := strconv.ParseInt(lo, 16, 32)
	if err != nil {
		return 0, 0, err
	}
	if hi == "" {
		return int(a), int(a), nil
	}
	b, err := strconv.ParseInt(hi, 16, 32)
	return int(a), int(b), err
}

// hangulClass is the class of a Hangul syllable, which the table leaves out.
func hangulClass(cp int) int {
	if (cp-hangulFirst)%hangulTailCount == 0 {
		c, _ := classOf("LV")
		return c
	}
	c, _ := classOf("LVT")
	return c
}

// digit is the character of the value v of a digit.
func digit(v int) byte {
	c := byte(digitFirst + v)
	if c >= digitEscape {
		c++
	}
	return c
}

// generate is the text of the generated Maxon file.
func generate() (string, error) {
	class := make([]byte, codePointCount)
	if err := readProperties(graphemeBreakFile, class); err != nil {
		return "", err
	}
	if err := readProperties(emojiDataFile, class); err != nil {
		return "", err
	}
	// The runtime computes the Hangul syllables, so the data must agree with the rule it is given.
	for cp := hangulFirst; cp <= hangulLast; cp++ {
		if int(class[cp]) != hangulClass(cp) {
			return "", fmt.Errorf("U+%04X is not the Hangul syllable class that its position gives", cp)
		}
		class[cp] = 0
	}
	if codePointCount<<tableClassBits >= 1<<(tableDigits*tableDigitBits) {
		return "", fmt.Errorf("an entry does not fit %d digits", tableDigits)
	}
	var table strings.Builder
	entries := 0
	for cp := range codePointCount {
		if cp > 0 && class[cp] == class[cp-1] {
			continue
		}
		value := cp<<tableClassBits | int(class[cp])
		for d := tableDigits - 1; d >= 0; d-- {
			table.WriteByte(digit(value >> (d * tableDigitBits) & (1<<tableDigitBits - 1)))
		}
		entries++
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\n", header)
	b.WriteString("// StrGraphemeClass is what a code point is to the grapheme cluster rules of UAX #29: its Grapheme_Cluster_Break value,\n" +
		"// with the code points of Extended_Pictographic as their own class.\n")
	b.WriteString("enum StrGraphemeClass\n")
	for _, c := range classes {
		fmt.Fprintf(&b, "\t%s\n", c.name)
	}
	b.WriteString("end 'StrGraphemeClass'\n\n")
	b.WriteString("// strGraphemeClassOfNumber is the class that a number of the table stands for.\n")
	b.WriteString("function strGraphemeClassOfNumber(number Count) returns StrGraphemeClass\n")
	for i, c := range classes[:len(classes)-1] {
		fmt.Fprintf(&b, "\tif number == %d '%s'\n\t\treturn StrGraphemeClass.%s\n\tend '%s'\n", i, c.name, c.name, c.name)
	}
	fmt.Fprintf(&b, "\treturn StrGraphemeClass.%s\n", classes[len(classes)-1].name)
	b.WriteString("end 'strGraphemeClassOfNumber'\n\n")
	b.WriteString("// strTableDigits is the number of characters of an entry of the table: the first code point of a run of one class, shifted\n// up by strTableClassBits, and the class, in strTableDigitBits bits a character, the first first.\n")
	fmt.Fprintf(&b, "let strTableDigits = %d as Count\n\n", tableDigits)
	fmt.Fprintf(&b, "let strTableDigitBits = %d as Count\n\n", tableDigitBits)
	fmt.Fprintf(&b, "let strTableClassBits = %d as Count\n\n", tableClassBits)
	fmt.Fprintf(&b, "let strTableClassMask = %d as Count\n\n", 1<<tableClassBits-1)
	b.WriteString("// strTableDigitFirst is the character of the digit 0; a character above strTableDigitEscape is the digit one more than its\n// distance from it, since a string literal does not hold that backslash.\n")
	fmt.Fprintf(&b, "let strTableDigitFirst = %d as Count\n\n", digitFirst)
	fmt.Fprintf(&b, "let strTableDigitEscape = %d as Count\n\n", digitEscape)
	fmt.Fprintf(&b, "let strTableEntryCount = %d as Count\n\n", entries)
	b.WriteString("// strGraphemeTable is the table of the classes: one entry for each run of code points of one class.\n")
	fmt.Fprintf(&b, "let strGraphemeTable = \"%s\"\n", table.String())
	return b.String(), nil
}
