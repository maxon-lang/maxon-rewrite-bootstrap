// Package arm64table is the arm64 instruction table (table.go) and the generator of self/backend's arm64 encoder from
// it: the register enum, one encoder function per form that appends the instruction's word to a code buffer, the
// encodings of the immediates that are not a plain field (a logical immediate, a scaled offset, a split distance), the
// ladder that sets a register to any word, the form enum and its FormIDs, and the encoder of a machine instruction.
// internal/arm64gen writes what Generate gives, and the generators of the machine IR and of instruction selection read
// the table as an isa.ISA (isa.go).
//
// The test of this package proves the table against the words the Go toolchain's arm64 assembler wrote, kept in
// testdata.
package arm64table

import (
	"fmt"
	"strings"

	"minimaxon/internal/isa"
)

const header = "// Code generated by internal/arm64gen from internal/arm64gen/arm64table/table.go; DO NOT EDIT.\n\n"

// tableError is a row of the table that the generator cannot make code of.
type tableError struct{ msg string }

func (e *tableError) Error() string { return e.msg }

func fail(format string, args ...any) {
	panic(&tableError{fmt.Sprintf(format, args...)})
}

// Generate is the Maxon of the encoder, or the error of a row it cannot make code of.
func Generate() (code string, err error) {
	defer func() {
		if r := recover(); r != nil {
			te, ok := r.(*tableError)
			if !ok {
				panic(r)
			}
			err = te
		}
	}()
	check()
	return emitMaxon(), nil
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

// param is a parameter of an encoder: its name and its Maxon type.
type param struct{ name, ty string }

const (
	typeRegister  = "Arm64Register"
	typeCondition = "MCond"
	// typeDisp is the type of an offset and of a distance, the machine IR's aux.
	typeDisp = "Imm32"
	// typeValue is the type of a logical immediate, the machine IR's imm.
	typeValue = "FullRangeInt"
)

// immType is the Maxon type of an unsigned field of a width: the range its bits hold.
func immType(bits int) string { return fmt.Sprintf("Arm64Imm%d", bits) }

// params are the parameters of an operand.
func (o operand) params() []param {
	switch o.kind {
	case kindReg:
		return []param{{o.name, typeRegister}}
	case kindImm:
		return []param{{o.name, immType(o.bits)}}
	case kindDisp, kindRel, kindAddress, kindPageOffset:
		return []param{{o.name, typeDisp}}
	case kindMask:
		return []param{{o.name, typeValue}}
	case kindCond:
		return []param{{o.name, typeCondition}}
	default:
		panic(fmt.Sprintf("operand kind %d has no parameters", o.kind))
	}
}

func (f form) params() []param {
	var ps []param
	for _, o := range f.operands {
		ps = append(ps, o.params()...)
	}
	return ps
}

// isPatched is whether a reference patches an operand's field, which the encoder of a machine instruction writes as 0.
func isPatched(k kind) bool { return k == kindRel || k == kindAddress || k == kindPageOffset }

// isUnits is whether an operand's field holds a value in units of its scale, which the field's bits must hold.
func isUnits(k kind) bool {
	return k == kindDisp || k == kindRel || k == kindAddress || k == kindPageOffset
}

// unitRange is the units a field of an operand holds: from 0 for an unsigned one, around 0 for a signed one.
func unitRange(o operand) (lo, hi int64) {
	if o.signed {
		return -(1 << (o.bits - 1)), 1<<(o.bits-1) - 1
	}
	return 0, 1<<o.bits - 1
}

func withKind(f form, k kind) (operand, bool) {
	for _, o := range f.operands {
		if o.kind == k {
			return o, true
		}
	}
	return operand{}, false
}

func formByName(name string) form {
	for _, f := range forms {
		if f.name == name {
			return f
		}
	}
	fail("there is no form %s", name)
	return form{}
}

// machineForms are the forms of the machine IR, in the order of the form enum: every form that is not direct.
func machineForms() []form {
	var out []form
	for _, f := range forms {
		if !f.direct {
			out = append(out, f)
		}
	}
	return out
}

// check refuses a table that has no encoding.
func check() {
	seen := map[string]bool{}
	for _, f := range forms {
		if seen[f.name] {
			fail("%s is declared twice", f.name)
		}
		seen[f.name] = true
		checkForm(f)
		if !f.direct {
			checkAlloc(f)
		}
	}
	if len(machineForms()) > isa.FormRange {
		fail("arm64 has %d forms, past the %d FormIDs of an instruction set", len(machineForms()), isa.FormRange)
	}
	checkEffects()
	checkConditions()
}

// checkConditions refuses a table whose conditions are not the machine IR's in order, or whose code cset cannot invert.
func checkConditions() {
	if len(conditions) != len(isa.Conditions) {
		fail("the table has %d conditions and the machine IR %d", len(conditions), len(isa.Conditions))
	}
	for i, c := range conditions {
		if c.name != isa.Conditions[i] {
			fail("condition %d is %s, and MCond's case %d is %s", i, c.name, i, isa.Conditions[i])
		}
		if c.code < 0 || c.code >= alwaysCode {
			fail("condition %s has the code %d, which is always or never and has no opposite", c.name, c.code)
		}
	}
}

// checkForm refuses a form whose fields overlap one another or its opcode's bits, or leave the word.
func checkForm(f form) {
	used := f.opcode
	if f.name == "" || f.mnemonic == "" {
		fail("a form with no name or no mnemonic, opcode 0x%08X", f.opcode)
	}
	patched, aux, imm := 0, 0, 0
	for i, o := range f.operands {
		var fieldMask uint32
		switch o.kind {
		case kindReg:
			if o.bits != regBits || o.access == accessNone {
				fail("%s: register %s has no 5-bit field or no access", f.name, o.name)
			}
			fieldMask = bitsAt(o.at, o.bits)
		case kindImm, kindDisp, kindRel, kindPageOffset, kindCond, kindMask:
			fieldMask = bitsAt(o.at, o.bits)
		case kindAddress:
			fieldMask = bitsAt(immloAt, immloBits) | bitsAt(immhiAt, o.bits-immloBits)
		default:
			fail("%s: operand %s is of no known kind", f.name, o.name)
		}
		if o.kind != kindReg && (o.access != accessNone || o.vector || o.stack) {
			fail("%s: %s is no register and has a register's access", f.name, o.name)
		}
		if isUnits(o.kind) != (o.scale > 0) {
			fail("%s: %s has a scale exactly when its field counts units", f.name, o.name)
		}
		if used&fieldMask != 0 {
			fail("%s: the field of %s overlaps the opcode or another field", f.name, o.name)
		}
		used |= fieldMask
		if isPatched(o.kind) {
			patched++
			if i != len(f.operands)-1 {
				fail("%s: the field a reference patches is not its last operand", f.name)
			}
		}
		switch o.kind {
		case kindDisp:
			aux++
		case kindImm, kindMask:
			imm++
		}
	}
	if patched > 1 {
		fail("%s has two fields a reference patches", f.name)
	}
	if imm > 2 || aux+imm > 2 || (aux > 0 && imm > 1) {
		fail("%s has more immediates than the imm and aux of a machine instruction hold", f.name)
	}
}

// logicalBits is the width of a logical immediate's N:immr:imms.
const logicalBits = 13

// bitsAt is the mask of a field.
func bitsAt(at, bits int) uint32 {
	if at < 0 || bits <= 0 || at+bits > 32 {
		fail("a field of %d bits at %d is not in a word", bits, at)
	}
	return uint32((uint64(1)<<bits - 1) << at)
}

// checkEffects refuses a table in which no form has an effect or every form does, which says that a column is wrong.
func checkEffects() {
	for _, e := range effectList {
		any, all := false, true
		for _, f := range forms {
			if e.of(f) {
				any = true
			} else {
				all = false
			}
		}
		if !any || all {
			fail("%s is true of no form or of every form", e.name)
		}
	}
}

// effectList are the predicates of the effects.
var effectList = []struct {
	name string
	of   func(form) bool
}{
	{"setsFlags", func(f form) bool { return f.setsFlags }},
	{"readsFlags", func(f form) bool { return f.readsFlags }},
	{"readsMemory", func(f form) bool { return f.readsMemory }},
	{"writesMemory", func(f form) bool { return f.writesMemory }},
}
