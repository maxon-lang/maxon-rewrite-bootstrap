package main

// reservedFile is where cmd/convert, which warns of a Maxon name that minimaxon reserves, finds the keywords.
const reservedFile = "../../cmd/convert/reserved_gen.go"

// operandNameRule and operandNameLabel are the rule and the label of the name that an operand reads, whose keywords are
// those a function or a parameter named by a keyword can be read or called by.
const (
	operandNameRule  = "nameExpr"
	operandNameLabel = "name"
)

func emitReserved(m *model) string {
	w := &writer{}
	w.p("// Code generated by internal/grammargen from %s; DO NOT EDIT.\n\npackage main\n\n", grammarName)
	w.p("// reservedWords are the keywords of minimaxon.\n")
	w.p("var reservedWords = map[string]bool{\n")
	for _, k := range m.keywords {
		w.p("\t%q: true,\n", k)
	}
	w.p("}\n\n")
	w.p("// operandWords are the keywords an operand may be: a function or a parameter named by one of them can be called or read.\n")
	w.p("var operandWords = map[string]bool{\n")
	for _, k := range operandKeywords(m) {
		w.p("\t%q: true,\n", k)
	}
	w.p("}\n")
	return w.b.String()
}

// operandKeywords are the keywords of the name an operand reads, in the grammar's order of keywords; a grammar with no
// such rule has none.
func operandKeywords(m *model) []string {
	var taken map[string]bool
	r := m.ruleByName[operandNameRule]
	if r == nil {
		return nil
	}
	m.walkElems(r.alts, func(e *elem) {
		if e.kind != ekGroup || e.label != operandNameLabel {
			return
		}
		taken = map[string]bool{}
		for _, a := range e.group {
			if len(a.elems) == 1 && a.elems[0].kind == ekLiteral {
				taken[a.elems[0].text] = true
			}
		}
	})
	if taken == nil {
		m.fail(r.line, "the rule %s has no group labelled %s, whose keywords an operand may be", operandNameRule, operandNameLabel)
	}
	var words []string
	for _, k := range m.keywords {
		if taken[k] {
			words = append(words, k)
		}
	}
	return words
}
