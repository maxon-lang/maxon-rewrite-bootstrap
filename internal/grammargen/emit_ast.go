package main

import (
	"fmt"
	"strings"
)

type writer struct{ b strings.Builder }

func (w *writer) p(format string, args ...any) { fmt.Fprintf(&w.b, format, args...) }

func header(w *writer, pkg string, imports ...string) {
	w.p("// Code generated by internal/grammargen from %s; DO NOT EDIT.\n\npackage %s\n\n", grammarFile, pkg)
	for _, imp := range imports {
		w.p("import %q\n\n", imp)
	}
}

// rootEmbed is what every node struct starts with: the position and the NodeID, defined by hand in package ast.
const rootEmbed = "Head"

func emitNodes(m *model) string {
	w := &writer{}
	header(w, "ast", "fmt", "minimaxon/internal/diag")

	emitKinds(w, m)
	emitted := map[*node]bool{}
	emitNode := func(n *node) {
		if emitted[n] {
			return
		}
		emitted[n] = true
		if n.record {
			emitRecord(w, m, n)
			return
		}
		embed := rootEmbed
		if n.set != nil {
			embed = n.set.name + "Base"
		}
		emitStruct(w, m, n.name, embed, n.fields)
	}
	for _, r := range m.g.rules {
		switch m.kind[r] {
		case rkSet:
			s := m.setOfRule[r]
			if len(s.members) > 0 && s.members[0].record {
				emitRecordSet(w, s)
			} else {
				embed := rootEmbed
				if s.parent != nil {
					embed = s.parent.name + "Base"
				}
				emitStruct(w, m, s.name+"Base", embed, s.base)
			}
			for _, a := range r.alts {
				if a.label != "" {
					emitNode(m.nodeByName[a.label])
				}
			}
		case rkNode:
			if r.builds == "" {
				emitNode(m.nodeOfRule[r])
			}
		}
	}

	emitTreeParts(w, m)

	w.p("var reservedWords = map[string]bool{\n")
	for _, k := range m.keywords {
		w.p("\t%q: true,\n", k)
	}
	w.p("}\n\nfunc IsReserved(word string) bool { return reservedWords[word] }\n\n")

	for _, s := range m.sets {
		emitVisitors(w, s)
	}
	return w.b.String()
}

func emitStruct(w *writer, m *model, name, embed string, fields []*field) {
	w.p("type %s struct {\n\t%s\n", name, embed)
	for _, f := range fields {
		if f.slot != "" {
			continue
		}
		if f.gap {
			w.p("\n")
		}
		// A field that parsing does not set is written in Go as it is.
		typ := f.typ
		if len(f.elems) > 0 {
			typ = m.goType(typ)
		}
		w.p("\t%s %s\n", f.name, typ)
	}
	w.p("}\n\n")
}

type flavour struct {
	suffix     string
	typeParams string
	typeArgs   string
	param      string
	arg        string
	result     string
}

// The three ways a phase walks a set: for effect, computing a result, or threading a state through and returning one.
var flavours = []flavour{
	{suffix: "Visitor"},
	{suffix: "ResultVisitor", typeParams: "[R any]", typeArgs: "[R]", result: " R"},
	{suffix: "StateVisitor", typeParams: "[S, R any]", typeArgs: "[S, R]", param: ", s S", arg: ", s", result: " R"},
}

func emitVisitors(w *writer, s *set) {
	records := len(s.members) > 0 && s.members[0].record
	if !records {
		w.p("var (\n")
		for _, n := range s.members {
			w.p("\t_ %s = (*%s)(nil)\n", s.name, n.name)
		}
		w.p(")\n\n")
	}
	// A visitor of records takes the view of each node; a visitor of structs, the pointer.
	param := func(n *node) string {
		if records {
			return n.name
		}
		return "*" + n.name
	}
	for _, f := range flavours {
		iface := s.name + f.suffix
		w.p("type %s%s interface {\n", iface, f.typeParams)
		for _, n := range s.members {
			w.p("\tVisit%s(n %s%s)%s\n", n.name, param(n), f.param, f.result)
		}
		w.p("}\n\n")
		fn := "Visit" + s.name + strings.TrimSuffix(f.suffix, "Visitor")
		if records {
			w.p("func %s%s(v %s%s, n %s%s)%s {\n\tswitch n.Kind() {\n", fn, f.typeParams, iface, f.typeArgs, s.name, f.param, f.result)
		} else {
			w.p("func %s%s(v %s%s, n %s%s)%s {\n\tswitch n := n.(type) {\n", fn, f.typeParams, iface, f.typeArgs, s.name, f.param, f.result)
		}
		for _, m := range s.members {
			arg := "n"
			label := "*" + m.name
			if records {
				arg = m.name + "{n.Ref}"
				label = kindName(m)
			}
			if f.result == "" {
				w.p("\tcase %s:\n\t\tv.Visit%s(%s%s)\n\t\treturn\n", label, m.name, arg, f.arg)
			} else {
				w.p("\tcase %s:\n\t\treturn v.Visit%s(%s%s)\n", label, m.name, arg, f.arg)
			}
		}
		if records {
			w.p("\t}\n\tpanic(diag.Internal(\"unhandled %s %%s\", n.Kind()))\n}\n\n", s.name)
		} else {
			w.p("\t}\n\tpanic(diag.Internal(\"unhandled %s %%T\", n))\n}\n\n", s.name)
		}
	}
}

func emitTokens(m *model) string {
	w := &writer{}
	header(w, "syntax", "minimaxon/internal/diag")
	w.p("type T int\n\nconst (\n")
	first := true
	for _, t := range m.g.tokens {
		if t.skip {
			continue
		}
		if first {
			w.p("\tT%s T = iota\n", t.name)
			first = false
		} else {
			w.p("\tT%s\n", t.name)
		}
	}
	w.p("\t%s\n", eofConst)
	for _, k := range m.keywords {
		w.p("\t%s\n", keywordConst(k))
	}
	w.p("\tnumTokens\n")
	w.p("\t// The skipped tokens: the lexer checks and drops them, so the parser never sees one.\n")
	for _, t := range m.g.tokens {
		if t.skip {
			w.p("\tT%s\n", t.name)
		}
	}
	w.p("\t// noToken is what a DFA state that accepts no token accepts.\n\tnoToken\n)\n\n")
	emitDfa(w, m)
	return w.b.String()
}
