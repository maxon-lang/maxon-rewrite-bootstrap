const maxonParserFile = "../../self/syntax/parser_gen.maxon"

// maxonLang writes the Maxon parser, self/syntax/parser_gen.maxon. A parse function is a function of the module that
// takes the parser, and fails with SyntaxError after recording the error in it, as the Go parser panics. Maxon refuses an
// argument that overlaps another, so every value that is stored in the parser or a node is first held by a local; it
// has no switch, so every choice is an if chain, each block carrying a label of its own.
type maxonLang struct {
	g *pgen
	w *writer
	// depth is how many blocks the next line is inside.
	depth int
	// fn is the function being written, temps and labels count the locals and the block labels it has used, and open
	// holds the labels of the blocks it has open.
	fn            string
	temps, labels int
	open          []string
}

func emitMaxonParser(m *model, a *analysis) string { return walkParser(m, a, &maxonLang{}) }

func (l *maxonLang) start(g *pgen, body *writer) { l.g, l.w = g, body }

func (l *maxonLang) line(s string) {
	l.w.p("%s%s\n", strings.Repeat("\t", l.depth), s)
}

func (l *maxonLang) linef(format string, args ...any) { l.line(fmt.Sprintf(format, args...)) }

func (l *maxonLang) file(body string) string {
	g := l.g
	w := &writer{}
	w.p("// Code generated by internal/grammargen from %s; DO NOT EDIT.\n", grammarFile)
	kinds, _ := tokenKinds(g.m)
	for _, name := range g.setList {
		w.p("\nlet %s = %q\n", name, kindSetText(kinds, g.setTerms[name]))
	}
	w.p("\n// ListStacks has a stack for each type of element that a list of structs in the grammar holds, and one for the\n")
	w.p("// numbers of the records and texts that each list of the tree holds.\ntype ListStacks\n")
	var fields []string
	for _, name := range g.idStacks {
		w.p("\tvar %s as ListStack with diag.U32\n", name)
		fields = append(fields, name)
	}
	for _, elem := range g.lists {
		w.p("\tvar %s as ListStack with %s\n", listField(elem), maxonElemType(g.m, elem))
		fields = append(fields, listField(elem))
	}
	inits := make([]string, len(fields))
	for i, f := range fields {
		inits[i] = f + ": ListStack.new()"
	}
	w.p("\n\tstatic function new() returns ListStacks\n\t\treturn ListStacks{%s}\n\tend 'new'\n", strings.Join(inits, ", "))
	w.p("\n\tfunction reset(mutates self)\n")
	for _, f := range fields {
		w.p("\t\t%s.reset()\n", f)
	}
	if len(fields) == 0 {
		w.p("\t\treturn\n")
	}
	w.p("\tend 'reset'\nend 'ListStacks'\n\n")
	w.b.WriteString(strings.TrimSuffix(body, "\n"))
	return w.b.String()
}

// maxonElemType is the Maxon type of an element of a list of structs, as package syntax names it.
func maxonElemType(m *model, elem string) string {
	if t, ok := m.maxonType(elem, astQualifier); ok {
		return t
	}
	m.fail(0, "a list of %s has no Maxon type", elem)
	return ""
}

// kindSetMember and kindSetNonMember are the characters of a kind in a set of kinds and of one that is not.
const kindSetMember, kindSetNonMember = '1', '0'

// kindSetText is a set of token kinds as Maxon holds it: a character per kind, in the order of their numbers.
func kindSetText(kinds, terms []string) string {
	var b strings.Builder
	for _, k := range kinds {
		if slices.Contains(terms, k) {
			b.WriteByte(kindSetMember)
		} else {
			b.WriteByte(kindSetNonMember)
		}
	}
	return b.String()
}

// maxonKind is the Maxon name of a token kind that Go names goName: the case of TokenKind.
func maxonKind(goName string) string {
	return lowerFirst(strings.TrimPrefix(goName, "T"))
}

func (l *maxonLang) term(goName string) string { return "TokenKind." + maxonKind(goName) }

func (l *maxonLang) at(term string) string     { return "p.at(" + l.term(term) + ")" }
func (l *maxonLang) in(set string) string      { return "p.inSet(" + set + ")" }
func (l *maxonLang) peekIs(term string) string { return "p.peekIs(" + l.term(term) + ")" }
func (l *maxonLang) peekIn(set string) string  { return "p.peekIn(" + set + ")" }
func (l *maxonLang) and(a, b string) string    { return a + " and " + b }
func (l *maxonLang) or(parts []cond) string    { return joinConds(parts, " or ") }
func (l *maxonLang) not(c string) string       { return "not " + c }

func (l *maxonLang) less(prec int, v string) string { return fmt.Sprintf("%d < %s", prec, v) }

func (l *maxonLang) hasSwitch() bool { return false }

func (l *maxonLang) switchOpen()       { panic("grammargen: Maxon has no switch") }
func (l *maxonLang) caseOpen([]string) { panic("grammargen: Maxon has no switch") }
func (l *maxonLang) defaultOpen()      { panic("grammargen: Maxon has no switch") }
func (l *maxonLang) switchClose()      { panic("grammargen: Maxon has no switch") }
func (l *maxonLang) newLabel() string  { l.labels++; return fmt.Sprintf("'b%d'", l.labels) }
func (l *maxonLang) pushLabel() string { lb := l.newLabel(); l.open = append(l.open, lb); return lb }
func (l *maxonLang) popLabel() string {
	lb := l.open[len(l.open)-1]
	l.open = l.open[:len(l.open)-1]
	return lb
}
func (l *maxonLang) blockOpen(s string) { l.line(s); l.depth++ }

func (l *maxonLang) ifOpen(c string) { l.blockOpen("if " + c + " " + l.pushLabel()) }

func (l *maxonLang) elseIfOpen(c string) {
	l.depth--
	end := l.popLabel()
	l.blockOpen("end " + end + " else if " + c + " " + l.pushLabel())
}

func (l *maxonLang) elseOpen() {
	l.depth--
	end := l.popLabel()
	l.blockOpen("end " + end + " else " + l.pushLabel())
}

func (l *maxonLang) whileOpen(c string) { l.blockOpen("while " + c + " " + l.pushLabel()) }

func (l *maxonLang) close() {
	l.depth--
	l.line("end " + l.popLabel())
}

// The operator tails are a loop while the next token starts one, with an if chain that picks it.
func (l *maxonLang) tailsOpen(all []string) { l.whileOpen(l.g.atAny(all)) }

func (l *maxonLang) tailOpen(i int, terms []string) {
	if i == 0 {
		l.ifOpen(l.g.atAny(terms))
	} else {
		l.elseIfOpen(l.g.atAny(terms))
	}
}

func (l *maxonLang) tailsClose(left string) {
	l.close()
	l.close()
	l.ret(left)
}

func (l *maxonLang) refuse(desc string) { l.line("throw p.expected(" + maxonQuote(desc) + ")") }

func (l *maxonLang) expect(term, desc string) string {
	return fmt.Sprintf("try p.expect(%s, what: %s)", l.term(term), maxonQuote(desc))
}
func (l *maxonLang) next() string        { return "try p.next()" }
func (l *maxonLang) call(r *rule) string { return "try " + parseFunc(r) + "(p)" }
func (l *maxonLang) callAfter(r *rule, first string) string {
	return fmt.Sprintf("try %sAfter(p, t: t, first: %s)", parseFunc(r), first)
}
func (l *maxonLang) callPrec(fn, prec string) string {
	return fmt.Sprintf("try %s(p, minPrec: %s)", fn, prec)
}

func (l *maxonLang) stmt(expr string)                    { l.line("_ = " + expr) }
func (l *maxonLang) assign(dst, value string)            { l.line(dst + " = " + value) }
func (l *maxonLang) assignText(dst, value string) string { return dst + " = " + value }
func (l *maxonLang) setJoin()                            { l.line("p.joinNext = true") }

func (l *maxonLang) joinsOpen(c string) string {
	l.temps++
	joins := fmt.Sprintf("joins%d", l.temps)
	l.linef("let %s = %s", joins, c)
	return joins
}

func (l *maxonLang) joinsClose(joins string) { l.linef("p.joinNext = p.joinNext or %s", joins) }

func (l *maxonLang) bind(expr string) string {
	if isWord(expr) {
		return expr
	}
	l.temps++
	v := fmt.Sprintf("v%d", l.temps)
	l.linef("let %s = %s", v, expr)
	return v
}

func (l *maxonLang) text(tok string) string    { return "p.text(" + tok + ")" }
func (l *maxonLang) textRef(tok string) string { return "p.textRef(" + tok + ")" }
func (l *maxonLang) conversion(n *node, f *field, tok string) string {
	return fmt.Sprintf("try %s%s(p, t: %s)", lowerFirst(n.name), f.name, tok)
}

func (l *maxonLang) setStructField(_ *node, f *field, value string) string {
	return fmt.Sprintf("n.%s = %s", l.g.m.maxonField(f), value)
}

// setRecordField calls the setter of self/ast/nodes_gen.maxon for the field, which takes the value under the label its
// storage gives it.
func (l *maxonLang) setRecordField(n *node, fp *fieldPlan, value string) string {
	v := l.bind(value)
	setter := "ast.set" + n.name + fp.f.name
	switch fp.st {
	case stText, stLabel, stWord, stList, stTexts:
		return fmt.Sprintf("%sRef(p.tree, id: n, ref: %s)", setter, v)
	case stNode, stI128:
		return fmt.Sprintf("%s(p.tree, id: n, value: %s)", setter, v)
	case stEnum:
		return fmt.Sprintf("%s(p.tree, id: n, text: %s)", setter, v)
	}
	panic(fmt.Sprintf("grammargen: field %s of %s takes no value", fp.f.name, n.name))
}

func (l *maxonLang) setRecordFlag(n *node, fp *fieldPlan) string {
	return fmt.Sprintf("ast.set%s%s(p.tree, id: n)", n.name, fp.f.name)
}

// convert is a struct as the union of the outermost set it is in, where the value goes into one of its sets; a record
// is its number in every set.
func (l *maxonLang) convert(n *node, dst, value string) string {
	if !n.record && n.set != nil && n.name != dst && l.g.m.inSet(n, dst) {
		return l.asSet(n, value)
	}
	return value
}

func (l *maxonLang) asSet(n *node, value string) string {
	if n.record || n.set == nil {
		return value
	}
	return fmt.Sprintf("%s%s.%s(%s)", astQualifier, rootSet(n.set).name, lowerFirst(n.name), value)
}

// rootSet is the outermost set that s is part of, whose union holds the structs of every set in it.
func rootSet(s *set) *set {
	for s.parent != nil {
		s = s.parent
	}
	return s
}

func (l *maxonLang) pushed(typ, value string) string {
	if _, _, ok := l.g.m.refersToRecord(typ); ok {
		return value + " as diag.U32"
	}
	return value
}

func (l *maxonLang) push(stack, value string) { l.linef("%s.push(%s)", stack, l.bind(value)) }

func (l *maxonLang) mark(name, stack string) { l.linef("let %s = %s.mark()", name, stack) }

func (l *maxonLang) takeRecords(_, stack, mark string) string { return l.takeTexts(stack, mark) }

func (l *maxonLang) takeTexts(stack, mark string) string {
	return fmt.Sprintf("takeIDs(p.tree, stack: %s, mark: %s)", stack, mark)
}

func (l *maxonLang) takeStructs(stack, mark string) string {
	return fmt.Sprintf("%s.take(%s)", stack, mark)
}

func (l *maxonLang) pushedSince(stack, mark string) string {
	return fmt.Sprintf("%s.pushedSince(%s)", stack, mark)
}

func (l *maxonLang) funcOpen(name string, params []param, ret string) {
	l.fn, l.temps, l.labels, l.open = name, 0, 0, nil
	ps := []string{"mutates p Parser"}
	for _, p := range params {
		convention := ""
		if !isScalarMaxonType(p.typ) {
			convention = "consumes "
		}
		ps = append(ps, convention+p.name+" "+p.typ)
	}
	l.linef("function %s(%s) returns %s throws SyntaxError", name, strings.Join(ps, ", "), ret)
	l.depth++
}

func (l *maxonLang) funcClose() {
	l.depth--
	l.linef("end '%s'", l.fn)
	l.w.p("\n")
}

// isScalarMaxonType is whether a value of the type is a number, which a function takes as it is rather than taking it
// over.
func isScalarMaxonType(typ string) bool {
	return typ == "diag.U32" || typ == astQualifier+"NodeID" || typ == "Count"
}

func (l *maxonLang) startType() string { return "diag.U32" }

func (l *maxonLang) valueType(r *rule) string { return l.helperType(l.g.m.valueType(r)) }

func (l *maxonLang) nodeType(n *node) string {
	if n.record {
		return astQualifier + "NodeID"
	}
	return astQualifier + n.name
}

func (l *maxonLang) setType(s *set) string {
	if len(s.members) > 0 && !s.members[0].record {
		return astQualifier + rootSet(s).name
	}
	return astQualifier + "NodeID"
}

func (l *maxonLang) helperType(typ string) string {
	if t, ok := l.g.m.maxonType(typ, astQualifier); ok {
		return t
	}
	if s := l.g.m.setByName(typ); s != nil {
		return l.setType(s)
	}
	l.g.fail(0, "the type %s has no Maxon type", typ)
	return ""
}

func (l *maxonLang) precType() string { return "Count" }
func (l *maxonLang) startVar()        { l.line("let t = p.curStart()") }
func (l *maxonLang) startOf() string  { return "t" }
func (l *maxonLang) curStart() string { return l.bind("p.curStart()") }

func (l *maxonLang) newNode(n *node, start string) {
	decl := "let"
	if !n.record {
		decl = "var"
	}
	l.linef("%s n = %snew%s(p.tree, start: %s)", decl, astQualifier, n.name, start)
}

func (l *maxonLang) endOfNode(*node)  {}
func (l *maxonLang) ret(value string) { l.line("return " + value) }

func (l *maxonLang) helperVar(name, typ string) {
	l.linef("var %s = %s", name, l.g.m.maxonZero(typ, astQualifier))
}

func (l *maxonLang) firstVar(call string) { l.line("let first = " + call) }

func (l *maxonLang) setVar(name string, s *set) {
	if t := l.setType(s); t != astQualifier+"NodeID" {
		l.linef("var %s as %s", name, t)
		return
	}
	l.linef("var %s = 0 as %sNodeID", name, astQualifier)
}

// maxonQuote writes s as a Maxon string literal: a brace starts an interpolation there, so it is escaped too.
func maxonQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case '"', '\\', '{', '}':
			b.WriteByte('\\')
			b.WriteByte(c)
		case '\n':
			b.WriteString("\\n")
		case '\t':
			b.WriteString("\\t")
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
