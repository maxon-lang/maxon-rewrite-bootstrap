package main

import (
	"slices"
	"strings"
)

const maxonTokensFile = "../../self/syntax/tokens_gen.maxon"

// A table of the Maxon lexer is a string: Maxon has no array constants, and a string literal is in the executable's
// data, so reading one allocates nothing. Each entry is tableDigits characters, the digits of the number in base
// tableBase, each digit the character tableDigitZero plus its value.
const (
	tableBase      = 32
	tableDigits    = 2
	tableDigitZero = '0'
	// tableLimit is the first number an entry cannot hold.
	tableLimit = tableBase * tableBase
)

// tableText is the entries as a table.
func tableText(m *model, what string, entries []int) string {
	var b strings.Builder
	for _, e := range entries {
		if e < 0 || e >= tableLimit {
			m.fail(0, "the lexer's %s holds %d, which a table entry of %d digits in base %d cannot", what, e, tableDigits, tableBase)
		}
		b.WriteByte(byte(tableDigitZero + e/tableBase))
		b.WriteByte(byte(tableDigitZero + e%tableBase))
	}
	return b.String()
}

// emitMaxonTokens generates self/syntax/tokens_gen.maxon from Maxon.g4: the token kinds, the lexer's DFA, and the tables
// of the tokens that the parser describes, joins or has the lexer scan, as internal/syntax/tokens_gen.go has them.
func emitMaxonTokens(m *model) string {
	w := &writer{}
	w.p("// Code generated by internal/grammargen from %s; DO NOT EDIT.\n", grammarFile)
	parsed, skipped := tokenKinds(m)
	all := append(append(append([]string{}, parsed...), skipped...), noTokenConst)
	w.p("export enum TokenKind\n")
	for _, k := range all {
		w.p("\t%s\n", maxonKind(k))
	}
	w.p("end 'TokenKind'\n")

	w.p("\n// tokenKindAt is the token kind of a number, as a table holds it.\n")
	w.p("function tokenKindAt(ordinal Count) returns TokenKind\n\treturn match ordinal 'kind'\n")
	for i, k := range all {
		w.p("\t\t%d gives TokenKind.%s\n", i, maxonKind(k))
	}
	w.p("\t\tdefault panic(\"no token kind has this number\")\n\tend 'kind'\nend 'tokenKindAt'\n")

	w.p("\n// tokenSetMember is the character of a kind a set of token kinds holds: a set has a character per token kind the\n")
	w.p("// parser sees, in the order of their numbers.\nlet tokenSetMember = %d as Byte\n", kindSetMember)
	w.p("\nexport function inTokenSet(set String, kind TokenKind) returns bool\n")
	w.p("\treturn kind.ordinal < set.byteLength() and set.byteAt(kind.ordinal) == tokenSetMember\nend 'inTokenSet'\n")

	w.p("\nlet tableBase = %d as Count\n", tableBase)
	w.p("\nlet tableDigits = %d as Count\n", tableDigits)
	w.p("\nlet tableDigitZero = %d as Count\n", tableDigitZero)
	w.p("\n// tableEntry is the entry at index of a table of the lexer: its high digit, then its low one.\n")
	w.p("function tableEntry(table String, index Count) returns Count\n")
	w.p("\tlet at = try index * tableDigits otherwise panic(\"a DFA table index overflows\")\n")
	w.p("\tlet high = try (table.byteAt(at) as Count) - tableDigitZero otherwise panic(\"a DFA table holds a byte that is no digit\")\n")
	w.p("\tlet low = try (table.byteAt(try at + 1 otherwise panic(\"a DFA table index overflows\")) as Count) - tableDigitZero otherwise panic(\"a DFA table holds a byte that is no digit\")\n")
	w.p("\treturn try high * tableBase + low otherwise panic(\"a DFA table entry overflows\")\nend 'tableEntry'\n")

	a := buildDfa(m)
	w.p("\n// The lexer's DFA, compiled from every token rule and keyword of %s. A state is a row of dfaNextTable, a\n", grammarFile)
	w.p("// column per byte class; state 0 is dead, as no token goes on from it, and dfaStart is the start.\n")
	w.p("\nlet dfaClasses = %d as Count\n", a.numClasses)
	w.p("\nlet dfaStart = 1 as Count\n")
	w.p("\n// dfaClassTable is each byte's class: bytes in one class lead to the same state from every state.\n")
	w.p("let dfaClassTable = \"%s\"\n", tableText(m, "byte classes", a.classes[:]))
	var next []int
	for _, row := range a.next {
		next = append(next, row...)
	}
	w.p("\n// dfaNextTable is the state each state goes to on each byte class, or 0 when no token goes on.\n")
	w.p("let dfaNextTable = \"%s\"\n", tableText(m, "transitions", next))
	accept := make([]int, len(a.accept))
	for d, t := range a.accept {
		accept[d] = len(all) - 1
		if t != noAccept {
			accept[d] = slices.Index(all, a.tokens[t].name)
		}
	}
	w.p("\n// dfaAcceptTable is the number of the token kind each state accepts.\n")
	w.p("let dfaAcceptTable = \"%s\"\n", tableText(m, "accepted tokens", accept))
	w.p("\nexport function dfaClass(b Byte) returns Count\n\treturn tableEntry(dfaClassTable, index: b as Count)\nend 'dfaClass'\n")
	w.p("\nexport function dfaNext(state Count, class Count) returns Count\n")
	w.p("\treturn tableEntry(dfaNextTable, index: try state * dfaClasses + class otherwise panic(\"a DFA state overflows\"))\nend 'dfaNext'\n")
	w.p("\nexport function dfaAccept(state Count) returns TokenKind\n\treturn tokenKindAt(tableEntry(dfaAcceptTable, index: state))\nend 'dfaAccept'\n")
	w.p("\n// dfaIncomplete names the token that input stopping in a state leaves unfinished; empty where the input is an\n")
	w.p("// unexpected character instead.\n")
	w.p("export function dfaIncomplete(state Count) returns String\n\treturn match state 'state'\n")
	for d, msg := range a.incomplete {
		if msg != "" {
			w.p("\t\t%d gives %s\n", d, maxonQuote(msg))
		}
	}
	w.p("\t\tdefault gives \"\"\n\tend 'state'\nend 'dfaIncomplete'\n")

	w.p("\n// tokenDescription is each described token's description, for a syntax error to name a token with no text.\n")
	w.p("export function tokenDescription(kind TokenKind) returns String\n")
	for _, t := range describedTokens(m) {
		k := maxonKind("T" + t.name)
		w.p("\tif kind == TokenKind.%s '%s'\n\t\treturn %s\n\tend '%s'\n", k, k, maxonQuote(t.desc), k)
	}
	w.p("\treturn \"\"\nend 'tokenDescription'\n")

	w.p("\n// tokenNoSpaceBefore and tokenNoSpaceAfter are the sets of the tokens joined to the token before or after them.\n")
	for _, side := range joinTables {
		var joined []string
		for _, t := range m.g.tokens {
			if side.on(t) {
				joined = append(joined, "T"+t.name)
			}
		}
		w.p("export let %s = %q\n\n", side.table, kindSetText(parsed, joined))
	}
	scanned := scannedTokens(m)
	var scannedKinds []string
	for _, t := range scanned {
		scannedKinds = append(scannedKinds, "T"+t.name)
	}
	w.p("// tokenScanned is the set of the tokens the DFA only starts; scanRest reads the rest of each.\n")
	w.p("export let tokenScanned = %q\n", kindSetText(parsed, scannedKinds))
	w.p("\nfunction scanRest(src Source, mutates errs diag.ErrorList, file Count, kind TokenKind, start Count) returns Count throws SyntaxError\n")
	for _, t := range scanned {
		k := maxonKind("T" + t.name)
		w.p("\tif kind == TokenKind.%s '%s'\n\t\treturn try scan%s(src, errs: errs, file: file, start: start)\n\tend '%s'\n", k, k, t.name, k)
	}
	w.p("\tpanic(\"the token is not scanned\")\nend 'scanRest'\n")
	return w.b.String()
}
