// Command irgen generates, from the table of IR operations in table.go, the IR's records, constructors, printer and
// visitor of self/ir. `go generate ./internal/irgen` runs it.
//
// A visitor has a method for every operation, so a row added to the table fails the build in every package that
// visits the IR and has not handled it yet.
package main

//go:generate go run .

import (
	"fmt"
	"os"
	"slices"
	"strings"
)

const (
	maxonFile = "../../self/ir/ir_gen.maxon"

	header = "// Code generated by irgen from internal/irgen/table.go; DO NOT EDIT.\n\n"
)

type output struct {
	path string
	code []byte
}

func main() {
	outs, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "irgen:", err)
		os.Exit(1)
	}
	for _, o := range outs {
		if err := os.WriteFile(o.path, o.code, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "irgen:", err)
			os.Exit(1)
		}
	}
}

// tableError is a row of the table that the generator cannot make code of.
type tableError struct{ msg string }

func (e *tableError) Error() string { return e.msg }

func fail(format string, args ...any) {
	panic(&tableError{fmt.Sprintf(format, args...)})
}

func generate() (outs []output, err error) {
	defer func() {
		if r := recover(); r != nil {
			te, ok := r.(*tableError)
			if !ok {
				panic(r)
			}
			err = te
		}
	}()
	check()
	return []output{{maxonFile, []byte(emitMaxon())}}, nil
}

// instrFields and termFields are the fields of the two records, in the order the codec writes them.
var (
	instrFields = []field{fDst, fA, fB, fC, fImm, fSub, fFlags}
	termFields  = []field{fValue, fThen, fElse, fFirst, fCount}
)

// kindFields are the fields an operand of each kind may be held in.
var kindFields = map[kind][]field{
	kReg:       {fA, fB, fValue},
	kRegs:      {fA},
	kMoreRegs:  {fC},
	kSlot:      {fImm},
	kInt:       {fImm},
	kWord:      {fImm},
	kSymbol:    {fImm},
	kEnum:      {fSub},
	kFlag:      {fFlags},
	kBlock:     {fThen, fElse},
	kFail:      {fC},
	kText:      {fC},
	kType:      {fC},
	kCallee:    {fC},
	kRoutine:   {fC},
	kErrorReg:  {fImm},
	kBehaviour: {fImm},
	kCases:     {fFirst},
}

// check refuses a table that the generator cannot make consistent code of.
func check() {
	names := map[string]bool{}
	for _, o := range ops {
		if names[o.Name] {
			fail("%s is in the table twice", o.Name)
		}
		names[o.Name] = true
		if o.Term && o.Result != noResult {
			fail("terminator %s gives a value; a terminator ends its block", o.Name)
		}
		recordFields := instrFields
		if o.Term {
			recordFields = termFields
		}
		used := map[field]string{}
		operands := map[string]bool{}
		for i, x := range o.Operands {
			if operands[x.Name] {
				fail("%s has two operands named %s", o.Name, x.Name)
			}
			operands[x.Name] = true
			if !slices.Contains(kindFields[x.Kind], x.Field) || !slices.Contains(recordFields, x.Field) {
				fail("%s.%s cannot be held in the field %s", o.Name, x.Name, x.Field)
			}
			if prev, ok := used[x.Field]; ok && x.Kind != kFlag {
				fail("%s.%s and %s.%s are both in the field %s", o.Name, x.Name, o.Name, prev, x.Field)
			}
			used[x.Field] = x.Name
			if x.Count != "" {
				if x.Kind != kRegs && x.Kind != kCases {
					fail("%s.%s has a count but is no list", o.Name, x.Name)
				}
				used[x.Count] = x.Name
			}
			if x.Kind == kMoreRegs && (i == 0 || o.Operands[i-1].Kind != kRegs) {
				fail("%s.%s follows no list of registers", o.Name, x.Name)
			}
			if x.Kind == kEnum && enumOf(x.Enum) == nil {
				fail("%s.%s is of the enum %s, which the table does not have", o.Name, x.Name, x.Enum)
			}
			needsFlag := x.Kind == kFlag || x.Kind == kErrorReg
			if (needsFlag && x.Flag == "") || (x.Flag != "" && flagOf(x.Flag) < 0) || (x.Flag != "" && !needsFlag && x.Kind != kFail) {
				fail("%s.%s names the flag %q, which it cannot have", o.Name, x.Name, x.Flag)
			}
			if (optional(x) || x.Kind == kFlag) != (x.Text != "") {
				fail("%s.%s: an optional operand or a flag, and only one, has the text the printer writes when it is there", o.Name, x.Name)
			}
			if !strings.Contains(o.Text, "{"+x.Name+"}") {
				fail("%s does not print its operand %s", o.Name, x.Name)
			}
		}
		for _, part := range templateParts(o.Text) {
			if part.operand != "" && !operands[part.operand] {
				fail("%s prints {%s}, which is none of its operands", o.Name, part.operand)
			}
		}
		for _, e := range o.Effects {
			if !slices.Contains(effects, e) {
				fail("%s has the effect %s, which the table does not have", o.Name, e)
			}
			if e == effExits && !o.Term {
				fail("%s leaves the function but is no terminator", o.Name)
			}
		}
	}
}

// optional is whether an operand may be absent from an instruction.
func optional(x operand) bool {
	return x.Kind == kRoutine || x.Kind == kErrorReg || (x.Kind == kFail && x.Flag != "")
}

// usesPool is whether an operand indexes a pool of the function, which only the builder appends to.
func usesPool(x operand) bool {
	switch x.Kind {
	case kRegs, kMoreRegs, kText, kType, kCallee, kRoutine, kBehaviour, kCases:
		return true
	}
	return false
}

func enumOf(name string) *enum {
	for i := range enums {
		if enums[i].Name == name {
			return &enums[i]
		}
	}
	return nil
}

func flagOf(name string) int {
	for i, f := range flags {
		if f.Name == name {
			return i
		}
	}
	return -1
}

// opEffects are the effects of an operation, with effFails for one that can fail.
func opEffects(o op) []effect {
	out := slices.Clone(o.Effects)
	if slices.ContainsFunc(o.Operands, func(x operand) bool { return x.Kind == kFail }) {
		out = append(out, effFails)
	}
	return out
}

// effectBit is the bit of an effect in Effects.
func effectBit(e effect) int {
	if e == effFails {
		return len(effects)
	}
	return slices.Index(effects, e)
}

// fieldsOf are the fields of the record an operation uses, in codec order.
func fieldsOf(o op) []field {
	used := map[field]bool{}
	if o.Result != noResult {
		used[fDst] = true
	}
	for _, x := range o.Operands {
		used[x.Field] = true
		if x.Count != "" {
			used[x.Count] = true
		}
		if x.Flag != "" {
			used[fFlags] = true
		}
	}
	order := instrFields
	if o.Term {
		order = termFields
	}
	var out []field
	for _, f := range order {
		if used[f] {
			out = append(out, f)
		}
	}
	return out
}

// part is a piece of a printer template: literal text, or an operand.
type part struct {
	text, operand string
}

func templateParts(t string) []part {
	var out []part
	for t != "" {
		open := strings.IndexByte(t, '{')
		if open < 0 {
			out = append(out, part{text: t})
			break
		}
		if open > 0 {
			out = append(out, part{text: t[:open]})
		}
		end := strings.IndexByte(t[open:], '}')
		if end < 0 {
			fail("template %q has an unclosed {", t)
		}
		out = append(out, part{operand: t[open+1 : open+end]})
		t = t[open+end+1:]
	}
	return out
}

func operandOf(o op, name string) operand {
	for _, x := range o.Operands {
		if x.Name == name {
			return x
		}
	}
	fail("%s has no operand %s", o.Name, name)
	return operand{}
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

func instrOps() []op {
	var out []op
	for _, o := range ops {
		if !o.Term {
			out = append(out, o)
		}
	}
	return out
}

func termOps() []op {
	var out []op
	for _, o := range ops {
		if o.Term {
			out = append(out, o)
		}
	}
	return out
}
