// Command targetgen writes, for each target of package target, the Maxon declarations of its register file and calling
// conventions that the backend reads: self/backend/regs_<target>_gen.maxon. `go generate ./internal/targetgen` runs it.
package main

//go:generate go run .

import (
	"fmt"
	"os"
	"strings"

	"minimaxon/internal/targetgen/target"
)

const header = "// Code generated by internal/targetgen from internal/targetgen/target/target.go; DO NOT EDIT.\n"

// outputPath is where a target's declarations are written.
func outputPath(t target.Target) string {
	return "../../self/backend/regs_" + t.Name + "_gen.maxon"
}

func main() {
	for _, t := range target.Targets {
		code, err := generate(t)
		if err == nil {
			err = os.WriteFile(outputPath(t), []byte(code), 0o644)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, "targetgen:", err)
			os.Exit(1)
		}
	}
}

// generate is the Maxon file of a target's declarations.
func generate(t target.Target) (string, error) {
	if err := t.Check(); err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n")
	if err := emitMask(&b, t, t.Name+"Reserved", "the registers that hold the stack and the frame, which no value is given", t.Reserved); err != nil {
		return "", err
	}
	fmt.Fprintf(&b, "// %sStackAlignment is the alignment of the stack pointer at a call of a host convention.\nexport let %sStackAlignment = %d\n\n", t.Name, t.Name, t.StackAlignment)
	for _, c := range t.Conventions() {
		if err := emitConvention(&b, t, c); err != nil {
			return "", err
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

func emitMask(b *strings.Builder, t target.Target, name, doc string, names []string) error {
	m, err := t.Mask(names)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "// %s are %s:\n// %s.\n", name, doc, strings.Join(names, " "))
	fmt.Fprintf(b, "export function %s() returns RegMask\n\treturn 0x%X\nend '%s'\n\n", name, m, name)
	return nil
}

// generalRegister is the name of a general register in the backend's register enum, which a convention passes a value in.
func generalRegister(t target.Target, name string) (string, error) {
	for _, r := range t.Registers {
		if r.Name == name {
			if r.Class != target.General {
				return "", fmt.Errorf("%s: %s passes a word but is no general register", t.Name, name)
			}
			return strings.ToUpper(t.Name[:1]) + t.Name[1:] + "Register." + name, nil
		}
	}
	return "", fmt.Errorf("%s: %s is no register", t.Name, name)
}

// emitFloats writes where a convention passes floats, as numbers in the register file, since the backend's register enum
// names only the general registers.
func emitFloats(b *strings.Builder, t target.Target, named target.NamedConvention) error {
	p, c := named.Prefix, named.Convention
	fmt.Fprintf(b, "// %sFloatArgCount is how many float arguments a call passes in registers, counted apart from the integer ones; the\n// rest go on the stack.\nexport let %sFloatArgCount = %d\n\n", p, p, len(c.FloatArgs))
	fmt.Fprintf(b, "// %sFloatArg is the number in the register file of the register of a float argument, of the first\n// %sFloatArgCount.\n", p, p)
	fmt.Fprintf(b, "export function %sFloatArg(index Count) returns RegNum\n\treturn match index 'index'\n", p)
	for i, a := range c.FloatArgs {
		n, err := t.Number(a)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "\t\t%d gives %d as RegNum\n", i, n)
	}
	fmt.Fprintf(b, "\t\tdefault panic(\"backend: a float argument past the registers of the %s convention\")\n\tend 'index'\nend '%sFloatArg'\n\n", named.Title, p)
	n, err := t.Number(c.FloatResult)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "// %sFloatResult is the number in the register file of the register of a call's float result.\nexport let %sFloatResult = %d as RegNum\n\n", p, p, n)
	return nil
}

func emitConvention(b *strings.Builder, t target.Target, named target.NamedConvention) error {
	p, c := named.Prefix, named.Convention
	fmt.Fprintf(b, "// The %s convention: %s.\n\n", named.Title, c.Doc)
	fmt.Fprintf(b, "// %sArgCount is how many integer arguments a call passes in registers; the rest go on the stack.\nexport let %sArgCount = %d\n\n", p, p, len(c.Args))
	fmt.Fprintf(b, "// %sArg is the register of an argument, of the first %sArgCount.\n", p, p)
	fmt.Fprintf(b, "export function %sArg(index Count) returns %sRegister\n\treturn match index 'index'\n", p, strings.ToUpper(t.Name[:1])+t.Name[1:])
	for i, a := range c.Args {
		r, err := generalRegister(t, a)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "\t\t%d gives %s\n", i, r)
	}
	fmt.Fprintf(b, "\t\tdefault panic(\"backend: an argument past the registers of the %s convention\")\n\tend 'index'\nend '%sArg'\n\n", named.Title, p)
	r, err := generalRegister(t, c.Result)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "// %sResult is the register of a call's result.\nexport let %sResult = %s\n\n", p, p, r)
	if c.Number != "" {
		n, err := generalRegister(t, c.Number)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "// %sNumber is the register of a system call's number.\nexport let %sNumber = %s\n\n", p, p, n)
	}
	if len(c.FloatArgs) > 0 {
		if err := emitFloats(b, t, named); err != nil {
			return err
		}
	}
	if c.Error != "" {
		e, err := generalRegister(t, c.Error)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "// %sError is the register of the error flag of a function that throws: 0 when it returned, and the\n// error's case plus 1 when it failed.\nexport let %sError = %s\n\n", p, p, e)
	}
	fmt.Fprintf(b, "// %sShadowBytes is the stack a caller keeps below the stack arguments for the callee to write.\nexport let %sShadowBytes = %d\n\n", p, p, c.ShadowBytes)
	if err := emitMask(b, t, p+"CalleeSaved", "the registers a call keeps", c.CalleeSaved); err != nil {
		return err
	}
	return emitMask(b, t, p+"CallerSaved", "the registers a call may leave holding anything", c.CallerSaved)
}
