// Command targetgen writes, from package target, the target model the compiler reads: the architectures, the systems and
// what each system is asked (self/ast/targets_gen.maxon); for each target the Maxon declarations of its register file
// and calling conventions that the backend reads (self/backend/regs_<target>_gen.maxon); and, with the instruction sets
// of internal/machines, what the target-neutral machine IR asks of every target (self/backend/machine_gen.maxon).
// `go generate ./internal/targetgen` runs it.
package main

//go:generate go run .

import (
	"fmt"
	"os"
	"slices"
	"strings"

	"minimaxon/internal/machines"
	"minimaxon/internal/targetgen/target"
)

const header = "// Code generated by internal/targetgen from internal/targetgen/target/target.go; DO NOT EDIT.\n"

// modelPath is where the target model is written.
const modelPath = "../../self/ast/targets_gen.maxon"

// outputPath is where a target's declarations are written.
func outputPath(t target.Target) string {
	return "../../self/backend/regs_" + t.Name + "_gen.maxon"
}

type output struct {
	path string
	code string
}

func main() {
	outs, err := generateAll()
	if err != nil {
		fmt.Fprintln(os.Stderr, "targetgen:", err)
		os.Exit(1)
	}
	for _, o := range outs {
		if err := os.WriteFile(o.path, []byte(o.code), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "targetgen:", err)
			os.Exit(1)
		}
	}
}

// generateAll is every file the generator writes.
func generateAll() ([]output, error) {
	model, err := generateModel(target.Targets)
	if err != nil {
		return nil, err
	}
	machine, err := generateMachine(target.Targets, machines.All)
	if err != nil {
		return nil, err
	}
	outs := []output{{modelPath, model}, {machinePath, machine}}
	for _, t := range append(slices.Clone(target.Targets), target.Pending...) {
		code, err := generate(t)
		if err != nil {
			return nil, err
		}
		outs = append(outs, output{outputPath(t), code})
	}
	return outs, nil
}

// generateModel is the Maxon file of the target model: the enums of the architectures and the systems, what each system
// is asked, and the targets, each architecture on each system it runs, in the order of the table.
func generateModel(targets []target.Target) (string, error) {
	for _, t := range targets {
		if err := t.Check(); err != nil {
			return "", err
		}
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n// TargetArch is the processor of a target, which picks the backend's instruction set and register file.\n")
	b.WriteString("export enum TargetArch\n")
	for _, t := range targets {
		fmt.Fprintf(&b, "\t%s\n", t.Name)
	}
	b.WriteString("end 'TargetArch'\n\n")
	b.WriteString("// TargetSystem is the operating system of a target, by which the backend picks the entry stub, the format of the\n")
	b.WriteString("// executable, the read of a thread's context and the way the runtime reaches the system. A system that no target runs\n")
	b.WriteString("// yet has its case, so that every match on one already says what it does for it.\n")
	b.WriteString("export enum TargetSystem\n")
	for _, o := range target.OSes {
		fmt.Fprintf(&b, "\t%s\n", o.Name)
	}
	b.WriteString("end 'TargetSystem'\n\n")
	b.WriteString("// ImageFormat is the format of a system's executables.\nexport enum ImageFormat\n")
	for _, f := range []target.ImageFormat{target.PE, target.ELF, target.MachO} {
		fmt.Fprintf(&b, "\t%s\n", f)
	}
	b.WriteString("end 'ImageFormat'\n\n")
	b.WriteString("// SystemReach is how a system's programs reach it: through the functions of its libraries, which the executable\n")
	b.WriteString("// imports, or through system calls they make themselves.\nexport enum SystemReach\n")
	for _, r := range []target.Reach{target.Imports, target.Syscalls} {
		fmt.Fprintf(&b, "\t%s\n", r)
	}
	b.WriteString("end 'SystemReach'\n\n")
	b.WriteString("// archName is an architecture's name as a target's name and `#if arch(...)` spell it.\n")
	b.WriteString("export function archName(arch TargetArch) returns String\n\treturn match arch 'arch'\n")
	for _, t := range targets {
		fmt.Fprintf(&b, "\t\t%s gives %q\n", t.Name, t.Name)
	}
	b.WriteString("\tend 'arch'\nend 'archName'\n\n")
	systemFunction(&b, "systemName", "a system's name as a target's name and `#if os(...)` spell it", "String", func(o target.OS) string { return fmt.Sprintf("%q", o.Display) })
	systemFunction(&b, "imageFormatOf", "the format of a system's executables", "ImageFormat", func(o target.OS) string { return "ImageFormat." + string(o.Image) })
	systemFunction(&b, "systemReach", "how a system's programs reach it", "SystemReach", func(o target.OS) string { return "SystemReach." + string(o.Reach) })
	systemFunction(&b, "executableSuffix", "what the name of an executable for a system ends with, as maxon names them", "String", func(o target.OS) string { return fmt.Sprintf("%q", o.ExecutableSuffix) })
	b.WriteString("// knownTargets are the targets this compiler compiles for, each architecture on each system it runs, in the order a\n// usage message lists them.\n")
	b.WriteString("export function knownTargets() returns TargetList\n\tvar targets = TargetList.create(0)\n")
	for _, t := range targets {
		for _, s := range t.Systems {
			fmt.Fprintf(&b, "\ttargets.push(Target.make(TargetArch.%s, system: TargetSystem.%s))\n", t.Name, s.OS.Name)
		}
	}
	b.WriteString("\treturn targets\nend 'knownTargets'\n")
	return b.String(), nil
}

// systemFunction writes a function of every system that gives what of says of it.
func systemFunction(b *strings.Builder, name, doc, ty string, of func(target.OS) string) {
	fmt.Fprintf(b, "// %s is %s.\n", name, doc)
	fmt.Fprintf(b, "export function %s(system TargetSystem) returns %s\n\treturn match system 'system'\n", name, ty)
	for _, o := range target.OSes {
		fmt.Fprintf(b, "\t\t%s gives %s\n", o.Name, of(o))
	}
	fmt.Fprintf(b, "\tend 'system'\nend '%s'\n\n", name)
}

// generate is the Maxon file of a target's declarations.
func generate(t target.Target) (string, error) {
	if err := t.Check(); err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n")
	if err := emitMask(&b, t, t.Name+"Reserved", "the registers no value is given: the stack's, the frame's, and those the code or the system keeps", t.Reserved); err != nil {
		return "", err
	}
	fmt.Fprintf(&b, "// %sFirstVector is the number of the first vector register in the register file, after the general registers.\nexport let %sFirstVector = %d\n\n", t.Name, t.Name, len(t.Names(target.General)))
	fmt.Fprintf(&b, "// %sRegisterFileSize is how many registers the register file has.\nexport let %sRegisterFileSize = %d\n\n", t.Name, t.Name, len(t.Registers))
	fmt.Fprintf(&b, "// %sStackAlignment is the alignment of the stack pointer at a call of a host convention.\nexport let %sStackAlignment = %d\n\n", t.Name, t.Name, t.StackAlignment)
	for _, c := range t.Conventions() {
		if err := emitConvention(&b, t, c); err != nil {
			return "", err
		}
	}
	if err := emitBySystem(&b, t); err != nil {
		return "", err
	}
	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

func emitMask(b *strings.Builder, t target.Target, name, doc string, names []string) error {
	m, err := t.Mask(names)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "// %s are %s:\n// %s.\n", name, doc, strings.Join(names, " "))
	fmt.Fprintf(b, "export function %s() returns RegMask\n\treturn 0x%X\nend '%s'\n\n", name, m, name)
	return nil
}

// registerType is the backend's enum of a target's general registers.
func registerType(t target.Target) string {
	return strings.ToUpper(t.Name[:1]) + t.Name[1:] + "Register"
}

// generalRegister is the name of a general register in the backend's register enum, which a convention passes a value in.
func generalRegister(t target.Target, name string) (string, error) {
	for _, r := range t.Registers {
		if r.Name == name {
			if r.Class != target.General {
				return "", fmt.Errorf("%s: %s passes a word but is no general register", t.Name, name)
			}
			return registerType(t) + "." + name, nil
		}
	}
	return "", fmt.Errorf("%s: %s is no register", t.Name, name)
}

// emitFloats writes where a convention passes floats, as numbers in the register file, since the backend's register enum
// names only the general registers.
func emitFloats(b *strings.Builder, t target.Target, named target.NamedConvention) error {
	p, c := named.Prefix, named.Convention
	fmt.Fprintf(b, "// %sFloatArgCount is how many float arguments a call passes in registers, counted apart from the integer ones; the\n// rest go on the stack.\nexport let %sFloatArgCount = %d\n\n", p, p, len(c.FloatArgs))
	fmt.Fprintf(b, "// %sFloatArg is the number in the register file of the register of a float argument, of the first\n// %sFloatArgCount.\n", p, p)
	fmt.Fprintf(b, "export function %sFloatArg(index Count) returns RegNum\n\treturn match index 'index'\n", p)
	for i, a := range c.FloatArgs {
		n, err := t.Number(a)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "\t\t%d gives %d as RegNum\n", i, n)
	}
	fmt.Fprintf(b, "\t\tdefault panic(\"backend: a float argument past the registers of the %s convention\")\n\tend 'index'\nend '%sFloatArg'\n\n", named.Title, p)
	n, err := t.Number(c.FloatResult)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "// %sFloatResult is the number in the register file of the register of a call's float result.\nexport let %sFloatResult = %d as RegNum\n\n", p, p, n)
	return nil
}

func emitConvention(b *strings.Builder, t target.Target, named target.NamedConvention) error {
	p, c := named.Prefix, named.Convention
	fmt.Fprintf(b, "// The %s convention: %s.\n\n", named.Title, c.Doc)
	fmt.Fprintf(b, "// %sArgCount is how many integer arguments a call passes in registers; the rest go on the stack.\nexport let %sArgCount = %d\n\n", p, p, len(c.Args))
	fmt.Fprintf(b, "// %sArg is the register of an argument, of the first %sArgCount.\n", p, p)
	fmt.Fprintf(b, "export function %sArg(index Count) returns %s\n\treturn match index 'index'\n", p, registerType(t))
	for i, a := range c.Args {
		r, err := generalRegister(t, a)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "\t\t%d gives %s\n", i, r)
	}
	fmt.Fprintf(b, "\t\tdefault panic(\"backend: an argument past the registers of the %s convention\")\n\tend 'index'\nend '%sArg'\n\n", named.Title, p)
	r, err := generalRegister(t, c.Result)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "// %sResult is the register of a call's result.\nexport let %sResult = %s\n\n", p, p, r)
	if c.Number != "" {
		n, err := generalRegister(t, c.Number)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "// %sNumber is the register of a system call's number.\nexport let %sNumber = %s\n\n", p, p, n)
	}
	if len(c.FloatArgs) > 0 {
		if err := emitFloats(b, t, named); err != nil {
			return err
		}
	}
	if c.Error != "" {
		e, err := generalRegister(t, c.Error)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "// %sError is the register of the error flag of a function that throws: 0 when it returned, and the\n// error's case plus 1 when it failed.\nexport let %sError = %s\n\n", p, p, e)
	}
	fmt.Fprintf(b, "// %sShadowBytes is the stack a caller keeps below the stack arguments for the callee to write.\nexport let %sShadowBytes = %d\n\n", p, p, c.ShadowBytes)
	fmt.Fprintf(b, "// %sVariadicOnStack is whether a variadic function takes every variadic argument on the stack, whatever\n// registers are free.\nexport let %sVariadicOnStack = %t\n\n", p, p, c.VariadicOnStack)
	if err := emitMask(b, t, p+"CalleeSaved", "the registers a call keeps", c.CalleeSaved); err != nil {
		return err
	}
	return emitMask(b, t, p+"CallerSaved", "the registers a call may leave holding anything", c.CallerSaved)
}

// systemOf is the target's row of a system, if the target runs it.
func systemOf(t target.Target, o target.OS) (target.System, bool) {
	for _, s := range t.Systems {
		if s.OS.Name == o.Name {
			return s, true
		}
	}
	return target.System{}, false
}

// roleQuantity is one declaration of a convention that the backend asks of the convention of a role on the system it
// compiles for: its name after the prefix, its type, whether it takes the index of an argument, and whether the
// declaration is a function.
type roleQuantity struct {
	name, ty      string
	indexed, call bool
}

// emitBySystem writes what the backend asks of a target by the system it compiles for: the declarations of the host
// convention and of the system call convention of that system, and how a thread reads its context there. A system the
// target does not run, or one with no system calls for the system call convention, is a panic: the backend never
// compiles for the one, and refuses a system call on the other.
func emitBySystem(b *strings.Builder, t target.Target) error {
	reg := registerType(t)
	roles := []struct {
		prefix, title string
		of            func(target.System) *target.Convention
		quantities    []roleQuantity
	}{
		{"Host", "the host convention, the one of the system's libraries", func(s target.System) *target.Convention { return &s.Host },
			[]roleQuantity{{"ArgCount", "Count", false, false}, {"Arg", reg, true, true}, {"Result", reg, false, false}, {"ShadowBytes", "Count", false, false}, {"CalleeSaved", "RegMask", false, true}}},
		{"Syscall", "the convention of a system call", func(s target.System) *target.Convention { return s.Syscall },
			[]roleQuantity{{"ArgCount", "Count", false, false}, {"Arg", reg, true, true}, {"Result", reg, false, false}, {"Number", reg, false, false}, {"CalleeSaved", "RegMask", false, true}}},
	}
	for _, role := range roles {
		for _, q := range role.quantities {
			name := t.Name + role.prefix + q.name
			params := "system ast.TargetSystem"
			args := ""
			if q.indexed {
				params += ", index Count"
				args = "(index)"
			} else if q.call {
				args = "()"
			}
			fmt.Fprintf(b, "// %s is the %s of %s on a system.\n", name, q.name, role.title)
			fmt.Fprintf(b, "export function %s(%s) returns %s\n\treturn match system 'system'\n", name, params, q.ty)
			for _, o := range target.OSes {
				s, runs := systemOf(t, o)
				switch {
				case !runs:
					fmt.Fprintf(b, "\t\t%s gives panic(\"backend: %s runs no %s\")\n", o.Name, t.Name, o.Display)
				case role.of(s) == nil:
					fmt.Fprintf(b, "\t\t%s gives panic(\"backend: %s programs make no system call\")\n", o.Name, o.Display)
				default:
					fmt.Fprintf(b, "\t\t%s gives %s%s%s%s\n", o.Name, t.Name, s.Name(), role.prefix, q.name+args)
				}
			}
			fmt.Fprintf(b, "\tend 'system'\nend '%s'\n\n", name)
		}
	}
	contexts := []string{}
	for _, s := range t.Systems {
		if s.ThreadContext == "" {
			return fmt.Errorf("%s on %s: no ThreadContext", t.Name, s.Name())
		}
		if !slices.Contains(contexts, s.ThreadContext) {
			contexts = append(contexts, s.ThreadContext)
		}
	}
	enum := strings.ToUpper(t.Name[:1]) + t.Name[1:] + "ThreadContext"
	fmt.Fprintf(b, "// %s is how a thread reads the word of its context on a system.\nexport enum %s\n", enum, enum)
	for _, c := range contexts {
		fmt.Fprintf(b, "\t%s\n", c)
	}
	fmt.Fprintf(b, "end '%s'\n\n", enum)
	name := t.Name + "ThreadContext"
	fmt.Fprintf(b, "// %s is how a thread reads its context on a system.\nexport function %s(system ast.TargetSystem) returns %s\n\treturn match system 'system'\n", name, name, enum)
	for _, o := range target.OSes {
		if s, runs := systemOf(t, o); runs {
			fmt.Fprintf(b, "\t\t%s gives %s.%s\n", o.Name, enum, s.ThreadContext)
		} else {
			fmt.Fprintf(b, "\t\t%s gives panic(\"backend: %s runs no %s\")\n", o.Name, t.Name, o.Display)
		}
	}
	fmt.Fprintf(b, "\tend 'system'\nend '%s'\n", name)
	return nil
}
