// machinePath is where the tables of the target-neutral machine IR are written.
const machinePath = "../../self/backend/machine_gen.maxon"

const machineHeader = "// Code generated by internal/targetgen from internal/targetgen/target/target.go and the instruction sets of\n// internal/machines; DO NOT EDIT.\n"

// formColumn is a yes or no, or a digit, that the machine IR asks of every form.
type formColumn struct {
	name, ty, doc string
	of            func(isa.Form, isa.Named) int
}

func flag(b bool) int {
	if b {
		return 1
	}
	return 0
}

