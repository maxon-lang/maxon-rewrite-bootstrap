// Package x64table is the x64 instruction table (table.go) and the generator of self/backend's encoder from it: the
// register and condition code enums, one encoder function per form that appends the bytes of the instruction to a code
// buffer, the choices and sequences of forms the backend asks for, the effects of each form, and the helpers that patch
// the 32-bit fields of labels and calls. internal/x64gen writes what Generate gives, and internal/rulegen checks the
// x64 rules against the forms (Params).
//
// The test of this package proves the table against the bytes the Go compiler's assembler wrote, kept in testdata.
package x64table

import (
	"fmt"
	"slices"
	"strings"

	"minimaxon/internal/isa"
)

const header = "// Code generated by internal/x64gen from internal/x64gen/x64table/table.go; DO NOT EDIT.\n\n"

// tableError is a row of the table that the generator cannot make code of.
type tableError struct{ msg string }

func (e *tableError) Error() string { return e.msg }

func fail(format string, args ...any) {
	panic(&tableError{fmt.Sprintf(format, args...)})
}

// Generate is the Maxon of the encoder, or the error of a row it cannot make code of.
func Generate() (code string, err error) {
	defer func() {
		if r := recover(); r != nil {
			te, ok := r.(*tableError)
			if !ok {
				panic(r)
			}
			err = te
		}
	}()
	check()
	return emitMaxon(), nil
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

func capitalize(s string) string { return strings.ToUpper(s[:1]) + s[1:] }

// param is a parameter of an encoder: its name and its Maxon type.
type param struct{ name, ty string }

const (
	typeRegister  = "X64Register"
	typeCondition = "MCond"
	typeDisp      = "Imm32"
	typeImm64     = "FullRangeInt"
)

// immediate is what an immediate or displacement kind is in Maxon: its type and the constants that bound it.
type immediate struct {
	ty     string
	lo, hi string
	// writer is the helper that appends the field.
	writer string
}

func immediateOf(k kind) immediate {
	switch k {
	case kindImm8:
		return immediate{"Imm8", "imm8Min", "imm8Max", "writeImm8"}
	case kindImm32, kindRel32:
		return immediate{"Imm32", "imm32Min", "imm32Max", "writeImm32"}
	case kindImm32U:
		return immediate{"Imm32U", "0", "imm32UMax", "writeImm32U"}
	case kindImm64:
		return immediate{typeImm64, "", "", "writeImm64"}
	default:
		panic(fmt.Sprintf("kind %d has no immediate", k))
	}
}

// scaleBitsOf is the SIB byte's scale field for a scale: its power of two.
func scaleBitsOf(scale int) int {
	switch scale {
	case 1:
		return 0
	case 2:
		return 1
	case 4:
		return 2
	case 8:
		return 3
	}
	fail("%d is no scale of an index", scale)
	return 0
}

func isImmediate(k kind) bool {
	return k == kindImm8 || k == kindImm32 || k == kindImm32U || k == kindImm64
}

// params are the parameters of an operand.
func (o operand) params() []param {
	switch o.kind {
	case kindReg:
		return []param{{o.name, typeRegister}}
	case kindMem:
		return []param{{"base", typeRegister}, {"disp", typeDisp}}
	case kindMemIndex:
		return []param{{"base", typeRegister}, {"index", typeRegister}, {"disp", typeDisp}}
	case kindRip:
		return []param{{"disp", typeDisp}}
	case kindCond:
		return []param{{"cond", typeCondition}}
	case kindImm8, kindImm32, kindImm32U, kindImm64, kindRel32:
		return []param{{o.name, immediateOf(o.kind).ty}}
	default:
		panic(fmt.Sprintf("operand kind %d has no parameters", o.kind))
	}
}

func paramsOf(ops []operand) []param {
	var ps []param
	for _, o := range ops {
		ps = append(ps, o.params()...)
	}
	return ps
}

func (f form) params() []param { return paramsOf(f.operands) }

// in is the operand of a form in a field, which check has made sure there is at most one of.
func (f form) in(fl field) (operand, bool) {
	for _, o := range f.operands {
		if o.field == fl {
			return o, true
		}
	}
	return operand{}, false
}

// withKind is the operand of a form of a kind, of which check has made sure there is at most one for the kinds it asks.
func (f form) withKind(k kind) (operand, bool) {
	for _, o := range f.operands {
		if o.kind == k {
			return o, true
		}
	}
	return operand{}, false
}

func formByName(name string) form {
	for _, f := range forms {
		if f.name == name {
			return f
		}
	}
	fail("there is no form %s", name)
	return form{}
}

func registerIndex(name string) int { return slices.Index(registers, name) }

// choiceParams are the parameters of a choice: those of its first alternative, with the immediate as wide as the widest
// alternative's, which is also what the last alternative holds.
func (c choice) params() []param {
	ps := formByName(c.alternatives[0]).params()
	for i, p := range ps {
		if p.name == "imm" {
			ps[i].ty = immediateOf(c.immediateKind()).ty
		}
	}
	return ps
}

// immediateKind is the kind of the widest immediate of the alternatives. An unsigned doubleword is not held by a signed
// one, so it makes the choice take a quadword.
func (c choice) immediateKind() kind {
	widest := kindImm8
	for _, name := range c.alternatives {
		switch immediateKindOf(formByName(name)) {
		case kindImm8:
		case kindImm32:
			if widest == kindImm8 {
				widest = kindImm32
			}
		case kindImm32U, kindImm64:
			widest = kindImm64
		default:
			fail("choice %s: %s has no integer immediate", c.name, name)
		}
	}
	return widest
}

// immediateKindOf is the kind of the one immediate of a form.
func immediateKindOf(f form) kind {
	for _, o := range f.operands {
		if isImmediate(o.kind) {
			return o.kind
		}
	}
	fail("form %s has no immediate", f.name)
	return 0
}

// check refuses a table that has no encoding.
func check() {
	seen := map[string]bool{}
	claim := func(name string) {
		if seen[name] {
			fail("%s is declared twice", name)
		}
		seen[name] = true
	}
	for _, f := range forms {
		claim(f.name)
		checkForm(f)
		checkAlloc(f)
	}
	for _, c := range choices {
		claim(c.name)
		checkChoice(c)
	}
	for _, s := range sequences {
		claim(s.name)
		checkSequence(s)
	}
	checkEffects()
	checkConditions()
}

// checkConditions refuses a table whose condition codes are not the machine IR's conditions in order, which the
// encoders take as MCond and add to an opcode as its rawValue.
func checkConditions() {
	if len(conditions) != len(isa.Conditions) {
		fail("the table has %d condition codes and the machine IR %d conditions", len(conditions), len(isa.Conditions))
	}
	for i, c := range conditions {
		if c.name != isa.Conditions[i] || c.code != i {
			fail("condition code %s is 0x%X, and MCond's case %d is %s", c.name, c.code, i, isa.Conditions[i])
		}
	}
}

func checkForm(f form) {
	if len(f.opcode) == 0 {
		fail("%s has no opcode", f.name)
	}
	var inReg, inRM, inOpcode, conds, immediates, rips int
	for _, o := range f.operands {
		switch o.field {
		case fieldReg:
			inReg++
		case fieldRM:
			inRM++
		case fieldOpcode:
			inOpcode++
		case fieldNone:
		default:
			fail("%s: operand %s is in no known field", f.name, o.name)
		}
		switch {
		case o.kind == kindCond:
			conds++
		case isImmediate(o.kind) || o.kind == kindRel32:
			immediates++
		case o.kind == kindRip:
			rips++
		}
		if o.kind == kindReg && o.field == fieldNone {
			fail("%s: register %s is in no field", f.name, o.name)
		}
		if o.kind != kindReg && o.field != fieldNone && o.kind != kindMem && o.kind != kindMemIndex && o.kind != kindRip {
			fail("%s: operand %s is not a register and is in a field", f.name, o.name)
		}
		if o.kind == kindMemIndex {
			scaleBitsOf(o.scale)
		} else if o.scale != 0 {
			fail("%s: operand %s has a scale and no index", f.name, o.name)
		}
		if o.byteReg && o.kind != kindReg {
			fail("%s: only a register is a byte register", f.name)
		}
		if o.vector && (o.kind != kindReg || o.byteReg || o.field == fieldOpcode) {
			fail("%s: an xmm register is a register in the reg or r/m field, and never a byte register", f.name)
		}
	}
	if inReg > 1 || inRM > 1 || inOpcode > 1 || conds > 1 || immediates > 1 {
		fail("%s has two operands in one place", f.name)
	}
	switch f.modrm {
	case modNone:
		if inReg+inRM > 0 {
			fail("%s has no ModRM byte for its operands", f.name)
		}
	case modOperands:
		if inReg != 1 || inRM != 1 {
			fail("%s needs one operand in the reg field and one in r/m", f.name)
		}
	case modDigit:
		if inReg != 0 || inRM != 1 {
			fail("%s needs one operand in r/m and none in reg", f.name)
		}
		if f.digit < 0 || f.digit >= lowRegisters {
			fail("%s has the digit %d", f.name, f.digit)
		}
	default:
		fail("%s has an unknown ModRM form", f.name)
	}
	if inOpcode+conds > 1 {
		fail("%s adds two operands to its opcode", f.name)
	}
}

func checkChoice(c choice) {
	if len(c.alternatives) < 2 {
		fail("choice %s has fewer than two alternatives", c.name)
	}
	first := formByName(c.alternatives[0])
	want := c.immediateKind()
	for i, name := range c.alternatives {
		f := formByName(name)
		got := paramsOf(withoutImmediate(f.operands))
		if !slices.Equal(got, paramsOf(withoutImmediate(first.operands))) {
			fail("choice %s: %s takes other operands than %s", c.name, name, first.name)
		}
		k := immediateKindOf(f)
		if i == len(c.alternatives)-1 && k != want {
			fail("choice %s: its last alternative %s does not hold every value of the choice", c.name, name)
		}
	}
}

func withoutImmediate(ops []operand) []operand {
	var out []operand
	for _, o := range ops {
		if !isImmediate(o.kind) {
			out = append(out, o)
		}
	}
	return out
}

func checkSequence(s sequence) {
	own := paramsOf(s.operands)
	for _, st := range s.steps {
		f := formByName(st.form)
		ps := f.params()
		if len(ps) != len(st.args) {
			fail("sequence %s: %s takes %d arguments, not %d", s.name, st.form, len(ps), len(st.args))
		}
		for i, a := range st.args {
			if registerIndex(a) >= 0 {
				if ps[i].ty != typeRegister {
					fail("sequence %s: %s is not a register argument of %s", s.name, a, st.form)
				}
				continue
			}
			j := slices.IndexFunc(own, func(p param) bool { return p.name == a })
			if j < 0 || own[j].ty != ps[i].ty {
				fail("sequence %s: %s is no parameter of the sequence of the type %s", s.name, a, ps[i].ty)
			}
		}
	}
}

// checkEffects refuses a table in which no form has an effect or every form does, which says that a column is wrong.
func checkEffects() {
	for _, e := range effectList {
		any, all := false, true
		for _, f := range forms {
			if e.of(f) {
				any = true
			} else {
				all = false
			}
		}
		if !any || all {
			fail("%s is true of no form or of every form", e.name)
		}
	}
}

// effectList are the predicates of the effects, in the order they are written.
var effectList = []struct {
	name string
	of   func(form) bool
}{
	{"setsFlags", func(f form) bool { return f.setsFlags }},
	{"readsFlags", func(f form) bool { return f.readsFlags }},
	{"readsMemory", func(f form) bool { return f.readsMemory }},
	{"writesMemory", func(f form) bool { return f.writesMemory }},
}
