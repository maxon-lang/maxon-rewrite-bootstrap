package main

import (
	"fmt"
	"slices"
	"strings"
)

// convertFile is where cmd/convert, which leaves out a library declaration of a name minimaxon has built in, finds the
// names.
const convertFile = "../../cmd/convert/builtins_gen.go"

// builtinNames are the names the table declares at the top level, in the table's order, each once.
func builtinNames(t table) []string {
	var names []string
	add := func(name string) {
		if !slices.Contains(names, name) {
			names = append(names, name)
		}
	}
	for _, a := range stdAliases {
		add(a.Name)
	}
	for _, bt := range builtinTypes {
		add(bt.Name)
	}
	for _, r := range recordTypes {
		add(r.Name)
	}
	for _, u := range unionTypes {
		add(u.Name)
	}
	for _, e := range enumTypes {
		add(e.Name)
	}
	for _, c := range slices.Concat(capabilities, markers) {
		add(c)
	}
	for _, a := range typeAliases {
		add(a.Name)
	}
	for _, f := range t.fns {
		if f.Owner == "" {
			add(f.Name)
		}
	}
	return names
}

func emitConvert(t table) string {
	var sb strings.Builder
	sb.WriteString("// Code generated by builtingen from internal/builtingen/table.go; DO NOT EDIT.\n\npackage main\n\n")
	sb.WriteString("// builtinNames are the names minimaxon declares at the top level as built-ins, which a library declaration does not declare\n// again.\n")
	sb.WriteString("var builtinNames = map[string]bool{\n")
	for _, name := range builtinNames(t) {
		fmt.Fprintf(&sb, "\t%q: true,\n", name)
	}
	sb.WriteString("}\n\n")
	sb.WriteString("// builtinMethods are the methods minimaxon declares on each type it builds in, by the type's name, in the table's order.\n")
	sb.WriteString("var builtinMethods = map[string][]string{\n")
	owners, methods := builtinMethods(t)
	for _, owner := range owners {
		fmt.Fprintf(&sb, "\t%q: {", owner)
		for i, m := range methods[owner] {
			if i > 0 {
				sb.WriteString(", ")
			}
			fmt.Fprintf(&sb, "%q", m)
		}
		sb.WriteString("},\n")
	}
	sb.WriteString("}\n\n")
	sb.WriteString("// libraryRawMembers are the functions of each type of maxon's raw surface that minimaxon's library declares, by the type's\n// name.\n")
	sb.WriteString("var libraryRawMembers = map[string][]string{\n")
	for _, r := range rawLibraryTypes {
		fmt.Fprintf(&sb, "\t%q: {", r.Name)
		for i, m := range r.Members {
			if i > 0 {
				sb.WriteString(", ")
			}
			fmt.Fprintf(&sb, "%q", m)
		}
		sb.WriteString("},\n")
	}
	sb.WriteString("}\n")
	return sb.String()
}

// builtinMethods are the names of the methods of each owner of the table, under the owner's type name, the owners in the
// order the table first names them.
func builtinMethods(t table) ([]string, map[string][]string) {
	nameOf := map[string]string{}
	for _, bt := range builtinTypes {
		nameOf[bt.Key] = bt.Name
	}
	var owners []string
	methods := map[string][]string{}
	for _, f := range t.fns {
		if f.Owner == "" {
			continue
		}
		owner := f.Owner
		if name, ok := nameOf[owner]; ok {
			owner = name
		}
		if _, ok := methods[owner]; !ok {
			owners = append(owners, owner)
		}
		if !slices.Contains(methods[owner], f.Name) {
			methods[owner] = append(methods[owner], f.Name)
		}
	}
	return owners, methods
}
