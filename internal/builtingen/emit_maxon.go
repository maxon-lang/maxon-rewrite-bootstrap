const maxonHeader = "// Code generated by builtingen from internal/builtingen/table.go; DO NOT EDIT.\n\n"

// maxonField is the field of self's Builtins record that holds a type of the table.
func maxonField(key string, generic bool) string {
	if generic {
		return lowerFirst(key) + "Origin"
	}
	return lowerFirst(key) + "Ty"
}

func maxonOwner(key string) string { return "b." + maxonField(key, len(ownerParams(key)) > 0) }

func maxonConv(conv string) string {
	if conv == "" {
		conv = "let"
	}
	return "Convention.conv" + upperFirst(conv)
}

// maxonBody is the body of a generated Maxon function: its lines, and a counter that names each temporary once.
type maxonBody struct {
	sb   strings.Builder
	temp int
}

func (m *maxonBody) line(format string, args ...any) {
	m.sb.WriteString("\t")
	fmt.Fprintf(&m.sb, format, args...)
	m.sb.WriteString("\n")
}

func (m *maxonBody) fresh(prefix string) string {
	m.temp++
	return fmt.Sprintf("%s%d", prefix, m.temp)
}

// strings binds a list of strings to a new variable, or is an empty list.
func (m *maxonBody) strings(xs []string) string {
	if len(xs) == 0 {
		return "StringList.create(0)"
	}
	v := m.fresh("names")
	m.line("var %s = StringList.create(0)", v)
	for _, x := range xs {
		m.line("%s.push(%q)", v, x)
	}
	return v
}

// ownerParam binds a parameter of a type of the table.
func (m *maxonBody) ownerParam(owner string, i int) string {
	v := m.fresh("p")
	m.line("let %s = typeEntry(tt, reads: reads, t: %s).typeParams[%d]", v, maxonOwner(owner), i)
	return v
}

// ty is the expression of a type the row writes; a type that has to be made is bound to a temporary first, so no
// operand of a call borrows the type table while another one changes it.
func (m *maxonBody) ty(f fn, generic string, t *tyExpr) string {
	switch {
	case t.name == "Self":
		v := m.fresh("ty")
		m.line("let %s = selfType(tt, reads: reads, declTy: %s)", v, maxonOwner(f.Owner))
		return v
	case t.name == f.generic:
		return generic
	case paramIndex(ownerParams(f.Owner), t.name) >= 0:
		return m.ownerParam(f.Owner, paramIndex(ownerParams(f.Owner), t.name))
	case primOf(t.name) != nil:
		return primOf(t.name).Maxon
	case t.arg != nil:
		arg := m.ty(f, generic, t.arg)
		v := m.fresh("ty")
		m.line("let %s = instantiateType(tt, reads: reads, origin: %s, args: oneArgList(%s))", v, maxonOwner(t.name), arg)
		return v
	}
	return maxonOwner(t.name)
}

func (m *maxonBody) params(f fn, generic string) string {
	if len(f.params) == 0 {
		return "ParamSpecList.create(0)"
	}
	types := make([]string, len(f.params))
	for i, p := range f.params {
		types[i] = m.ty(f, generic, p.ty)
	}
	v := m.fresh("ps")
	m.line("var %s = ParamSpecList.create(0)", v)
	for i, p := range f.params {
		if p.defaultCase != "" {
			m.line("%s.push(ParamSpec.withCaseDefault(%q, ty: %s, conv: %s, defaultCase: %d))", v, p.name, types[i], maxonConv(p.conv), defaultIndex(p))
			continue
		}
		maker := "make"
		if p.labelled {
			maker = "labelledFirst"
		}
		if p.mayOmitLabel {
			maker = "mayOmitLabel"
		}
		m.line("%s.push(ParamSpec.%s(%q, ty: %s, conv: %s))", v, maker, p.name, types[i], maxonConv(p.conv))
	}
	return v
}

func emitMaxon(t table) string {
	var sb strings.Builder
	sb.WriteString(maxonHeader)
	for _, r := range recordTypes {
		for i, f := range r.Fields {
			fmt.Fprintf(&sb, "export let %s = %d as Count\n\n", lowerFirst(fieldConst(r, parseField(f))), i)
		}
	}
	for _, u := range unionTypes {
		for i, c := range u.Cases {
			fmt.Fprintf(&sb, "export let %s = %d as Count\n\n", lowerFirst(c.Const), i)
		}
	}
	for _, e := range enumTypes {
		for i, c := range e.Cases {
			fmt.Fprintf(&sb, "export let %s = %d as Count\n\n", lowerFirst(c.Const), i)
		}
	}
	sb.WriteString("export enum Intrinsic\n\tintrNone\n")
	for _, in := range t.intrinsics {
		fmt.Fprintf(&sb, "\tintr%s\n", in.name)
	}
	sb.WriteString("end 'Intrinsic'\n\n")
	sb.WriteString("// intrinsicRuntimeOnly is whether only the runtime module may call the intrinsic (E3152).\nexport function intrinsicRuntimeOnly(op Intrinsic) returns bool\n")
	for _, in := range t.intrinsics {
		if in.runtimeOnly {
			fmt.Fprintf(&sb, "\tif op == Intrinsic.intr%s 'intr%s'\n\t\treturn true\n\tend 'intr%s'\n", in.name, in.name, in.name)
		}
	}
	sb.WriteString("\treturn false\nend 'intrinsicRuntimeOnly'\n\n")
	sb.WriteString("// intrinsicMayOverlap is whether an argument of a call of the intrinsic may name the place of its receiver.\nexport function intrinsicMayOverlap(op Intrinsic) returns bool\n")
	for _, in := range t.intrinsics {
		if in.mayOverlap {
			fmt.Fprintf(&sb, "\tif op == Intrinsic.intr%s 'intr%s'\n\t\treturn true\n\tend 'intr%s'\n", in.name, in.name, in.name)
		}
	}
	sb.WriteString("\treturn false\nend 'intrinsicMayOverlap'\n\n")
	emitMaxonRawSurface(&sb, t)

	var groups []string
	byGroup := map[string][]fn{}
	for _, f := range t.fns {
		g := f.Owner
		if _, ok := byGroup[g]; !ok {
			groups = append(groups, g)
		}
		byGroup[g] = append(byGroup[g], f)
	}

	sb.WriteString("function declareStdAliases(mutates tt TypeSlot, reads TypeTable, mutates std ParsedModule, mutates b Builtins, mutates typeMap TypeIDMap)\n")
	for _, a := range stdAliases {
		if a.Bits != 0 {
			fmt.Fprintf(&sb, "\tb.%s = registerStdBitsAlias(tt, reads: reads, std: std, typeMap: typeMap, name: %q, width: %d)\n", a.Field, a.Name, a.Bits)
			continue
		}
		register := "registerStdAlias"
		if a.Float {
			register = "registerStdFloatAlias"
		}
		fmt.Fprintf(&sb, "\tb.%s = %s(tt, reads: reads, std: std, typeMap: typeMap, name: %q, lo: %s, hi: %s)\n", a.Field, register, a.Name, a.Lo, a.Hi)
	}
	sb.WriteString("end 'declareStdAliases'\n\n")

	sb.WriteString("function declareBuiltinTable(mutates tt TypeSlot, reads TypeTable, mutates ft FuncSlot, funcReads FuncTable, mutates std ParsedModule, mutates b Builtins, mutates typeMap TypeIDMap, mutates funcMap FuncIDMap)\n")
	sb.WriteString("\tdeclareBuiltinTypes(tt, reads: reads, std: std, b: b, typeMap: typeMap)\n")
	for _, g := range groups {
		fmt.Fprintf(&sb, "\t%s(tt, reads: reads, ft: ft, funcReads: funcReads, std: std, b: b, funcMap: funcMap)\n", maxonGroupFunction(g))
	}
	sb.WriteString("end 'declareBuiltinTable'\n")

	types := &maxonBody{}
	for _, bt := range builtinTypes {
		names := types.strings(bt.Params)
		kind := bt.Kind
		if kind == "" {
			kind = bt.Key
		}
		types.line("%s = registerPrimType(tt, reads: reads, std: std, typeMap: typeMap, kind: TypeKind.builtin%s, name: %q, paramNames: %s)", maxonOwner(bt.Key), kind, bt.Name, names)
	}
	for _, r := range recordTypes {
		types.line("%s = registerRecordType(tt, reads: reads, std: std, typeMap: typeMap, name: %q)", maxonOwner(r.Key), r.Name)
	}
	for _, r := range recordTypes {
		owner := fn{Owner: r.Key}
		for _, s := range r.Fields {
			f := parseField(s)
			ty := types.ty(owner, "", f.ty)
			types.line("addRecordField(tt, reads: reads, owner: %s, name: %q, ty: %s, isVar: %v, exported: %v)", maxonOwner(r.Key), f.name, ty, f.isVar, !f.private)
		}
	}
	for _, u := range unionTypes {
		names := types.strings(u.Params)
		types.line("%s = registerUnionType(tt, reads: reads, std: std, typeMap: typeMap, name: %q, paramNames: %s)", maxonOwner(u.Key), u.Name, names)
		owner := fn{Owner: u.Key}
		for _, c := range u.Cases {
			payload := "CaseFieldList.create(0)"
			if len(c.Payload) > 0 {
				fields := make([]string, len(c.Payload))
				tys := make([]string, len(c.Payload))
				for i, p := range c.Payload {
					name, ty, _ := strings.Cut(p, " ")
					fields[i] = name
					tys[i] = types.ty(owner, "", parseType(ty))
				}
				payload = types.fresh("payload")
				types.line("var %s = CaseFieldList.create(0)", payload)
				for i := range fields {
					types.line("%s.push(CaseFieldInfo.make(%q, ty: %s))", payload, fields[i], tys[i])
				}
			}
			types.line("addUnionCase(tt, reads: reads, owner: %s, name: %q, payload: %s)", maxonOwner(u.Key), c.Name, payload)
		}
	}
	for _, e := range enumTypes {
		var cases []string
		for _, c := range e.Cases {
			cases = append(cases, c.Name)
		}
		names := types.strings(cases)
		types.line("b.%s = registerEnumType(tt, reads: reads, std: std, typeMap: typeMap, name: %q, cases: %s)", maxonField(e.Key, false), e.Name, names)
	}
	for _, c := range slices.Concat(capabilities, markers) {
		types.line("b.%s = registerInterfaceType(tt, reads: reads, std: std, typeMap: typeMap, name: %q)", maxonField(c, false), c)
	}
	for _, r := range recordTypes {
		for _, iface := range r.Implements {
			types.line("tt.lists[typeList(tt, t: %[1]s)][typeIndex(tt, t: %[1]s)].conforms.push(b.%s)", maxonOwner(r.Key), maxonField(iface, false))
		}
	}
	for _, a := range typeAliases {
		ty := types.ty(fn{}, "", parseType(a.Type))
		types.line("registerStdInstanceAlias(std, typeMap: typeMap, name: %q, ty: %s)", a.Name, ty)
	}
	sb.WriteString("\nfunction declareBuiltinTypes(mutates tt TypeSlot, reads TypeTable, mutates std ParsedModule, mutates b Builtins, mutates typeMap TypeIDMap)\n")
	sb.WriteString(types.sb.String())
	sb.WriteString("end 'declareBuiltinTypes'\n")

	for _, g := range groups {
		body := &maxonBody{}
		for _, f := range byGroup[g] {
			emitMaxonFunction(body, f)
		}
		name := maxonGroupFunction(g)
		fmt.Fprintf(&sb, "\nfunction %s(mutates tt TypeSlot, reads TypeTable, mutates ft FuncSlot, funcReads FuncTable, mutates std ParsedModule, mutates b Builtins, mutates funcMap FuncIDMap)\n", name)
		sb.WriteString(body.sb.String())
		fmt.Fprintf(&sb, "end '%s'\n", name)
	}
	return sb.String()
}

// emitMaxonRawSurface writes what the checker refuses outside the library tiers (E3185): the types of maxon's raw surface,
// the static functions of the records whose calls are raw, and the views.
func emitMaxonRawSurface(sb *strings.Builder, t table) {
	sb.WriteString("// RawSurface is a door of maxon's raw surface, which only the library tiers may go through (E3185): what it is or reaches,\n// and what a program uses instead.\n")
	sb.WriteString("export type RawSurface\n\texport var what as String\n\texport var instead as String\n\n")
	sb.WriteString("\tstatic function make(consumes what String, consumes instead String) returns RawSurface\n\t\treturn RawSurface{what: what, instead: instead}\n\tend 'make'\nend 'RawSurface'\n\n")
	some := func(s rawSurface) string {
		return fmt.Sprintf("table.Option.some(RawSurface.make(%q, instead: %q))", s.What, s.Instead)
	}
	for _, door := range []struct {
		name, doc string
		of        func(rawType) rawSurface
	}{
		{"rawTypeSurface", "naming a type of the table is", func(r rawType) rawSurface { return r.Named }},
		{"rawMethodSurface", "calling a method of a type of the table is", func(r rawType) rawSurface { return r.Methods }},
	} {
		fmt.Fprintf(sb, "// %s is the door of the raw surface that %s, or none for a type that is no part of it.\n", door.name, door.doc)
		fmt.Fprintf(sb, "export function %s(b Builtins, origin TypeID) returns table.Option with RawSurface\n", door.name)
		for _, bt := range builtinTypes {
			// A type whose values are a program's but whose name is the library's has a door for its name alone.
			if bt.Raw != nil && door.of(*bt.Raw).What != "" {
				fmt.Fprintf(sb, "\tif origin == %s 'raw%s'\n\t\treturn %s\n\tend 'raw%s'\n", maxonOwner(bt.Key), bt.Key, some(door.of(*bt.Raw)), bt.Key)
			}
		}
		fmt.Fprintf(sb, "\treturn table.Option.none\nend '%s'\n\n", door.name)
	}
	sb.WriteString("// rawCallInstead is what a program calls in place of a static function of a record of the table whose calls are raw, or\n// none for a function of any other owner.\n")
	sb.WriteString("export function rawCallInstead(b Builtins, owner TypeID, name String) returns table.Option with String\n")
	for _, r := range recordTypes {
		if !r.RawCalls {
			continue
		}
		fmt.Fprintf(sb, "\tif owner == %s 'raw%s'\n", maxonOwner(r.Key), r.Key)
		for _, f := range t.fns {
			if f.Owner == r.Key {
				fmt.Fprintf(sb, "\t\tif name == %q '%s'\n\t\t\treturn table.Option.some(%q)\n\t\tend '%s'\n", f.Name, f.Name, f.Instead, f.Name)
			}
		}
		fmt.Fprintf(sb, "\t\tpanic(\"'{name}' is no static function of %s\")\n\tend 'raw%s'\n", r.Name, r.Key)
	}
	sb.WriteString("\treturn table.Option.none\nend 'rawCallInstead'\n\n")
	sb.WriteString("// rawMemberSurface is the door of the raw surface that calling a method of that name of a type of the table is, for a\n// method that is one, or none.\n")
	sb.WriteString("export function rawMemberSurface(b Builtins, owner TypeID, name String) returns table.Option with RawSurface\n")
	for _, f := range t.fns {
		if f.Raw != nil {
			fmt.Fprintf(sb, "\tif owner == %s and name == %q '%s%s'\n\t\treturn %s\n\tend '%s%s'\n", maxonOwner(f.Owner), f.Name, lowerFirst(f.Owner), upperFirst(f.Name), some(*f.Raw), lowerFirst(f.Owner), upperFirst(f.Name))
		}
	}
	sb.WriteString("\treturn table.Option.none\nend 'rawMemberSurface'\n\n")
	sb.WriteString("// BuiltinView is a member of a built-in generic type that is the same value seen as an instance of another type of the\n// table, at the same type arguments, and the door of the raw surface that reading it is.\n")
	sb.WriteString("export type BuiltinView\n\texport var origin as TypeID\n\texport var surface as RawSurface\n\n")
	sb.WriteString("\tstatic function make(origin TypeID, consumes surface RawSurface) returns BuiltinView\n\t\treturn BuiltinView{origin: origin, surface: surface}\n\tend 'make'\nend 'BuiltinView'\n\n")
	sb.WriteString("// builtinView is the view of that name of a built-in generic type, or none.\n")
	sb.WriteString("export function builtinView(b Builtins, owner TypeID, name String) returns table.Option with BuiltinView\n")
	for _, v := range views {
		fmt.Fprintf(sb, "\tif owner == %s and name == %q '%s%s'\n\t\treturn table.Option.some(BuiltinView.make(%s, surface: RawSurface.make(%q, instead: %q)))\n\tend '%s%s'\n",
			maxonOwner(v.Owner), v.Name, lowerFirst(v.Owner), upperFirst(v.Name), maxonOwner(v.Type), v.Raw.What, v.Raw.Instead, lowerFirst(v.Owner), upperFirst(v.Name))
	}
	sb.WriteString("\treturn table.Option.none\nend 'builtinView'\n\n")
}

func maxonGroupFunction(owner string) string {
	if owner == "" {
		return "declareBuiltinFunctions"
	}
	return "declare" + owner + "Methods"
}

func emitMaxonFunction(m *maxonBody, f fn) {
	op := "Intrinsic.intr" + f.Intrinsic
	if f.Owner != "" && !isPrimOwner(f.Owner) {
		ret := m.ty(f, "", f.result)
		ps := m.params(f, "")
		call := fmt.Sprintf("registerMethodOn(tt, reads: reads, ft: ft, funcReads: funcReads, std: std, owner: %s, op: %s, name: %q, isStatic: %v, selfConv: %s, ret: %s, params: %s, listed: %v)",
			maxonOwner(f.Owner), op, f.Name, f.Static, maxonConv(f.Self), ret, ps, f.Field == "")
		if len(f.bounds) == 0 && f.Throws == "" && f.Field == "" && !f.Lends {
			m.line("_ = %s", call)
			return
		}
		id := m.fresh("f")
		m.line("let %s = %s", id, call)
		m.lends(f, id)
		for _, bd := range f.bounds {
			p := m.ownerParam(f.Owner, paramIndex(ownerParams(f.Owner), bd.param))
			m.line("ft.lists[funcList(ft, f: %[1]s)][funcIndex(ft, f: %[1]s)].bounds.push(ParamBound.make(%s, ifaceTy: b.%s))", id, p, maxonField(bd.iface, false))
		}
		m.errorType(f, id)
		if f.Field != "" {
			m.line("b.%sFunc = %s", lowerFirst(f.Field), id)
		}
		return
	}
	generics, generic := "TypeIDList.create(0)", ""
	if f.generic != "" {
		tp := m.fresh("tp")
		m.line("var %s = TypeEntry.make(TypeKind.typeParam, name: %q)", tp, f.generic)
		if f.gbound != "" {
			m.line("%s.boundIface = b.%s", tp, maxonField(f.gbound, false))
		}
		generic = m.fresh("g")
		m.line("let %s = allocType(tt, module: diag.stdlibID, e: %s)", generic, tp)
		generics = fmt.Sprintf("oneArgList(%s)", generic)
	}
	ret := m.ty(f, generic, f.result)
	ps := m.params(f, generic)
	declared := f.Owner == "" && f.Field == ""
	call := fmt.Sprintf("registerStdFunc(ft, funcReads: funcReads, std: std, funcMap: funcMap, op: %s, name: %q, generics: %s, ret: %s, params: %s, declareInStd: %v)",
		op, f.Name, generics, ret, ps, declared)
	if declared && f.gbound == "" && f.Throws == "" {
		m.line("_ = %s", call)
		return
	}
	id := m.fresh("f")
	m.line("let %s = %s", id, call)
	m.errorType(f, id)
	m.lends(f, id)
	if f.gbound != "" {
		m.line("ft.lists[funcList(ft, f: %[1]s)][funcIndex(ft, f: %[1]s)].bounds.push(ParamBound.make(%s, ifaceTy: b.%s))", id, generic, maxonField(f.gbound, false))
	}
	if prefix, ok := primOwners[f.Owner]; ok {
		m.line("ft.lists[funcList(ft, f: %[1]s)][funcIndex(ft, f: %[1]s)].ownerTy = b.%[2]sTy", id, prefix)
		m.line("ft.lists[funcList(ft, f: %[1]s)][funcIndex(ft, f: %[1]s)].isStatic = %v", id, f.Static)
		m.line("ft.lists[funcList(ft, f: %[1]s)][funcIndex(ft, f: %[1]s)].hasReceiver = %v", id, !f.Static)
		if f.Self != "" {
			m.line("ft.lists[funcList(ft, f: %[1]s)][funcIndex(ft, f: %[1]s)].selfConv = %s", id, maxonConv(f.Self))
		}
		m.line("b.%sMethods.insert(%q, value: %s)", prefix, f.Name, id)
	}
	if f.Field != "" {
		m.line("b.%sFunc = %s", lowerFirst(f.Field), id)
	}
}

// lends makes the function id lend a place, or a view, rather than give a value, when its row says so.
func (m *maxonBody) lends(f fn, id string) {
	if f.Lends {
		m.line("ft.lists[funcList(ft, f: %[1]s)][funcIndex(ft, f: %[1]s)].result = ResultConv.resultBorrowed", id)
	}
}

// errorType sets the error that the function id throws, when it throws one.
func (m *maxonBody) errorType(f fn, id string) {
	if f.Throws != "" {
		m.line("ft.lists[funcList(ft, f: %[1]s)][funcIndex(ft, f: %[1]s)].errTy = b.%s", id, maxonField(f.Throws, false))
	}
}

// emitMaxonRt writes self/ir's Rt, numbered in the order of the table's entries. Its symbols are self's: an entry that
// the runtime's source defines is linked by its function's link name.
func emitMaxonRt(t table) string {
	var sb strings.Builder
	sb.WriteString(maxonHeader)
	sb.WriteString("// Rt names a symbol the runtime defines: an entry that code calls or a global it reads.\nexport enum Rt\n\trtNone\n")
	for _, e := range entries {
		fmt.Fprintf(&sb, "\trt%s\n", e.Name)
	}
	sb.WriteString("end 'Rt'\n\n// rtSymbol is the name the runtime defines a symbol by.\nexport function rtSymbol(r Rt) returns String\n")
	for _, e := range entries {
		fmt.Fprintf(&sb, "\tif r == Rt.rt%s 'rt%s'\n\t\treturn %q\n\tend 'rt%s'\n", e.Name, e.Name, t.symbolOf(e), e.Name)
	}
	sb.WriteString("\tpanic(\"ir: rtNone names no runtime symbol\")\nend 'rtSymbol'\n\n// rtText is the name the IR text and a report give a symbol, which is the same in either compiler.\nexport function rtText(r Rt) returns String\n")
	for _, e := range entries {
		fmt.Fprintf(&sb, "\tif r == Rt.rt%s 'rt%s'\n\t\treturn %q\n\tend 'rt%s'\n", e.Name, e.Name, e.Symbol, e.Name)
	}
	sb.WriteString("\tpanic(\"ir: rtNone has no text\")\nend 'rtText'\n\n// rtCode is the number an instruction holds a symbol as.\nexport function rtCode(r Rt) returns Count\n")
	for i, e := range entries {
		fmt.Fprintf(&sb, "\tif r == Rt.rt%s 'rt%s'\n\t\treturn %d\n\tend 'rt%s'\n", e.Name, e.Name, i+1, e.Name)
	}
	sb.WriteString("\tpanic(\"ir: rtNone has no number\")\nend 'rtCode'\n\n// rtOf is the symbol an instruction holds as a number.\nexport function rtOf(code Count) returns Rt\n\treturn match code 'code'\n")
	for i, e := range entries {
		fmt.Fprintf(&sb, "\t\t%d gives Rt.rt%s\n", i+1, e.Name)
	}
	sb.WriteString("\t\tdefault panic(\"ir: a number that is no runtime symbol\")\n\tend 'code'\nend 'rtOf'\n")

	sb.WriteString("\n// RtUnit is where a runtime symbol is defined.\nexport enum RtUnit\n")
	for _, u := range units {
		fmt.Fprintf(&sb, "\trtUnit%s\n", u.Key)
	}
	sb.WriteString("end 'RtUnit'\n\n// rtUnit is where the symbol is defined.\nexport function rtUnit(r Rt) returns RtUnit\n")
	for _, e := range entries {
		fmt.Fprintf(&sb, "\tif r == Rt.rt%s 'rt%s'\n\t\treturn RtUnit.rtUnit%s\n\tend 'rt%s'\n", e.Name, e.Name, e.Unit, e.Name)
	}
	sb.WriteString("\tpanic(\"ir: rtNone is defined by no unit\")\nend 'rtUnit'\n")
	emitMaxonRtFunctions(&sb, t)
	return sb.String()
}

// emitMaxonRtFunctions writes the functions of the runtime's source that define entries, with their signatures, which the
// driver holds the runtime to.
func emitMaxonRtFunctions(sb *strings.Builder, t table) {
	sb.WriteString("\n// RtParam is a parameter of an RtFunction.\nexport type RtParam\n\texport var conv as ast.Convention\n\texport var name as String\n\texport var ty as ast.TypeID\n\n")
	sb.WriteString("\tstatic function make(conv ast.Convention, consumes name String, ty ast.TypeID) returns RtParam\n\t\treturn RtParam{conv: conv, name: name, ty: ty}\n\tend 'make'\nend 'RtParam'\n\n")
	sb.WriteString("export typealias RtParamList = Array with RtParam\n\n")
	sb.WriteString("// RtFunction is the function of the runtime's source that defines an entry (README, \"The runtime\"): code calls the\n// entry as it calls any function, so its signature is the entry's calling convention.\n")
	sb.WriteString("export type RtFunction\n\texport var entry as Rt\n\texport var name as String\n\texport var params as RtParamList\n\texport var result as ast.TypeID\n\n")
	sb.WriteString("\tstatic function make(entry Rt, consumes name String, consumes params RtParamList, result ast.TypeID) returns RtFunction\n\t\treturn RtFunction{entry: entry, name: name, params: params, result: result}\n\tend 'make'\nend 'RtFunction'\n\n")
	sb.WriteString("export typealias RtFunctionList = Array with RtFunction\n\n")
	sb.WriteString("// rtFunctions are the functions of the runtime's source that define entries, in the table's order.\nexport function rtFunctions(b ast.Builtins) returns RtFunctionList\n\tvar fns = RtFunctionList.create(0)\n")
	for i, r := range t.rtFuncs {
		binding := "var"
		if len(r.params) == 0 {
			binding = "let"
		}
		fmt.Fprintf(sb, "\t%s params%d = RtParamList.create(0)\n", binding, i)
		for _, p := range r.params {
			fmt.Fprintf(sb, "\tparams%d.push(RtParam.make(ast.%s, name: %q, ty: %s))\n", i, maxonConv(p.conv), p.name, primOf(p.ty.name).Maxon)
		}
		fmt.Fprintf(sb, "\tfns.push(RtFunction.make(Rt.rt%s, name: %q, params: params%d, result: %s))\n", r.entry.Name, r.name, i, primOf(r.result.name).Maxon)
	}
	sb.WriteString("\treturn fns\nend 'rtFunctions'\n")
	sb.WriteString("\n// rtGivesString is whether the function that defines an entry returns a String, which a call of it gives in a\n// register of that kind.\nexport function rtGivesString(r Rt) returns bool\n\treturn match r 'entry'\n")
	gives := map[string]bool{}
	for _, r := range t.rtFuncs {
		gives[r.entry.Name] = r.result.name == "String"
	}
	var strs, others []string
	others = append(others, "rtNone")
	for _, e := range entries {
		if gives[e.Name] {
			strs = append(strs, "rt"+e.Name)
		} else {
			others = append(others, "rt"+e.Name)
		}
	}
	for _, group := range []struct {
		names []string
		gives string
	}{{strs, "true"}, {others, "false"}} {
		if len(group.names) > 0 {
			fmt.Fprintf(sb, "\t\t%s gives %s\n", strings.Join(group.names, " or\n\t\t"), group.gives)
		}
	}
	sb.WriteString("\tend 'entry'\nend 'rtGivesString'\n")
}

// emitMaxonIntrinsics writes self/ir's dispatch from an intrinsic to the function that lowers it, which the lowerer
// defines for each row of the table.
func emitMaxonIntrinsics(t table) string {
	var sb strings.Builder
	sb.WriteString(maxonHeader)
	sb.WriteString("// intrinsicCall lowers a call of a built-in whose receiver and arguments are lowered.\n")
	sb.WriteString("export function intrinsicCall(mutates l Lowerer, p ast.Project, mutates ms ast.ModuleState, op ast.Intrinsic, c CallSite, recv Reg, args RegList) returns Reg\n")
	for _, in := range t.intrinsics {
		fmt.Fprintf(&sb, "\tif op == ast.Intrinsic.intr%s 'intr%s'\n\t\treturn lower%s(l, p: p, ms: ms, c: c, recv: recv, args: args)\n\tend 'intr%s'\n", in.name, in.name, in.name, in.name)
	}
	sb.WriteString("\tpanic(\"lower: a call names no intrinsic\")\nend 'intrinsicCall'\n\n")
	sb.WriteString("// ownsOperands is whether the lowering of an intrinsic evaluates its receiver and arguments itself.\n")
	sb.WriteString("export function ownsOperands(op ast.Intrinsic) returns bool\n")
	for _, in := range t.intrinsics {
		fmt.Fprintf(&sb, "\tif op == ast.Intrinsic.intr%s 'intr%s'\n\t\treturn %v\n\tend 'intr%s'\n", in.name, in.name, in.ownsOperands, in.name)
	}
	sb.WriteString("\tpanic(\"lower: a call names no intrinsic\")\nend 'ownsOperands'\n")
	return sb.String()
}

// emitMaxonCheck is self's dispatch from each intrinsic to the check of the arguments its signature alone cannot refuse.
func emitMaxonCheck(t table) string {
	var sb strings.Builder
	sb.WriteString(maxonHeader)
	sb.WriteString("// checkIntrinsicArgs refuses an argument of a built-in that its signature alone cannot.\n")
	sb.WriteString("function checkIntrinsicArgs(mutates c Checker, p ast.Project, mutates ms ast.ModuleState, call ast.NodeID, target ast.FuncID, ordered ast.NodeIDList, mutates errs diag.ErrorList)\n")
	sb.WriteString("\tlet op = ast.funcEntry(ms.funcs, funcReads: p.funcs, f: target).intrinsic\n")
	var unchecked []string
	for _, in := range t.intrinsics {
		if in.checked {
			fmt.Fprintf(&sb, "\tif op == ast.Intrinsic.intr%s 'check%s'\n\t\tcheck%sArgs(c, p: p, ms: ms, call: call, ordered: ordered, errs: errs)\n\t\treturn\n\tend 'check%s'\n", in.name, in.name, in.name, in.name)
		} else {
			unchecked = append(unchecked, in.name)
		}
	}
	// The signature checks every argument of the rest.
	var conds []string
	for _, name := range unchecked {
		conds = append(conds, "op == ast.Intrinsic.intr"+name)
	}
	for i := 0; i < len(conds); i += 4 {
		end := min(i+4, len(conds))
		fmt.Fprintf(&sb, "\tif %s 'signature%d'\n\t\treturn\n\tend 'signature%d'\n", strings.Join(conds[i:end], " or "), i/4, i/4)
	}
	sb.WriteString("\tpanic(\"check: {op.name} is no intrinsic\")\nend 'checkIntrinsicArgs'\n")
	return sb.String()
}

// emitMaxonInterp writes self/interp's dispatch from a runtime entry to the function of the interpreter that runs it, which
// is entry+Name.
func emitMaxonInterp(t table) string {
	var sb strings.Builder
	sb.WriteString(maxonHeader)
	sb.WriteString("// runtimeEntry runs a call of a runtime entry.\nfunction runtimeEntry(mutates vm Vm, f ir.IrFunction, x ir.Instr) throws Halt\n\tlet symbol = ir.callRuntimeSymbol(x)\n")
	var others []string
	for _, e := range entries {
		if e.Role != roleCall {
			others = append(others, "symbol == ir.Rt.rt"+e.Name)
			continue
		}
		fmt.Fprintf(&sb, "\tif symbol == ir.Rt.rt%s 'rt%s'\n\t\ttry entry%s(vm, f: f, x: x)\n\t\treturn\n\tend 'rt%s'\n", e.Name, e.Name, e.Name, e.Name)
	}
	for i := 0; i < len(others); i += 4 {
		end := min(i+4, len(others))
		fmt.Fprintf(&sb, "\tif %s 'internal%d'\n\t\tpanic(\"interp: {ir.rtText(symbol)} is no entry the IR calls\")\n\tend 'internal%d'\n", strings.Join(others[i:end], " or "), i/4, i/4)
	}
	sb.WriteString("\tpanic(\"interp: a call of no runtime entry\")\nend 'runtimeEntry'\n")
	return sb.String()
}

// emitSharedRuntime is the interpreter's copy of a file of the runtime that it shares, the text operations or the hash's
// fold: one text says what each of them means, and the interpreter runs it where the executable runs the runtime's.
func emitSharedRuntime(path, name string) string {
	src, err := os.ReadFile(path)
	if err != nil {
		fail("the runtime's %s: %v", name, err)
	}
	return "// Code generated by builtingen from runtime/" + filepath.Base(path) + "; DO NOT EDIT.\n\n" + strings.ReplaceAll(string(src), "\r\n", "\n")
}

// builtinsField is a field of self's Builtins record and the value Builtins.empty() gives it.
type builtinsField struct{ name, ty, zero string }

// builtinsFields are the fields of the record in the order of the table: the primitives, the fields initBuiltins gives by
// hand, the type of every row, the function handles the checker and the lowering read, and the stdlib's maps.
func builtinsFields(t table) []builtinsField {
	var out []builtinsField
	seen := map[string]bool{}
	add := func(name, ty, zero string) {
		if seen[name] {
			return
		}
		seen[name] = true
		out = append(out, builtinsField{name, ty, zero})
	}
	typeField := func(name string) { add(name, "TypeID", "noType") }
	for _, p := range primTypes {
		typeField(strings.TrimPrefix(p.Maxon, "b."))
	}
	for _, f := range extraFields {
		if f.Type == "TypeID" {
			typeField(f.Name)
		}
	}
	for _, b := range builtinTypes {
		typeField(maxonField(b.Key, len(b.Params) > 0))
	}
	for _, r := range recordTypes {
		typeField(maxonField(r.Key, false))
	}
	for _, u := range unionTypes {
		typeField(maxonField(u.Key, len(u.Params) > 0))
	}
	for _, e := range enumTypes {
		typeField(maxonField(e.Key, false))
	}
	for _, c := range slices.Concat(capabilities, markers) {
		typeField(maxonField(c, false))
	}
	for _, f := range t.fns {
		if f.Field != "" {
			add(lowerFirst(f.Field)+"Func", "FuncID", "noFunc")
		}
	}
	for _, f := range extraFields {
		if f.Type != "TypeID" {
			add(f.Name, f.Type, f.Zero)
		}
	}
	return out
}

// emitMaxonBuiltinsRecord is the Builtins record: a field for each type and function handle that the declarations
// register, with the constructor that holds none of them yet and the test of a capability.
func emitMaxonBuiltinsRecord(t table) string {
	fields := builtinsFields(t)
	var sb strings.Builder
	sb.WriteString(maxonHeader)
	sb.WriteString("export type Builtins\n")
	for _, f := range fields {
		fmt.Fprintf(&sb, "\texport var %s as %s\n", f.name, f.ty)
	}
	sb.WriteString("\n\texport static function empty() returns Builtins\n\t\treturn Builtins{")
	for i, f := range fields {
		if i > 0 {
			sb.WriteString(", ")
		}
		fmt.Fprintf(&sb, "%s: %s", f.name, f.zero)
	}
	sb.WriteString("}\n\tend 'empty'\n\n")
	sb.WriteString("\t// isCapability is whether an interface is one that a type has by its parts and no declaration implements.\n")
	var tests []string
	for _, c := range capabilities {
		tests = append(tests, "iface == "+maxonField(c, false))
	}
	sb.WriteString("\texport function isCapability(iface TypeID) returns bool\n\t\treturn " + strings.Join(tests, " or ") + "\n\tend 'isCapability'\n")
	sb.WriteString("end 'Builtins'\n")
	return sb.String()
}
