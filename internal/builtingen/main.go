// Command builtingen generates, from the table in table.go, the declarations of minimaxon's built-ins, the
// Intrinsic and runtime-symbol enums, and the dispatch from each intrinsic and each runtime entry to its hand-written
// body in the checker, the lowering, the interpreter and the backend, plus self's declarations and Rt. `go generate
// ./internal/ast` runs it in that directory.
//
// A dispatch calls a method named after each intrinsic or entry on the package's own type, so a row added to the
// table fails the build in every package that has no body for it yet.
package main

import (
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

const (
	astFile             = "builtins_gen.go"
	checkFile           = "../check/builtins_gen.go"
	irFile              = "../ir/builtins_gen.go"
	interpFile          = "../interp/builtins_gen.go"
	backendFile         = "../backend/builtins_gen.go"
	maxonFile           = "../../self/ast/builtins_gen.maxon"
	maxonRtFile         = "../../self/ir/runtime_gen.maxon"
	maxonIntrinsicsFile = "../../self/ir/intrinsics_gen.maxon"
	maxonCheckFile      = "../../self/check/builtins_gen.maxon"

	header = "// Code generated by builtingen from internal/builtingen/table.go; DO NOT EDIT.\n\n"
)

type output struct {
	path string
	code []byte
}

func main() {
	outs, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "builtingen:", err)
		os.Exit(1)
	}
	for _, o := range outs {
		if err := os.WriteFile(o.path, o.code, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "builtingen:", err)
			os.Exit(1)
		}
	}
}

// tableError is a row of the table that the generator cannot make code of.
type tableError struct{ msg string }

func (e *tableError) Error() string { return e.msg }

func fail(format string, args ...any) {
	panic(&tableError{fmt.Sprintf(format, args...)})
}

func generate() (outs []output, err error) {
	defer func() {
		if r := recover(); r != nil {
			te, ok := r.(*tableError)
			if !ok {
				panic(r)
			}
			err = te
		}
	}()
	t := load()
	for _, o := range []struct {
		path string
		code string
	}{
		{astFile, emitAst(t)},
		{checkFile, emitCheck(t)},
		{irFile, emitIr(t)},
		{interpFile, emitInterp(t)},
		{backendFile, emitBackend(t)},
	} {
		code, err := format.Source([]byte(o.code))
		if err != nil {
			return nil, fmt.Errorf("%s does not parse as Go: %w\n%s", o.path, err, o.code)
		}
		outs = append(outs, output{o.path, code})
	}
	outs = append(outs, output{maxonFile, []byte(emitMaxon(t))}, output{maxonRtFile, []byte(emitMaxonRt())}, output{maxonIntrinsicsFile, []byte(emitMaxonIntrinsics(t))}, output{maxonCheckFile, []byte(emitMaxonCheck(t))})
	return outs, nil
}

// tyExpr is a type as a signature in the table writes it: a name, given an argument when the name is generic.
type tyExpr struct {
	name string
	arg  *tyExpr
}

func parseType(s string) *tyExpr {
	name, rest, generic := strings.Cut(strings.TrimSpace(s), " with ")
	if name == "" || strings.Contains(name, " ") {
		fail("type %q is not a name or 'Name with Type'", s)
	}
	t := &tyExpr{name: name}
	if generic {
		t.arg = parseType(rest)
	}
	return t
}

// param is a parameter of a built-in: its convention, its name and its type.
type param struct {
	conv string // "let", "mutates" or "consumes"
	name string
	ty   *tyExpr
}

var conventions = []string{"let", "mutates", "consumes"}

func parseParam(s string) param {
	fields := strings.SplitN(s, " ", 3)
	conv := "let"
	if len(fields) == 3 && isConvention(fields[0]) {
		conv, fields = fields[0], []string{fields[1], strings.Join(fields[2:], " ")}
	} else if len(fields) >= 2 {
		fields = []string{fields[0], strings.Join(fields[1:], " ")}
	}
	if len(fields) != 2 {
		fail("parameter %q is not 'convention name Type'", s)
	}
	return param{conv: conv, name: fields[0], ty: parseType(fields[1])}
}

func isConvention(s string) bool {
	return slices.Contains(conventions, s)
}

// bound is a type parameter and the capability it must have.
type bound struct{ param, iface string }

func parseBound(s string) bound {
	p, iface, ok := strings.Cut(s, " ")
	if !ok || !isCapability(iface) {
		fail("bound %q is not 'Param Capability' with a capability of %v", s, capabilities)
	}
	return bound{p, iface}
}

func isCapability(s string) bool {
	return slices.Contains(capabilities, s)
}

// fn is a function row with its signature parsed.
type fn struct {
	function
	params  []param
	result  *tyExpr
	generic string // the name of a free function's own type parameter
	gbound  string // the capability that parameter must have, or ""
	bounds  []bound
}

// intrinsic is one value of the Intrinsic enum, with what every row that lowers to it says about it.
type intrinsic struct {
	name                  string
	checked, ownsOperands bool
}

type table struct {
	fns        []fn
	intrinsics []intrinsic
}

func load() table {
	var t table
	seen := map[string]int{}
	names := map[string]bool{}
	for _, f := range functions {
		if f.Throws != "" && enumOf(f.Throws) == nil {
			fail("%s throws %s, which is no enum row of the table", f.Name, f.Throws)
		}
		if f.Owner != "" && f.Owner != stringOwner && !isOwner(f.Owner) {
			fail("%s is a method of %s, which the table does not declare", f.Name, f.Owner)
		}
		key := f.Owner + "." + f.Name
		if (f.Self != "" && (!isConvention(f.Self) || f.Owner == "" || f.Static)) || (f.Static && f.Owner == "") {
			fail("%s: only a method takes its receiver %q, and only a method of a type is static", key, f.Self)
		}
		if names[key] && f.Field == "" {
			fail("%s is declared twice", key)
		}
		names[key] = true
		r := fn{function: f}
		for _, p := range f.Params {
			r.params = append(r.params, parseParam(p))
		}
		result := f.Result
		if result == "" {
			result = "Void"
		}
		r.result = parseType(result)
		if f.Generic != "" {
			if f.Owner != "" {
				fail("%s has a type parameter of its own; only a free function does", key)
			}
			r.generic, r.gbound, _ = strings.Cut(f.Generic, " ")
			if r.gbound != "" && !isCapability(r.gbound) {
				fail("%s: %s is no capability", key, r.gbound)
			}
		}
		for _, b := range f.Bounds {
			r.bounds = append(r.bounds, parseBound(b))
		}
		r.check()
		t.fns = append(t.fns, r)
		if i, ok := seen[f.Intrinsic]; ok {
			if t.intrinsics[i].checked != f.Checked || t.intrinsics[i].ownsOperands != f.OwnsOperands {
				fail("the rows of intrinsic %s disagree on how it is checked or lowered", f.Intrinsic)
			}
			continue
		}
		seen[f.Intrinsic] = len(t.intrinsics)
		t.intrinsics = append(t.intrinsics, intrinsic{f.Intrinsic, f.Checked, f.OwnsOperands})
	}
	for _, a := range typeAliases {
		fn{Name: a.Name}.checkType(parseType(a.Type))
	}
	for _, e := range entries {
		if unitOf(e.Unit) == nil {
			fail("entry %s is in unit %s, which the table does not have", e.Name, e.Unit)
		}
		if e.Role != roleCall && e.Role != roleInternal && e.Role != roleGlobal {
			fail("entry %s has the role %q", e.Name, e.Role)
		}
	}
	return t
}

// stringOwner is the Owner of a method of String, which is a primitive and no type the table declares.
const stringOwner = "String"

// check refuses a signature that names a type the row cannot see.
func (f fn) check() {
	for _, p := range f.params {
		f.checkType(p.ty)
	}
	f.checkType(f.result)
	for _, b := range f.bounds {
		if paramIndex(ownerParams(f.Owner), b.param) < 0 {
			fail("%s bounds %s, which is no parameter of %s", f.Name, b.param, f.Owner)
		}
	}
}

func (f fn) checkType(t *tyExpr) {
	switch {
	case t.name == "Self":
		if f.Owner == "" || f.Owner == stringOwner {
			fail("%s names Self, and has no owner of its own", f.Name)
		}
	case t.name == f.generic || paramIndex(ownerParams(f.Owner), t.name) >= 0 || primOf(t.name) != nil:
	case isOwner(t.name):
		if (t.arg != nil) != (len(ownerParams(t.name)) == 1) {
			fail("%s writes %s with %d argument(s); it takes %d", f.Name, t.name, boolInt(t.arg != nil), len(ownerParams(t.name)))
		}
	default:
		fail("%s names the type %s, which the table does not have", f.Name, t.name)
	}
	if t.arg != nil {
		f.checkType(t.arg)
	}
}

func boolInt(b bool) int {
	if b {
		return 1
	}
	return 0
}

func primOf(name string) *primType {
	for i := range primTypes {
		if primTypes[i].Key == name {
			return &primTypes[i]
		}
	}
	return nil
}

func enumOf(key string) *enumType {
	for i := range enumTypes {
		if enumTypes[i].Key == key {
			return &enumTypes[i]
		}
	}
	return nil
}

func unitOf(key string) *unit {
	for i := range units {
		if units[i].Key == key {
			return &units[i]
		}
	}
	return nil
}

// isOwner is whether name is a type the table declares and a method may belong to.
func isOwner(name string) bool {
	for _, b := range builtinTypes {
		if b.Key == name {
			return true
		}
	}
	for _, u := range unionTypes {
		if u.Key == name {
			return true
		}
	}
	for _, r := range recordTypes {
		if r.Key == name {
			return true
		}
	}
	return false
}

// field is a field of a built-in record.
type field struct {
	name           string
	ty             *tyExpr
	isVar, private bool
}

const (
	privateField = "private"
	varField     = "var"
	letField     = "let"
)

func parseField(s string) field {
	words := strings.Fields(s)
	var f field
	if len(words) > 0 && words[0] == privateField {
		f.private, words = true, words[1:]
	}
	if len(words) < 3 || (words[0] != varField && words[0] != letField) {
		fail("field %q is not '[private] var|let name Type'", s)
	}
	f.isVar, f.name, f.ty = words[0] == varField, words[1], parseType(strings.Join(words[2:], " "))
	return f
}

// fieldConst is the Go constant of the index of a field of a built-in record.
func fieldConst(r recordType, f field) string { return r.Key + upperFirst(f.name) + "Field" }

func ownerParams(name string) []string {
	for _, b := range builtinTypes {
		if b.Key == name {
			return b.Params
		}
	}
	for _, u := range unionTypes {
		if u.Key == name {
			return u.Params
		}
	}
	// A record of the table is not generic.
	return nil
}

func paramIndex(params []string, name string) int {
	for i, p := range params {
		if p == name {
			return i
		}
	}
	return -1
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

func upperFirst(s string) string { return strings.ToUpper(s[:1]) + s[1:] }

// codeEntries are the entries of a unit that the backend writes code for, in the order of the table.
func codeEntries(u unit) []entry {
	var out []entry
	for _, e := range entries {
		if e.Unit == u.Key && e.Role != roleGlobal {
			out = append(out, e)
		}
	}
	return out
}
