// Command builtingen generates, from the table in table.go, the declarations of minimaxon's built-ins in self/ and the record that holds their handles, the
// Intrinsic and runtime-symbol enums, and the dispatch from each intrinsic to its hand-written body in the checker and
// the interpreter. `go generate ./internal/builtingen` runs it.
package main

//go:generate go run .

import (
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

const (
	maxonFile           = "../../self/ast/builtins_gen.maxon"
	maxonRecordFile     = "../../self/ast/builtins_record_gen.maxon"
	maxonRtFile         = "../../self/ir/runtime_gen.maxon"
	maxonIntrinsicsFile = "../../self/ir/intrinsics_gen.maxon"
	maxonCheckFile      = "../../self/check/builtins_gen.maxon"
	maxonInterpFile     = "../../self/interp/builtins_gen.maxon"
	runtimeTextOpsFile  = "../../runtime/textops.maxon"
	interpTextOpsFile   = "../../self/interp/textops_gen.maxon"
	syntaxTextOpsFile   = "../../self/syntax/textops_gen.maxon"
	runtimeHashFoldFile = "../../runtime/hashfold.maxon"
	interpHashFoldFile  = "../../self/interp/hashfold_gen.maxon"

	header = "// Code generated by builtingen from internal/builtingen/table.go; DO NOT EDIT.\n\n"
)

type output struct {
	path string
	code []byte
}

func main() {
	outs, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "builtingen:", err)
		os.Exit(1)
	}
	for _, o := range outs {
		if err := os.WriteFile(o.path, o.code, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "builtingen:", err)
			os.Exit(1)
		}
	}
}

// tableError is a row of the table that the generator cannot make code of.
type tableError struct{ msg string }

func (e *tableError) Error() string { return e.msg }

func fail(format string, args ...any) {
	panic(&tableError{fmt.Sprintf(format, args...)})
}

func generate() (outs []output, err error) {
	defer func() {
		if r := recover(); r != nil {
			te, ok := r.(*tableError)
			if !ok {
				panic(r)
			}
			err = te
		}
	}()
	t := load()
	names, err := format.Source([]byte(emitConvert(t)))
	if err != nil {
		return nil, err
	}
	outs = append(outs, output{maxonFile, []byte(emitMaxon(t))}, output{maxonRecordFile, []byte(emitMaxonBuiltinsRecord(t))}, output{maxonRtFile, []byte(emitMaxonRt(t))}, output{maxonIntrinsicsFile, []byte(emitMaxonIntrinsics(t))}, output{maxonCheckFile, []byte(emitMaxonCheck(t))}, output{maxonInterpFile, []byte(emitMaxonInterp(t))}, output{interpTextOpsFile, []byte(emitSharedRuntime(runtimeTextOpsFile, "text operations"))}, output{syntaxTextOpsFile, []byte(emitSharedRuntime(runtimeTextOpsFile, "text operations"))}, output{interpHashFoldFile, []byte(emitSharedRuntime(runtimeHashFoldFile, "hash fold"))}, output{convertFile, names})
	return outs, nil
}

// tyExpr is a type as a signature in the table writes it: a name, given an argument when the name is generic.
type tyExpr struct {
	name string
	arg  *tyExpr
}

func parseType(s string) *tyExpr {
	name, rest, generic := strings.Cut(strings.TrimSpace(s), " with ")
	if name == "" || strings.Contains(name, " ") {
		fail("type %q is not a name or 'Name with Type'", s)
	}
	t := &tyExpr{name: name}
	if generic {
		t.arg = parseType(rest)
	}
	return t
}

// param is a parameter of a built-in: its convention, its name and its type.
type param struct {
	conv string // "let", "mutates" or "consumes"
	name string
	ty   *tyExpr
	// labelled is a parameter that a call names with its label even where it is the first, written "name:".
	labelled bool
	// mayOmitLabel is a parameter after the first that a call may name by its place too, written "name?": maxon's buffer
	// roster takes `set(i, v)` as well as `set(i, value: v)`.
	mayOmitLabel bool
	// defaultCase is the case of an enum parameter that a call leaving the argument out gives, written "= case", or "".
	defaultCase string
}

var conventions = []string{"let", "mutates", "consumes"}

func parseParam(s string) param {
	s, defaultCase, hasDefault := strings.Cut(s, " = ")
	if hasDefault && defaultCase == "" {
		fail("parameter %q has no default after '='", s)
	}
	p := parseSignature(s)
	p.defaultCase = defaultCase
	return p
}

func parseSignature(s string) param {
	fields := strings.SplitN(s, " ", 3)
	conv := "let"
	if len(fields) == 3 && isConvention(fields[0]) {
		conv, fields = fields[0], []string{fields[1], strings.Join(fields[2:], " ")}
	} else if len(fields) >= 2 {
		fields = []string{fields[0], strings.Join(fields[1:], " ")}
	}
	if len(fields) != 2 {
		fail("parameter %q is not 'convention name Type'", s)
	}
	name, labelled := strings.CutSuffix(fields[0], ":")
	name, mayOmitLabel := strings.CutSuffix(name, "?")
	if labelled && mayOmitLabel {
		fail("parameter %q is both labelled and unlabelled", s)
	}
	return param{conv: conv, name: name, ty: parseType(fields[1]), labelled: labelled, mayOmitLabel: mayOmitLabel}
}

func isConvention(s string) bool {
	return slices.Contains(conventions, s)
}

// bound is a type parameter and the capability it must have.
type bound struct{ param, iface string }

func parseBound(s string) bound {
	p, iface, ok := strings.Cut(s, " ")
	if !ok || !isCapability(iface) {
		fail("bound %q is not 'Param Capability' with a capability of %v", s, capabilities)
	}
	return bound{p, iface}
}

func isCapability(s string) bool {
	return slices.Contains(capabilities, s)
}

// fn is a function row with its signature parsed.
type fn struct {
	function
	params  []param
	result  *tyExpr
	generic string // the name of a free function's own type parameter
	gbound  string // the capability that parameter must have, or ""
	bounds  []bound
}

// intrinsic is one value of the Intrinsic enum, with what every row that lowers to it says about it.
type intrinsic struct {
	name                                           string
	checked, ownsOperands, runtimeOnly, mayOverlap bool
	// requires, count and measure are the columns of the same names, given by the rows of the intrinsic and, once they are
	// all read, the default where none gave one.
	requires, count, measure string
	// changesSelf is whether a row of the intrinsic mutates or consumes its receiver, which decides the default of count.
	changesSelf bool
}

type table struct {
	fns        []fn
	intrinsics []intrinsic
	// rtFuncs are the functions of the runtime's source, in the order of the entries they define.
	rtFuncs []rtFunc
}

func load() table {
	t := loadFunctions(functions)
	for _, name := range synthesizedIntrinsics {
		for _, in := range t.intrinsics {
			if in.name == name {
				fail("the synthesized intrinsic %s is also a row's", name)
			}
		}
		t.intrinsics = append(t.intrinsics, intrinsic{name: name, requires: requiresNone, count: countKeep, measure: measureNone})
	}
	for _, a := range typeAliases {
		fn{Name: a.Name}.checkType(parseType(a.Type))
	}
	for _, v := range views {
		owner, of := builtinTypeOf(v.Owner), builtinTypeOf(v.Type)
		if owner == nil || of == nil || len(owner.Params) == 0 || len(owner.Params) != len(of.Params) {
			fail("view %s.%s: a view is of a generic built-in type, as another built-in type of as many parameters", v.Owner, v.Name)
		}
	}
	for _, e := range entries {
		if unitOf(e.Unit) == nil {
			fail("entry %s is in unit %s, which the table does not have", e.Name, e.Unit)
		}
		if e.Role != roleCall && e.Role != roleInternal && e.Role != roleGlobal {
			fail("entry %s has the role %q", e.Name, e.Role)
		}
	}
	t.rtFuncs = loadRuntimeFunctions()
	return t
}

// loadFunctions parses the rows and makes the intrinsics of them, holding the rows to each other where they share an
// intrinsic or are each other's twins.
func loadFunctions(rows []function) table {
	var t table
	seen := map[string]int{}
	names := map[string]bool{}
	for _, f := range rows {
		if f.Throws != "" && enumOf(f.Throws) == nil {
			fail("%s throws %s, which is no enum row of the table", f.Name, f.Throws)
		}
		if f.Owner != "" && !isPrimOwner(f.Owner) && !isOwner(f.Owner) {
			fail("%s is a method of %s, which the table does not declare", f.Name, f.Owner)
		}
		key := f.Owner + "." + f.Name
		if (f.Self != "" && (!isConvention(f.Self) || f.Owner == "" || f.Static)) || (f.Static && f.Owner == "") {
			fail("%s: only a method takes its receiver %q, and only a method of a type is static", key, f.Self)
		}
		if names[key] && f.Field == "" {
			fail("%s is declared twice", key)
		}
		names[key] = true
		r := fn{function: f}
		for _, p := range f.Params {
			r.params = append(r.params, parseParam(p))
		}
		result := f.Result
		if result == "" {
			result = "Void"
		}
		r.result = parseType(result)
		if f.Generic != "" {
			if f.Owner != "" {
				fail("%s has a type parameter of its own; only a free function does", key)
			}
			r.generic, r.gbound, _ = strings.Cut(f.Generic, " ")
			if r.gbound != "" && !isCapability(r.gbound) {
				fail("%s: %s is no capability", key, r.gbound)
			}
		}
		for _, b := range f.Bounds {
			r.bounds = append(r.bounds, parseBound(b))
		}
		r.check()
		if rawCalls(f.Owner) != (f.Instead != "") || (f.Instead != "" && !f.Static) {
			fail("%s: a row names what a program calls instead exactly where it is a static function of a record whose calls are raw", key)
		}
		r.checkColumns()
		t.fns = append(t.fns, r)
		changesSelf := f.Self == "mutates" || f.Self == "consumes"
		if i, ok := seen[f.Intrinsic]; ok {
			in := &t.intrinsics[i]
			if in.checked != f.Checked || in.ownsOperands != f.OwnsOperands || in.runtimeOnly != f.RuntimeOnly || in.mayOverlap != f.MayOverlap {
				fail("the rows of intrinsic %s disagree on how it is checked or lowered, or where it may be called", f.Intrinsic)
			}
			in.requires = mergeColumn(f.Intrinsic, "Requires", in.requires, f.Requires)
			in.count = mergeColumn(f.Intrinsic, "Count", in.count, f.Count)
			in.measure = mergeColumn(f.Intrinsic, "Measure", in.measure, f.Measure)
			in.changesSelf = in.changesSelf || changesSelf
			checkSharedFailure(t.fns, f)
			continue
		}
		seen[f.Intrinsic] = len(t.intrinsics)
		t.intrinsics = append(t.intrinsics, intrinsic{name: f.Intrinsic, checked: f.Checked, ownsOperands: f.OwnsOperands, runtimeOnly: f.RuntimeOnly, mayOverlap: f.MayOverlap,
			requires: f.Requires, count: f.Count, measure: f.Measure, changesSelf: changesSelf})
	}
	for i := range t.intrinsics {
		t.intrinsics[i].resolveColumns()
	}
	t.checkTwins()
	return t
}

// mergeColumn is the value of a column of an intrinsic after one more of its rows: the rows that say it say the same.
func mergeColumn(intrinsicName, column, have, row string) string {
	switch {
	case row == "":
		return have
	case have == "" || have == row:
		return row
	}
	panic(&tableError{fmt.Sprintf("the rows of intrinsic %s disagree on %s: %s and %s", intrinsicName, column, have, row)})
}

// refinesCount is whether a twin's count effect says what its checked row's does, or says it exactly: where the checked
// row fails nothing changed, so shrink is true of both of its exits and the twin, which has only the success, shrinks by one.
func refinesCount(twin, checked string) bool {
	return twin == checked || (checked == countShrink && twin == countShrinkOne)
}

// resolveColumns gives a column that no row of the intrinsic said its default, and refuses a count effect on an intrinsic
// that no row calls on a receiver it may change.
func (in *intrinsic) resolveColumns() {
	if in.requires == "" {
		in.requires = requiresNone
	}
	if in.measure == "" {
		in.measure = measureNone
	}
	switch {
	case in.count == "" && in.changesSelf:
		in.count = countChange
	case in.count == "":
		in.count = countKeep
	case in.count != countKeep && !in.changesSelf:
		fail("intrinsic %s says it %s the count, and no row of it mutates or consumes its receiver", in.name, in.count)
	}
}

// checkColumns refuses a value that is no value of its column, and a column on a row that has nothing for it to describe.
func (f fn) checkColumns() {
	key := f.Owner + "." + f.Name
	for _, c := range []struct {
		name, value string
		values      []string
	}{{"Requires", f.Requires, requirements}, {"Count", f.Count, countEffects}, {"Measure", f.Measure, measures}} {
		if c.value != "" && !slices.Contains(c.values, c.value) {
			fail("%s: %s is %q, which is none of %v", key, c.name, c.value, c.values)
		}
	}
	hasReceiver := f.Owner != "" && !f.Static && !isPrimOwner(f.Owner)
	describesReceiver := f.Requires != "" || f.Count != "" || f.Measure != "" || f.Proven != ""
	if describesReceiver && !hasReceiver {
		fail("%s: Requires, Count, Measure and Proven describe a method of a type of the table on its receiver", key)
	}
	switch f.Requires {
	case requiresIndexBelow:
		if len(f.params) == 0 || f.params[0].ty.name != "ElementIndex" {
			fail("%s: Requires %s names argument 0, which is no ElementIndex", key, f.Requires)
		}
	case "", requiresNone, requiresNonEmpty:
	default:
		panic("builtingen: a requirement that checkColumns does not handle: " + f.Requires)
	}
	switch f.Measure {
	case measureCount:
		if len(f.params) != 0 || f.result.name != "Count" {
			fail("%s: Measure %s is a method with no arguments that gives a Count", key, f.Measure)
		}
	case measureIsEmpty:
		if len(f.params) != 0 || f.result.name != "Bool" {
			fail("%s: Measure %s is a method with no arguments that gives a Bool", key, f.Measure)
		}
	case "", measureNone:
	default:
		panic("builtingen: a measure that checkColumns does not handle: " + f.Measure)
	}
	if f.Proven != "" && f.Throws == "" {
		fail("%s: Proven names the row that cannot fail where this one can, and this one throws nothing", key)
	}
}

// provenCheckedField is the field of the Builtins record that holds the row that has a twin, which provenTwin looks it up
// by, as Field is for the twin.
func (f fn) provenCheckedField() string { return f.Owner + upperFirst(f.Name) }

// checkTwins holds each row that names its twin to what makes the twin a stand-in for it: the same method of the same type,
// taking and giving the same, that cannot fail, and the same fact needed and the same effect on the count.
func (t table) checkTwins() {
	intrinsicOf := func(name string) intrinsic {
		for _, in := range t.intrinsics {
			if in.name == name {
				return in
			}
		}
		panic("builtingen: a row names the intrinsic " + name + ", which no row declares")
	}
	for _, checked := range t.fns {
		if checked.Proven == "" {
			continue
		}
		key := checked.Owner + "." + checked.Name
		var twin *fn
		for i := range t.fns {
			if t.fns[i].Field != checked.Proven {
				continue
			}
			if twin != nil {
				fail("%s: Proven names the Field %s, which two rows have", key, checked.Proven)
			}
			twin = &t.fns[i]
		}
		if twin == nil {
			fail("%s: Proven names the Field %s, which no row has", key, checked.Proven)
		}
		same := twin.Owner == checked.Owner && twin.Name == checked.Name && twin.Self == checked.Self && twin.Static == checked.Static &&
			slices.Equal(twin.Params, checked.Params) && twin.Result == checked.Result && slices.Equal(twin.Bounds, checked.Bounds)
		if !same {
			fail("%s: its twin %s differs in its owner, name, receiver, parameters, result or bounds", key, checked.Proven)
		}
		if twin.Throws != "" {
			fail("%s: its twin %s throws, which a twin that cannot fail does not", key, checked.Proven)
		}
		want, got := intrinsicOf(checked.Intrinsic), intrinsicOf(twin.Intrinsic)
		if want.requires == requiresNone {
			fail("%s: it has a twin and Requires nothing for the twin to rely on", key)
		}
		if want.requires != got.requires || !refinesCount(got.count, want.count) {
			fail("%s: its twin %s needs %s and has the count effect %s, where it needs %s and has %s", key, checked.Proven, got.requires, got.count, want.requires, want.count)
		}
	}
}

// primOwners are the Owners of methods of a primitive, which is no type the table declares, each with the lowerCamelCase
// prefix of its Builtins fields: the type (stringTy) and the methods (stringMethods).
var primOwners = map[string]string{"String": "string", "Character": "character"}

// isPrimOwner is whether owner is a primitive's.
func isPrimOwner(owner string) bool {
	_, ok := primOwners[owner]
	return ok
}

// checkSharedFailure holds the rows that lower to one intrinsic and throw different enums to enums whose shared cases have
// the same indexes, since the lowering fails with a case's index and knows nothing of the row.
func checkSharedFailure(fns []fn, f function) {
	thrown := enumOf(f.Throws)
	for _, other := range fns {
		if other.Intrinsic != f.Intrinsic || other.Throws == f.Throws {
			continue
		}
		was := enumOf(other.Throws)
		if thrown == nil || was == nil {
			fail("the rows of intrinsic %s disagree on whether it throws", f.Intrinsic)
		}
		for i := range min(len(thrown.Cases), len(was.Cases)) {
			if thrown.Cases[i].Name != was.Cases[i].Name {
				fail("the rows of intrinsic %s throw %s and %s, whose case %d differs", f.Intrinsic, f.Throws, other.Throws, i)
			}
		}
	}
}

// rawCalls is whether owner is a record of the table whose static functions are raw intrinsics.
func rawCalls(owner string) bool {
	for _, r := range recordTypes {
		if r.Key == owner {
			return r.RawCalls
		}
	}
	return false
}

func builtinTypeOf(key string) *builtinType {
	for i := range builtinTypes {
		if builtinTypes[i].Key == key {
			return &builtinTypes[i]
		}
	}
	return nil
}

// check refuses a signature that names a type the row cannot see.
func (f fn) check() {
	for _, p := range f.params {
		f.checkType(p.ty)
		if p.defaultCase != "" {
			f.checkDefault(p)
		}
	}
	f.checkType(f.result)
	for _, b := range f.bounds {
		if paramIndex(ownerParams(f.Owner), b.param) < 0 {
			fail("%s bounds %s, which is no parameter of %s", f.Name, b.param, f.Owner)
		}
	}
}

// checkDefault holds a default to a case of an enum row that the parameter takes by let.
func (f fn) checkDefault(p param) {
	e := enumOf(p.ty.name)
	if e == nil || p.ty.arg != nil || p.conv != "let" {
		fail("%s: the parameter %s has a default, which only a let parameter of an enum row of the table may", f.Name, p.name)
	}
	if defaultIndex(p) < 0 {
		fail("%s: the default of %s is %s, which is no case of %s", f.Name, p.name, p.defaultCase, e.Name)
	}
}

// defaultIndex is the index of the case a parameter's default names in its enum row, or -1.
func defaultIndex(p param) int {
	return slices.IndexFunc(enumOf(p.ty.name).Cases, func(c enumCase) bool { return c.Name == p.defaultCase })
}

func (f fn) checkType(t *tyExpr) {
	switch {
	case t.name == "Self":
		if f.Owner == "" || isPrimOwner(f.Owner) {
			fail("%s names Self, and has no owner of its own", f.Name)
		}
	case t.name == f.generic || paramIndex(ownerParams(f.Owner), t.name) >= 0 || primOf(t.name) != nil:
	case isOwner(t.name):
		if (t.arg != nil) != (len(ownerParams(t.name)) == 1) {
			fail("%s writes %s with %d argument(s); it takes %d", f.Name, t.name, boolInt(t.arg != nil), len(ownerParams(t.name)))
		}
	default:
		fail("%s names the type %s, which the table does not have", f.Name, t.name)
	}
	if t.arg != nil {
		f.checkType(t.arg)
	}
}

func boolInt(b bool) int {
	if b {
		return 1
	}
	return 0
}

func primOf(name string) *primType {
	for i := range primTypes {
		if primTypes[i].Key == name {
			return &primTypes[i]
		}
	}
	return nil
}

func enumOf(key string) *enumType {
	for i := range enumTypes {
		if enumTypes[i].Key == key {
			return &enumTypes[i]
		}
	}
	return nil
}

func unitOf(key string) *unit {
	for i := range units {
		if units[i].Key == key {
			return &units[i]
		}
	}
	return nil
}

// isOwner is whether name is a type the table declares and a method may belong to.
func isOwner(name string) bool {
	for _, b := range builtinTypes {
		if b.Key == name {
			return true
		}
	}
	for _, u := range unionTypes {
		if u.Key == name {
			return true
		}
	}
	for _, r := range recordTypes {
		if r.Key == name {
			return true
		}
	}
	return enumOf(name) != nil
}

// field is a field of a built-in record.
type field struct {
	name           string
	ty             *tyExpr
	isVar, private bool
}

const (
	privateField = "private"
	varField     = "var"
	letField     = "let"
)

func parseField(s string) field {
	words := strings.Fields(s)
	var f field
	if len(words) > 0 && words[0] == privateField {
		f.private, words = true, words[1:]
	}
	if len(words) < 3 || (words[0] != varField && words[0] != letField) {
		fail("field %q is not '[private] var|let name Type'", s)
	}
	f.isVar, f.name, f.ty = words[0] == varField, words[1], parseType(strings.Join(words[2:], " "))
	return f
}

// fieldConst is the constant of the index of a field of a built-in record.
func fieldConst(r recordType, f field) string { return r.Key + upperFirst(f.name) + "Field" }

func ownerParams(name string) []string {
	for _, b := range builtinTypes {
		if b.Key == name {
			return b.Params
		}
	}
	for _, u := range unionTypes {
		if u.Key == name {
			return u.Params
		}
	}
	// A record of the table is not generic.
	return nil
}

func paramIndex(params []string, name string) int {
	for i, p := range params {
		if p == name {
			return i
		}
	}
	return -1
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

func upperFirst(s string) string { return strings.ToUpper(s[:1]) + s[1:] }

// codeEntries are the entries of a unit that the backend writes code for, in the order of the table.
func codeEntries(u unit) []entry {
	var out []entry
	for _, e := range entries {
		if e.Unit == u.Key && e.Role != roleGlobal {
			out = append(out, e)
		}
	}
	return out
}

// runtimeLinkPath is the module part of the link name of a function of the runtime's source, as ast.Module.LinkPath
// gives it; `minimaxon check runtime` fails if the two differ.
const runtimeLinkPath = "runtime"

// rtFunc is a runtimeFunction row with its signature parsed. A function that returns nothing has the result Void.
type rtFunc struct {
	entry  entry
	name   string
	params []param
	result *tyExpr
}

func (r rtFunc) symbol() string { return runtimeLinkPath + "::" + r.name }

// loadRuntimeFunctions parses the runtimeFunctions rows, in the order of the entries. An entry the runtime's source
// defines is called by the compiler's own code (internal) or by the IR (call); a global is the entry stub's or the
// linker's.
func loadRuntimeFunctions() []rtFunc {
	byEntry := map[string]runtimeFunction{}
	for _, r := range runtimeFunctions {
		if _, twice := byEntry[r.Entry]; twice {
			fail("entry %s has two runtime functions", r.Entry)
		}
		byEntry[r.Entry] = r
	}
	var out []rtFunc
	for _, e := range entries {
		r, ok := byEntry[e.Name]
		if !ok {
			continue
		}
		delete(byEntry, e.Name)
		if e.Role == roleGlobal {
			fail("entry %s is a global, which no function defines", e.Name)
		}
		out = append(out, parseRuntimeFunction(e, r.Sig))
	}
	for _, r := range runtimeFunctions {
		if _, left := byEntry[r.Entry]; left {
			fail("runtime function %q names the entry %s, which the table does not have", r.Sig, r.Entry)
		}
	}
	return out
}

func parseRuntimeFunction(e entry, sig string) rtFunc {
	open, close := strings.Index(sig, "("), strings.LastIndex(sig, ")")
	if open <= 0 || close < open {
		fail("runtime function %q is not 'name(param Type, ...) Result'", sig)
	}
	r := rtFunc{entry: e, name: sig[:open], result: parseType("Void")}
	if inner := strings.TrimSpace(sig[open+1 : close]); inner != "" {
		for p := range strings.SplitSeq(inner, ",") {
			r.params = append(r.params, parseParam(strings.TrimSpace(p)))
		}
	}
	if result := strings.TrimSpace(sig[close+1:]); result != "" {
		r.result = parseType(result)
	}
	for _, p := range r.params {
		if p.conv == "mutates" {
			fail("runtime function %q takes %s mutates: the compiler passes an entry values, never places", sig, p.name)
		}
	}
	for _, p := range append(r.params, param{ty: r.result}) {
		if primOf(p.ty.name) == nil || p.ty.arg != nil {
			fail("runtime function %q names %s: a runtime function takes and gives only words, of a type of primTypes", sig, p.ty.name)
		}
	}
	return r
}

// symbolOf is the symbol self links an entry by: the link name of the runtime's function that defines it, or the
// entry's own symbol for one that the entry stub or the linker defines.
func (t table) symbolOf(e entry) string {
	for _, r := range t.rtFuncs {
		if r.entry.Name == e.Name {
			return r.symbol()
		}
	}
	return e.Symbol
}
