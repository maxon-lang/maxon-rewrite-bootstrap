package main

import (
	"fmt"
	"slices"
	"strings"

	"minimaxon/internal/irgen/irtable"
)

const genericHeader = "// Code generated by rulegen from internal/rulegen/generic.rules and pressure.rules; DO NOT EDIT.\n\n"

// The parameters of every generated function: the function, the instruction it rewrites, the defining instruction of
// each register, and what the instruction is rewritten to.
const (
	ruleParams = "mutates fn ir.IrFunction, at Count, defs ir.Defs, mutates out Rewrite"
	ruleArgs   = "fn, at: at, defs: defs, out: out"
	// The dispatching functions also take whether the rules that may raise register pressure apply.
	dispatchParams = ruleParams + ", raises bool"
	dispatchArgs   = ruleArgs + ", raises: raises"
)

// ruleSet is the checked rules of one file, and whether they may raise register pressure.
type ruleSet struct {
	file   string
	raises bool
	rules  []checked
}

// emitGeneric writes the matcher: rewriteInstr dispatches on the opcode to the function of each operation that has
// rules, which tries the rules of each set in the order of its file, the sets in order and those that raise register
// pressure only where raises, each a function that returns false at the first thing that does not match; mayRaise says
// which instructions those rules can match at all.
func emitGeneric(sets []ruleSet) string {
	var b strings.Builder
	b.WriteString(genericHeader)
	var withRules []irtable.Op
	for _, o := range irtable.Ops {
		if !o.Term && slices.ContainsFunc(sets, func(s ruleSet) bool {
			return slices.ContainsFunc(s.rules, func(c checked) bool { return c.r.match.op.Name == o.Name })
		}) {
			withRules = append(withRules, o)
		}
	}
	b.WriteString("// rewriteInstr applies to the instruction at of fn the first rule of generic.rules that matches it, or with raises of\n")
	b.WriteString("// pressure.rules, and says whether one did; out then holds what the instruction is rewritten to.\n")
	fmt.Fprintf(&b, "export function rewriteInstr(%s) returns bool\n", dispatchParams)
	b.WriteString("\tlet op = fn.instrs[at].op\n")
	for _, o := range irtable.Ops {
		if o.Term {
			continue
		}
		c := "opcode" + o.Name
		fmt.Fprintf(&b, "\tif op == ir.Opcode.op%s '%s'\n", o.Name, c)
		if slices.ContainsFunc(withRules, func(w irtable.Op) bool { return w.Name == o.Name }) {
			fmt.Fprintf(&b, "\t\treturn rewrite%s(%s)\n", o.Name, dispatchArgs)
		} else {
			b.WriteString("\t\treturn false\n")
		}
		fmt.Fprintf(&b, "\tend '%s'\n", c)
	}
	b.WriteString("\tpanic(\"opt: an instruction with no opcode\")\nend 'rewriteInstr'\n")
	for _, o := range withRules {
		name := "rewrite" + o.Name
		fmt.Fprintf(&b, "\n// %s applies the rules of %s.\nfunction %s(%s) returns bool\n", name, lowerFirst(o.Name), name, dispatchParams)
		for _, s := range sets {
			indent := "\t"
			opened := false
			for _, c := range s.rules {
				if c.r.match.op.Name != o.Name {
					continue
				}
				if s.raises && !opened {
					b.WriteString("\tif raises 'raises'\n")
					indent, opened = "\t\t", true
				}
				for i := range c.variants {
					fn := setVariantName(s, c, i)
					fmt.Fprintf(&b, "%sif %s(%s) '%s'\n%s\treturn true\n%send '%s'\n", indent, fn, ruleArgs, fn, indent, indent, fn)
				}
			}
			if opened {
				b.WriteString("\tend 'raises'\n")
			}
		}
		fmt.Fprintf(&b, "\treturn false\nend '%s'\n", name)
	}
	emitMayRaise(&b, sets)
	for _, s := range sets {
		for _, c := range s.rules {
			for i, v := range c.variants {
				emitRule(&b, s, c, i, v)
			}
		}
	}
	return b.String()
}

// emitMayRaise writes mayRaise, whether an instruction has the operation and the case of a rule that may raise register
// pressure, so that a caller asks the rules of those only of a function that holds one.
func emitMayRaise(b *strings.Builder, sets []ruleSet) {
	b.WriteString("\n// mayRaise is whether a rule of pressure.rules, which may raise register pressure, could match x: x has the operation\n")
	b.WriteString("// and the case of one.\nexport function mayRaise(x ir.Instr) returns bool\n")
	seen := map[string]bool{}
	n := 0
	for _, s := range sets {
		if !s.raises {
			continue
		}
		for _, c := range s.rules {
			t := c.r.match
			test := "x.op == ir.Opcode.op" + t.op.Name
			if t.cas != "" {
				x, _ := enumOperand(t.op)
				en := enumOf(x.Enum)
				test += fmt.Sprintf(" and %s(x) == ir.%s.%s%s", getter(t.op, x), en.Name, lowerFirst(en.Prefix), t.cas)
			}
			if seen[test] {
				continue
			}
			seen[test] = true
			n++
			fmt.Fprintf(b, "\tif %s 'case%d'\n\t\treturn true\n\tend 'case%d'\n", test, n, n)
		}
	}
	b.WriteString("\treturn false\nend 'mayRaise'\n")
}

func variantName(c checked, i int) string {
	if i == 0 {
		return fmt.Sprintf("rule%d", c.r.line)
	}
	return fmt.Sprintf("rule%dv%d", c.r.line, i+1)
}

// setVariantName is the function of the i-th variant of a rule of a set: the rules that may raise register pressure have
// their own prefix, since two files can have a rule on the same line.
func setVariantName(s ruleSet, c checked, i int) string {
	if s.raises {
		return "raising" + upperFirst(variantName(c, i))
	}
	return variantName(c, i)
}

// ruleEmitter writes the function of one variant of a rule.
type ruleEmitter struct {
	b      *strings.Builder
	r      *rule
	vars   map[string]*binding
	bound  map[string]bool
	labels int
	temps  int
	// made is the local of each register that a result binds, once its instruction is built.
	made map[string]string
	// tg is the target of the rules, which says how the matcher reads the instruction that defines a register.
	tg target
}

// local is the Maxon local of a variable, which no name of the generated code has.
func local(name string) string { return "v" + upperFirst(name) }

func emitRule(b *strings.Builder, s ruleSet, c checked, i int, v *term) {
	r := c.r
	fn := setVariantName(s, c, i)
	fmt.Fprintf(b, "\n// %s:%d: %s\n", s.file, r.line, r.text)
	if i > 0 {
		fmt.Fprintf(b, "// with the operands swapped: %s\n", v)
	}
	fmt.Fprintf(b, "function %s(%s) returns bool\n", fn, ruleParams)
	e := &ruleEmitter{b: b, r: r, vars: map[string]*binding{}, bound: map[string]bool{}, tg: genericTarget, made: map[string]string{}}
	checkMatch(r, v, e.vars, true, genericTarget)
	e.matchRoot(v, "fn.instrs[at]")
	b.WriteString("\tout.pre.clear()\n")
	res := r.results[0]
	switch res.kind {
	case termVar:
		b.WriteString("\tout.kind = RewriteKind.rewriteToReg\n")
		fmt.Fprintf(b, "\tout.reg = %s\n", local(res.name))
	case termOp:
		dst := ""
		if res.op.Result != irtable.NoResult {
			b.WriteString("\tlet dst = fn.instrs[at].dst\n")
			dst = "dst"
		}
		fmt.Fprintf(b, "\tout.instr = %s\n", e.build(res, dst))
		b.WriteString("\tout.kind = RewriteKind.rewriteToInstr\n")
	case termWild, termAux:
		panic("rulegen: a checked rule rewrites to " + res.String())
	default:
		panic(fmt.Sprintf("rulegen: a term of kind %d", res.kind))
	}
	fmt.Fprintf(b, "\treturn true\nend '%s'\n", fn)
}

func (e *ruleEmitter) line(format string, args ...any) {
	e.b.WriteString("\t" + fmt.Sprintf(format, args...) + "\n")
}

// reject returns false when cond holds.
func (e *ruleEmitter) reject(cond string) {
	e.labels++
	l := fmt.Sprintf("m%d", e.labels)
	e.line("if %s '%s'", cond, l)
	e.line("\treturn false")
	e.line("end '%s'", l)
}

func (e *ruleEmitter) temp(prefix string) string {
	e.temps++
	return fmt.Sprintf("%s%d", prefix, e.temps)
}

// bindOrCompare binds a variable to the value of expr where the pattern first names it, and elsewhere asks that the value
// be the same.
func (e *ruleEmitter) bindOrCompare(name, expr string) {
	if e.bound[name] {
		e.reject(expr + " != " + local(name))
		return
	}
	e.bound[name] = true
	e.line("let %s = %s", local(name), expr)
}

func getter(o irtable.Op, x irtable.Operand) string { return "ir." + lowerFirst(o.Name) + x.Name }

// matchRoot matches the instruction instr, whose opcode is already the pattern's, against the rest of the pattern
// and the rule's condition.
func (e *ruleEmitter) matchRoot(v *term, instr string) {
	if v.bind != "" {
		e.bindOrCompare(v.bind, instr+".dst")
	}
	e.matchOp(v, instr)
	if e.r.cond != "" {
		e.reject("not (" + rewriteExpr(e.r, e.r.cond, e.vars, local, e.tg.selects()) + ")")
	}
}

// matchOp matches the instruction instr, whose opcode is already t's, against the rest of t.
func (e *ruleEmitter) matchOp(t *term, instr string) {
	o := t.op
	if t.cas != "" {
		x, _ := enumOperand(o)
		en := enumOf(x.Enum)
		e.reject(fmt.Sprintf("%s(%s) != ir.%s.%s%s", getter(o, x), instr, en.Name, lowerFirst(en.Prefix), t.cas))
	}
	for _, x := range o.Operands {
		set, ok := t.flags[x.Flag]
		if x.Flag == "" || !ok {
			continue
		}
		has := getter(o, x) + "(" + instr + ")"
		if x.Kind != irtable.KFlag {
			has = "ir." + lowerFirst(o.Name) + "Has" + x.Name + "(" + instr + ")"
		}
		if set {
			has = "not " + has
		}
		e.reject(has)
	}
	pos := positionals(o)
	for i, a := range t.args {
		x := pos[i]
		if x.Kind == irtable.KReg {
			e.matchReg(a, getter(o, x)+"("+instr+")")
			continue
		}
		e.matchAux(a, auxRead(o, x, instr))
	}
}

func (e *ruleEmitter) matchReg(a *term, expr string) {
	switch a.kind {
	case termWild:
	case termVar:
		e.bindOrCompare(a.name, expr)
	case termOp:
		reg := e.temp("reg")
		e.line("let %s = %s", reg, expr)
		if a.bind != "" {
			e.bindOrCompare(a.bind, reg)
		}
		def := e.temp("def")
		if e.tg.selects() {
			e.reject(fmt.Sprintf("not sel.definedBy(fn, r: %s, op: ir.Opcode.op%s)", reg, a.op.Name))
			e.line("let %s = sel.defOf(%s)", def, reg)
		} else {
			e.reject(fmt.Sprintf("not definedBy(fn, defs: defs, r: %s, op: ir.Opcode.op%s)", reg, a.op.Name))
			e.line("let %s = defOf(defs, r: %s)", def, reg)
		}
		e.matchOp(a, "fn.instrs["+def+"]")
	case termAux:
		panic("rulegen: a register matched by " + a.String())
	default:
		panic(fmt.Sprintf("rulegen: a term of kind %d", a.kind))
	}
}

func (e *ruleEmitter) matchAux(a *term, expr string) {
	switch {
	case a.text == "_":
	case number.MatchString(a.text):
		e.reject(expr + " != " + a.text)
	default:
		e.bindOrCompare(a.text, expr)
	}
}

// auxRead is the value of an operand that is no register, as a constructor of the operation takes it: a pool's index
// rather than what the pool holds there.
func auxRead(o irtable.Op, x irtable.Operand, instr string) string {
	switch x.Kind {
	case irtable.KInt, irtable.KSlot, irtable.KWord, irtable.KSymbol, irtable.KBody, irtable.KDatum, irtable.KFrameBox, irtable.KBlock:
		return getter(o, x) + "(" + instr + ")"
	case irtable.KFail:
		return instr + "." + string(x.Field) + " as ir.BlockID"
	case irtable.KText, irtable.KType, irtable.KCallee, irtable.KTable:
		return instr + "." + string(x.Field)
	case irtable.KReg, irtable.KRegs, irtable.KMoreRegs, irtable.KEnum, irtable.KFlag, irtable.KRoutine, irtable.KErrorReg, irtable.KCases, irtable.KEdgeArgs, irtable.KMoreEdgeArgs, irtable.KFloats:
		panic("rulegen: no pattern reads the operand " + x.Name)
	}
	panic(fmt.Sprintf("rulegen: an operand of kind %d", x.Kind))
}

// absent is what a constructor takes for an optional operand that a result leaves out.
func absent(x irtable.Operand) string {
	switch x.Kind {
	case irtable.KFail:
		return "ir.noBlock"
	case irtable.KErrorReg:
		return "ir.noReg"
	case irtable.KRoutine:
		return "ir.noRoutine"
	}
	panic("rulegen: an operand that cannot be absent: " + x.Name)
}

// build is the constructor call of a result's operation, after the instructions of its nested operations, each of which
// defines a new register, are pushed to out.pre.
func (e *ruleEmitter) build(t *term, dst string) string {
	o := t.op
	pos := positionals(o)
	var args []string
	if dst != "" {
		args = append(args, dst)
	}
	at := 0
	for _, x := range o.Operands {
		var v string
		switch x.Kind {
		case irtable.KEdgeArgs, irtable.KMoreEdgeArgs:
			panic("rulegen: a result builds the terminator " + o.Name + ", whose edges carry arguments")
		case irtable.KFloats:
			panic("rulegen: a result builds the call " + o.Name + ", whose float signature its function's pool holds")
		case irtable.KEnum:
			en := enumOf(x.Enum)
			v = "ir." + en.Name + "." + lowerFirst(en.Prefix) + t.cas
		case irtable.KFlag:
			v = fmt.Sprint(t.flags[x.Flag])
		default:
			if pos[at].Name != x.Name {
				panic("rulegen: the positional operands are out of step at " + x.Name)
			}
			switch {
			case at >= len(t.args):
				v = absent(x)
			case x.Kind == irtable.KReg:
				v = e.buildReg(t.args[at])
			default:
				v = rewriteExpr(e.r, t.args[at].text, e.vars, local, false)
			}
			at++
		}
		if len(args) > 0 {
			v = lowerFirst(x.Name) + ": " + v
		}
		args = append(args, v)
	}
	return "ir.new" + o.Name + "(" + strings.Join(args, ", ") + ")"
}

func (e *ruleEmitter) buildReg(a *term) string {
	switch a.kind {
	case termVar:
		if n, ok := e.made[a.name]; ok {
			return n
		}
		return local(a.name)
	case termOp:
		n := e.temp("new")
		ctor := e.build(a, n)
		e.line("let %s = fn.newReg(ir.IrKind.kindScalar)", n)
		e.line("out.pre.push(%s)", ctor)
		if a.bind != "" {
			e.made[a.bind] = n
		}
		return n
	case termWild, termAux:
		panic("rulegen: a register built from " + a.String())
	}
	panic(fmt.Sprintf("rulegen: a term of kind %d", a.kind))
}
