package main

import (
	"fmt"
	"slices"
	"strings"

	"minimaxon/internal/irgen/irtable"
)

const genericHeader = "// Code generated by rulegen from internal/rulegen/generic.rules; DO NOT EDIT.\n\n"

// The parameters of every generated function: the function, the instruction it rewrites, the defining instruction of
// each register, and what the instruction is rewritten to.
const (
	ruleParams = "mutates fn ir.IrFunction, at Count, defs ir.Defs, mutates out Rewrite"
	ruleArgs   = "fn, at: at, defs: defs, out: out"
)

// emitGeneric writes the matcher: rewriteInstr dispatches on the opcode to the function of each operation that has
// rules, which tries the rules in the order of the file, each a function that returns false at the first thing that does
// not match.
func emitGeneric(file string, rules []checked) string {
	var b strings.Builder
	b.WriteString(genericHeader)
	var withRules []irtable.Op
	for _, o := range irtable.Ops {
		if !o.Term && slices.ContainsFunc(rules, func(c checked) bool { return c.r.match.op.Name == o.Name }) {
			withRules = append(withRules, o)
		}
	}
	b.WriteString("// rewriteInstr applies to the instruction at of fn the first rule of generic.rules that matches it, and says whether\n")
	b.WriteString("// one did; out then holds what the instruction is rewritten to.\n")
	fmt.Fprintf(&b, "export function rewriteInstr(%s) returns bool\n", ruleParams)
	b.WriteString("\tlet op = fn.instrs[at].op\n")
	for _, o := range irtable.Ops {
		if o.Term {
			continue
		}
		c := "opcode" + o.Name
		fmt.Fprintf(&b, "\tif op == ir.Opcode.op%s '%s'\n", o.Name, c)
		if slices.ContainsFunc(withRules, func(w irtable.Op) bool { return w.Name == o.Name }) {
			fmt.Fprintf(&b, "\t\treturn rewrite%s(%s)\n", o.Name, ruleArgs)
		} else {
			b.WriteString("\t\treturn false\n")
		}
		fmt.Fprintf(&b, "\tend '%s'\n", c)
	}
	b.WriteString("\tpanic(\"opt: an instruction with no opcode\")\nend 'rewriteInstr'\n")
	for _, o := range withRules {
		name := "rewrite" + o.Name
		fmt.Fprintf(&b, "\n// %s applies the rules of %s.\nfunction %s(%s) returns bool\n", name, lowerFirst(o.Name), name, ruleParams)
		for _, c := range rules {
			if c.r.match.op.Name != o.Name {
				continue
			}
			for i := range c.variants {
				fn := variantName(c, i)
				fmt.Fprintf(&b, "\tif %s(%s) '%s'\n\t\treturn true\n\tend '%s'\n", fn, ruleArgs, fn, fn)
			}
		}
		fmt.Fprintf(&b, "\treturn false\nend '%s'\n", name)
	}
	for _, c := range rules {
		for i, v := range c.variants {
			emitRule(&b, file, c, i, v)
		}
	}
	return b.String()
}

func variantName(c checked, i int) string {
	if i == 0 {
		return fmt.Sprintf("rule%d", c.r.line)
	}
	return fmt.Sprintf("rule%dv%d", c.r.line, i+1)
}

// ruleEmitter writes the function of one variant of a rule.
type ruleEmitter struct {
	b      *strings.Builder
	r      *rule
	vars   map[string]*binding
	bound  map[string]bool
	labels int
	temps  int
}

// local is the Maxon local of a variable, which no name of the generated code has.
func local(name string) string { return "v" + upperFirst(name) }

func emitRule(b *strings.Builder, file string, c checked, i int, v *term) {
	r := c.r
	fn := variantName(c, i)
	fmt.Fprintf(b, "\n// %s:%d: %s\n", file, r.line, r.text)
	if i > 0 {
		fmt.Fprintf(b, "// with the operands swapped: %s\n", v)
	}
	fmt.Fprintf(b, "function %s(%s) returns bool\n", fn, ruleParams)
	e := &ruleEmitter{b: b, r: r, vars: map[string]*binding{}, bound: map[string]bool{}}
	checkMatch(r, v, e.vars, true, genericTarget)
	if v.bind != "" {
		e.bindOrCompare(v.bind, "fn.instrs[at].dst")
	}
	e.matchOp(v, "at")
	if r.cond != "" {
		e.reject("not (" + rewriteExpr(r, r.cond, e.vars, local) + ")")
	}
	b.WriteString("\tout.pre.clear()\n")
	res := r.results[0]
	switch res.kind {
	case termVar:
		b.WriteString("\tout.kind = RewriteKind.rewriteToReg\n")
		fmt.Fprintf(b, "\tout.reg = %s\n", local(res.name))
	case termOp:
		dst := ""
		if res.op.Result != irtable.NoResult {
			b.WriteString("\tlet dst = fn.instrs[at].dst\n")
			dst = "dst"
		}
		fmt.Fprintf(b, "\tout.instr = %s\n", e.build(res, dst))
		b.WriteString("\tout.kind = RewriteKind.rewriteToInstr\n")
	case termWild, termAux:
		panic("rulegen: a checked rule rewrites to " + res.String())
	default:
		panic(fmt.Sprintf("rulegen: a term of kind %d", res.kind))
	}
	fmt.Fprintf(b, "\treturn true\nend '%s'\n", fn)
}

func (e *ruleEmitter) line(format string, args ...any) {
	e.b.WriteString("\t" + fmt.Sprintf(format, args...) + "\n")
}

// reject returns false when cond holds.
func (e *ruleEmitter) reject(cond string) {
	e.labels++
	l := fmt.Sprintf("m%d", e.labels)
	e.line("if %s '%s'", cond, l)
	e.line("\treturn false")
	e.line("end '%s'", l)
}

func (e *ruleEmitter) temp(prefix string) string {
	e.temps++
	return fmt.Sprintf("%s%d", prefix, e.temps)
}

// bindOrCompare binds a variable to the value of expr where the pattern first names it, and elsewhere asks that the value
// be the same.
func (e *ruleEmitter) bindOrCompare(name, expr string) {
	if e.bound[name] {
		e.reject(expr + " != " + local(name))
		return
	}
	e.bound[name] = true
	e.line("let %s = %s", local(name), expr)
}

func getter(o irtable.Op, x irtable.Operand) string { return "ir." + lowerFirst(o.Name) + x.Name }

// matchOp matches the instruction fn.instrs[idx], whose opcode is already t's, against the rest of t.
func (e *ruleEmitter) matchOp(t *term, idx string) {
	o := t.op
	instr := "fn.instrs[" + idx + "]"
	if t.cas != "" {
		x, _ := enumOperand(o)
		en := enumOf(x.Enum)
		e.reject(fmt.Sprintf("%s(%s) != ir.%s.%s%s", getter(o, x), instr, en.Name, lowerFirst(en.Prefix), t.cas))
	}
	for _, x := range o.Operands {
		set, ok := t.flags[x.Flag]
		if x.Flag == "" || !ok {
			continue
		}
		has := getter(o, x) + "(" + instr + ")"
		if x.Kind != irtable.KFlag {
			has = "ir." + lowerFirst(o.Name) + "Has" + x.Name + "(" + instr + ")"
		}
		if set {
			has = "not " + has
		}
		e.reject(has)
	}
	pos := positionals(o)
	for i, a := range t.args {
		x := pos[i]
		if x.Kind == irtable.KReg {
			e.matchReg(a, getter(o, x)+"("+instr+")")
			continue
		}
		e.matchAux(a, auxRead(o, x, instr))
	}
}

func (e *ruleEmitter) matchReg(a *term, expr string) {
	switch a.kind {
	case termWild:
	case termVar:
		e.bindOrCompare(a.name, expr)
	case termOp:
		reg := e.temp("reg")
		e.line("let %s = %s", reg, expr)
		if a.bind != "" {
			e.bindOrCompare(a.bind, reg)
		}
		e.reject(fmt.Sprintf("not definedBy(fn, defs: defs, r: %s, op: ir.Opcode.op%s)", reg, a.op.Name))
		def := e.temp("def")
		e.line("let %s = defOf(defs, r: %s)", def, reg)
		e.matchOp(a, def)
	case termAux:
		panic("rulegen: a register matched by " + a.String())
	default:
		panic(fmt.Sprintf("rulegen: a term of kind %d", a.kind))
	}
}

func (e *ruleEmitter) matchAux(a *term, expr string) {
	switch {
	case a.text == "_":
	case number.MatchString(a.text):
		e.reject(expr + " != " + a.text)
	default:
		e.bindOrCompare(a.text, expr)
	}
}

// auxRead is the value of an operand that is no register, as a constructor of the operation takes it: a pool's index
// rather than what the pool holds there.
func auxRead(o irtable.Op, x irtable.Operand, instr string) string {
	switch x.Kind {
	case irtable.KInt, irtable.KSlot, irtable.KWord, irtable.KSymbol, irtable.KBody, irtable.KBlock:
		return getter(o, x) + "(" + instr + ")"
	case irtable.KFail:
		return instr + "." + string(x.Field) + " as ir.BlockID"
	case irtable.KText, irtable.KType, irtable.KCallee, irtable.KTable:
		return instr + "." + string(x.Field)
	case irtable.KReg, irtable.KRegs, irtable.KMoreRegs, irtable.KEnum, irtable.KFlag, irtable.KRoutine, irtable.KErrorReg, irtable.KCases, irtable.KEdgeArgs, irtable.KMoreEdgeArgs:
		panic("rulegen: no pattern reads the operand " + x.Name)
	}
	panic(fmt.Sprintf("rulegen: an operand of kind %d", x.Kind))
}

// absent is what a constructor takes for an optional operand that a result leaves out.
func absent(x irtable.Operand) string {
	switch x.Kind {
	case irtable.KFail:
		return "ir.noBlock"
	case irtable.KErrorReg:
		return "ir.noReg"
	case irtable.KRoutine:
		return "ir.noRoutine"
	}
	panic("rulegen: an operand that cannot be absent: " + x.Name)
}

// build is the constructor call of a result's operation, after the instructions of its nested operations, each of which
// defines a new register, are pushed to out.pre.
func (e *ruleEmitter) build(t *term, dst string) string {
	o := t.op
	pos := positionals(o)
	var args []string
	if dst != "" {
		args = append(args, dst)
	}
	at := 0
	for _, x := range o.Operands {
		var v string
		switch x.Kind {
		case irtable.KEdgeArgs, irtable.KMoreEdgeArgs:
			panic("rulegen: a result builds the terminator " + o.Name + ", whose edges carry arguments")
		case irtable.KEnum:
			en := enumOf(x.Enum)
			v = "ir." + en.Name + "." + lowerFirst(en.Prefix) + t.cas
		case irtable.KFlag:
			v = fmt.Sprint(t.flags[x.Flag])
		default:
			if pos[at].Name != x.Name {
				panic("rulegen: the positional operands are out of step at " + x.Name)
			}
			switch {
			case at >= len(t.args):
				v = absent(x)
			case x.Kind == irtable.KReg:
				v = e.buildReg(t.args[at])
			default:
				v = rewriteExpr(e.r, t.args[at].text, e.vars, local)
			}
			at++
		}
		if len(args) > 0 {
			v = lowerFirst(x.Name) + ": " + v
		}
		args = append(args, v)
	}
	return "ir.new" + o.Name + "(" + strings.Join(args, ", ") + ")"
}

func (e *ruleEmitter) buildReg(a *term) string {
	switch a.kind {
	case termVar:
		return local(a.name)
	case termOp:
		n := e.temp("new")
		ctor := e.build(a, n)
		e.line("let %s = fn.newReg(ir.IrKind.kindScalar)", n)
		e.line("out.pre.push(%s)", ctor)
		return n
	case termWild, termAux:
		panic("rulegen: a register built from " + a.String())
	}
	panic(fmt.Sprintf("rulegen: a term of kind %d", a.kind))
}
