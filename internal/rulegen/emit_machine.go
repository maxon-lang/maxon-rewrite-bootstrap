// The parameters of every generated selection function: the selector, which holds the machine IR being written, the IR
// function, and the instruction or terminator being selected.
// dispType is the Maxon type of a machine instruction's aux, which holds a displacement.
const dispType = "Imm32"

const (
	selectInstrParams = "mutates sel Selector, fn ir.IrFunction, ins ir.Instr"
	selectTermParams  = "mutates sel Selector, fn ir.IrFunction, ins ir.Term"
	selectArgs        = "sel, fn: fn, ins: ins"
)

// emitMachine writes instruction selection: <isa>SelectInstr and <isa>SelectTerm dispatch on the opcode to the function of each
// operation, which tries its rules in the order of the file, each a function that returns false at the first thing
// that does not match and otherwise writes the operation's machine instructions. Every operation has a rule that always
// matches, so the panic that ends each function is never reached.
func emitMachine(file string, rules []checked, tg target) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by rulegen from internal/rulegen/%s; DO NOT EDIT.\n\n", file)
	emitDispatch(&b, file, tg, false)
	emitDispatch(&b, file, tg, true)
	for _, o := range irtable.Ops {
		name := tg.machine.Name() + "Select" + o.Name
		params := selectInstrParams
		if o.Term {
			params = selectTermParams
		}
		fmt.Fprintf(&b, "\n// %s writes the machine instructions of %s by the first of its rules that matches.\nfunction %s(%s)\n", name, lowerFirst(o.Name), name, params)
		for _, c := range rules {
			if c.r.match.op.Name != o.Name {
				continue
			}
			for i := range c.variants {
				fn := machineVariantName(tg, c, i)
				fmt.Fprintf(&b, "\tif %s(%s) '%s'\n\t\treturn\n\tend '%s'\n", fn, selectArgs, fn, fn)
			}
		}
		fmt.Fprintf(&b, "\tpanic(\"backend: no rule of %s selects this %s\")\nend '%s'\n", file, lowerFirst(o.Name), name)
	}
	for _, c := range rules {
		for i, v := range c.variants {
			emitMachineRule(&b, file, c, i, v, tg)
		}
	}
	return b.String()
}

// machineVariantName is the function of a variant of a selection rule, named after its instruction set so that the
// selections of two instruction sets share a module.
func machineVariantName(tg target, c checked, i int) string {
	return tg.machine.Name() + capitalize(variantName(c, i))
}

// emitDispatch writes <isa>SelectInstr, or with terms <isa>SelectTerm.
func emitDispatch(b *strings.Builder, file string, tg target, terms bool) {
	isa := tg.machine.Name()
	if terms {
		fmt.Fprintf(b, "\n// %sSelectTerm writes the machine instructions of the terminator ins of fn by the first rule of %s that\n// matches it.\n", isa, file)
		fmt.Fprintf(b, "export function %sSelectTerm(%s)\n\tlet kind = ins.kind\n", isa, selectTermParams)
	} else {
		fmt.Fprintf(b, "// %sSelectInstr writes the machine instructions of the instruction ins of fn by the first rule of %s that\n// matches it.\n", isa, file)
		fmt.Fprintf(b, "export function %sSelectInstr(%s)\n\tlet op = ins.op\n", isa, selectInstrParams)
	}
	for _, o := range irtable.Ops {
		if o.Term != terms {
			continue
		}
		label := "opcode" + o.Name
		test := "op == ir.Opcode.op" + o.Name
		if terms {
			label = "term" + o.Name
			test = "kind == ir.TermKind.term" + o.Name
		}
		fmt.Fprintf(b, "\tif %s '%s'\n\t\t%sSelect%s(%s)\n\t\treturn\n\tend '%s'\n", test, label, isa, o.Name, selectArgs, label)
	}
	if terms {
		fmt.Fprintf(b, "\tpanic(\"backend: a terminator of no kind\")\nend '%sSelectTerm'\n", isa)
	} else {
		fmt.Fprintf(b, "\tpanic(\"backend: an instruction with no opcode\")\nend '%sSelectInstr'\n", isa)
	}
}

// defEvent is a form of a rule's results that defines a variable.
type defEvent struct {
	form int
	name string
}

// machineEmitter writes the results of one variant of a rule.
type machineEmitter struct {
	*ruleEmitter
	// cur is the Maxon expression of the machine register that each variable names at this point of the results: a
	// two-address form gives the variable it reads a new register.
	cur map[string]string
	// final is the definition that is the operation's result, if it has one.
	final    defEvent
	hasFinal bool
}

func emitMachineRule(b *strings.Builder, file string, c checked, i int, v *term, tg target) {
	r := c.r
	fn := machineVariantName(tg, c, i)
	fmt.Fprintf(b, "\n// %s:%d: %s\n", file, r.line, r.text)
	if i > 0 {
		fmt.Fprintf(b, "// with the operands swapped: %s\n", v)
	}
	params := selectInstrParams
	if r.match.op.Term {
		params = selectTermParams
	}
	fmt.Fprintf(b, "function %s(%s) returns bool\n", fn, params)
	e := &machineEmitter{ruleEmitter: &ruleEmitter{b: b, r: r, vars: map[string]*binding{}, bound: map[string]bool{}, tg: tg}, cur: map[string]string{}}
	checkMatch(r, v, e.vars, true, tg)
	e.matchRoot(v, "ins")
	if len(r.results) == 1 && isHelper(r.results[0]) {
		e.line("%s(%s)", r.results[0].name, selectArgs)
	} else {
		e.findFinal(v)
		for k, res := range r.results {
			e.emitForm(k, res)
		}
	}
	fmt.Fprintf(b, "\treturn true\nend '%s'\n", fn)
}

// findFinal finds the definition that is the operation's result: the last of the variable the pattern binds the
// result to, or if it binds none, the last of the results.
func (e *machineEmitter) findFinal(v *term) {
	if v.op.Result == irtable.NoResult {
		return
	}
	for k, res := range e.r.results {
		sh := shapeOf(e.tg, e.r, res)
		for i, a := range res.args {
			p := sh.Params[i]
			if (p.Role == isa.RoleDef || p.Role == isa.RoleReuse) && !e.tg.isRegister(a.name) && (v.bind == "" || a.name == v.bind) {
				e.final, e.hasFinal = defEvent{k, a.name}, true
			}
		}
	}
	if !e.hasFinal {
		panic("rulegen: a checked rule defines no result: " + e.r.text)
	}
}

// reg is the machine register a variable names at this point.
func (e *machineEmitter) reg(name string) string {
	if e.tg.isRegister(name) {
		return e.tg.machine.Name() + "PhysReg(" + isa.TypeName(e.tg.machine, "Register") + "." + name + ")"
	}
	if c, ok := e.cur[name]; ok {
		return c
	}
	return "vregOf(" + local(name) + ")"
}

// define is a new machine register for a variable that form k defines, which becomes what the variable names: the
// result's register, or a new one of the class of the form's operand.
func (e *machineEmitter) define(k int, name string, vector bool) string {
	t := e.temp("t")
	switch {
	case e.hasFinal && e.final == (defEvent{k, name}):
		e.line("let %s = sel.resultOf(ins.dst)", t)
	case vector:
		e.line("let %s = sel.newTempOf(RegClass.xmm)", t)
	default:
		e.line("let %s = sel.newTemp()", t)
	}
	e.cur[name] = t
	return t
}

// value is the Maxon of an expression of the rule, converted to ty when it is given.
func (e *machineEmitter) value(text, ty string) string {
	expr := rewriteExpr(e.r, text, e.vars, local, true)
	if ty == "" || number.MatchString(expr) {
		return expr
	}
	return fmt.Sprintf("try (%s) as %s otherwise panic(\"backend: a value of %s:%d does not fit %s\")", expr, ty, e.r.file, e.r.line, ty)
}

// emitForm writes result k: a copy, or a form with its fields.
func (e *machineEmitter) emitForm(k int, res *term) {
	sh := shapeOf(e.tg, e.r, res)
	letters := map[string]string{"a": "noMReg", "b": "noMReg", "c": "noMReg"}
	aux, imm, cond, ref := "0", "0", "", ""
	form := isa.TypeName(e.tg.machine, "Form") + "." + sh.Form
	var defs []string
	var vector []bool
	for i, a := range res.args {
		p := sh.Params[i]
		switch p.Role {
		case isa.RoleUse:
			letters[p.Letter] = e.reg(a.name)
		case isa.RoleReuse:
			letters["b"] = e.reg(a.name)
			if e.tg.isRegister(a.name) {
				letters["a"] = letters["b"]
			} else {
				defs = append(defs, a.name)
				vector = append(vector, p.Vector)
			}
		case isa.RoleDef:
			if e.tg.isRegister(a.name) {
				letters["a"] = e.reg(a.name)
			} else {
				defs = append(defs, a.name)
				vector = append(vector, p.Vector)
			}
		case isa.RoleDisp:
			aux = e.value(a.text, p.Type)
			// A second immediate, which a form of arm64 holds in aux, is of a narrower type than aux's.
			if p.Type != dispType {
				v := e.temp("x")
				e.line("let %s = %s", v, aux)
				aux = v + " as " + dispType
			}
		case isa.RoleImm:
			v := e.temp("i")
			e.line("let %s = %s", v, e.value(a.text, p.Type))
			imm = v
			if p.Type != "FullRangeInt" {
				imm = v + " as FullRangeInt"
			}
			if sh.Choice {
				form = "choose" + sh.Form + "(" + v + ")"
			}
		case isa.RoleCond:
			cond = e.value(a.text, "")
		case isa.RoleRel:
			if isEdgeVar(e.vars, a.text) {
				ref = e.edge(a.text)
				break
			}
			ref = e.referent(a.text)
		case isa.RoleRip:
			ref = e.referent(a.text)
		default:
			panic(fmt.Sprintf("rulegen: role %d", p.Role))
		}
	}
	// The registers a form reads are named before the ones it defines, so a two-address form reads the register its
	// variable named before it.
	for i, name := range defs {
		letters["a"] = e.define(k, name, vector[i])
	}
	if sh.Form == copyForm {
		e.line("sel.emit(newCopy(%s, src: %s))", letters["a"], letters["b"])
		return
	}
	m := e.temp("mi")
	e.line("var %s = new%s(%s, a: %s, b: %s, c: %s, aux: %s, imm: %s)", m, isa.TypeName(e.tg.machine, "Target"), form, letters["a"], letters["b"], letters["c"], aux, imm)
	if cond != "" {
		e.line("%s.cond = %s", m, cond)
	}
	if ref != "" {
		e.line("%s.ref = %s.ref", m, ref)
		e.line("%s.aux = %s.aux", m, ref)
	}
	e.line("sel.emit(%s)", m)
}

// referent is a local that holds what an expression of the rule refers to: a symbol, data or an import.
func (e *machineEmitter) referent(text string) string {
	v := e.temp("r")
	e.line("let %s = %s", v, e.value(text, ""))
	return v
}

// edge is a local that refers to the edge to the block of a variable, with the arguments the instruction passes along
// it: a terminator's target has the edge arguments of the operand that follows it, and a failure block none.
func (e *machineEmitter) edge(name string) string {
	b := e.vars[name]
	start, count := "0", "0"
	if b.operand.Kind == irtable.KBlock {
		o := e.r.match.op
		at := slices.IndexFunc(o.Operands, func(x irtable.Operand) bool { return x.Name == b.operand.Name })
		if at+1 >= len(o.Operands) || (o.Operands[at+1].Kind != irtable.KEdgeArgs && o.Operands[at+1].Kind != irtable.KMoreEdgeArgs) {
			panic("rulegen: the block " + b.operand.Name + " of " + o.Name + " is followed by no edge arguments")
		}
		args := getter(o, o.Operands[at+1])
		start, count = args+"Start(ins)", args+"Count(ins)"
	}
	v := e.temp("r")
	e.line("let %s = sel.edgeTo(fn, target: %s, start: %s, count: %s)", v, local(name), start, count)
	return v
}
