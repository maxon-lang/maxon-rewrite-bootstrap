package main

import (
	"fmt"
	"strings"
)

const (
	skipTableFile = "../../self/driver/skips.tsv"
	skipMaxonFile = "../../self/driver/skips_gen.maxon"
	skipNote      = "Code generated by internal/diaggen from self/driver/skips.tsv; DO NOT EDIT."

	maxonOnlyKind    = "code"
	maxonOnlyColumns = 3
	skipKind         = "skip"
	skipColumns      = 4
	expectKind       = "expect"
	runKind          = "run"
	firstKind        = "first"
	codeListColumns  = 3
	testKind         = "test"
	manualKind       = "manual"
	testColumns      = 4
	causeKind        = "cause"
	specSuffix       = ".md"

	// reasonForbidden are the characters that Go and Maxon do not escape alike in a string.
	reasonForbidden = "\"\\{}"
)

// skipRow is a row of the skip table: its kind, the codes maxon expects and the codes minimaxon reports for a test that is
// skipped for the reason, each as the Maxon expression of the code, the spec file and the name of the one test a test or manual row
// skips, or the case of diag.ErrorCause that a cause row skips by. An expect row has no reported codes, a run row no
// expected ones, and a test, manual or cause row neither.
type skipRow struct {
	kind               string
	expected, reported []string
	file, test         string
	cause              string
	reason             string
}

// parseSkips reads the skip table. The expected codes of a row are constants of the code table or maxon codes that a code
// row declares, and the reported codes are constants of the code table, so a code that does not exist is refused.
func parseSkips(src string, codes []row) ([]skipRow, error) {
	known := map[string]bool{}
	numbers := map[string]bool{}
	for _, r := range codes {
		known[r.constant] = true
		numbers[r.code] = true
	}
	maxonOnly := map[string]bool{}
	named := map[string]bool{}
	causes := map[string]bool{}
	var rows []skipRow
	for i, line := range strings.Split(src, "\n") {
		line = strings.TrimSuffix(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		at := fmt.Sprintf("%s:%d", skipTableFile, i+1)
		cols := strings.Split(line, "\t")
		var s skipRow
		var err error
		switch {
		case cols[0] == maxonOnlyKind && len(cols) == maxonOnlyColumns:
			code := cols[1]
			switch {
			case !codeText.MatchString(code):
				return nil, fmt.Errorf("%s: %q is not a code: write E and four digits", at, code)
			case numbers[code]:
				return nil, fmt.Errorf("%s: %s is a code of %s; name its constant instead of declaring it here", at, code, tableFile)
			case maxonOnly[code]:
				return nil, fmt.Errorf("%s: %s is declared twice", at, code)
			case cols[2] == "":
				return nil, fmt.Errorf("%s: %s has no meaning", at, code)
			}
			maxonOnly[code] = true
			continue
		case cols[0] == skipKind && len(cols) == skipColumns:
			s = skipRow{kind: skipKind, reason: cols[3]}
			if s.expected, err = skipCodes(cols[1], known, maxonOnly, at); err != nil {
				return nil, err
			}
			if s.reported, err = skipCodes(cols[2], known, nil, at); err != nil {
				return nil, err
			}
		case cols[0] == expectKind && len(cols) == codeListColumns:
			s = skipRow{kind: expectKind, reason: cols[2]}
			if s.expected, err = skipCodes(cols[1], known, maxonOnly, at); err != nil {
				return nil, err
			}
		case cols[0] == runKind && len(cols) == codeListColumns:
			s = skipRow{kind: runKind, reason: cols[2]}
			if s.reported, err = skipCodes(cols[1], known, nil, at); err != nil {
				return nil, err
			}
		case cols[0] == firstKind && len(cols) == codeListColumns:
			s = skipRow{kind: firstKind, reason: cols[2]}
			if s.reported, err = skipCodes(cols[1], known, nil, at); err != nil {
				return nil, err
			}
		case (cols[0] == testKind || cols[0] == manualKind) && len(cols) == testColumns:
			s = skipRow{kind: cols[0], file: cols[1], test: cols[2], reason: cols[3]}
			key := s.kind + "\t" + s.file + "\t" + s.test
			switch {
			case !strings.HasSuffix(s.file, specSuffix) || strings.ContainsAny(s.file, "/\\"+reasonForbidden):
				return nil, fmt.Errorf("%s: %q is not the name of a spec file: write the file's name, which ends in %s", at, s.file, specSuffix)
			case s.test == "" || strings.ContainsAny(s.test, reasonForbidden):
				return nil, fmt.Errorf("%s: the test's name is empty or holds a quote, a backslash or a brace", at)
			case named[key]:
				return nil, fmt.Errorf("%s: %s: %s is named twice", at, s.file, s.test)
			}
			named[key] = true
		case cols[0] == causeKind && len(cols) == codeListColumns:
			s = skipRow{kind: causeKind, cause: cols[1], reason: cols[2]}
			switch {
			case !causeText.MatchString(s.cause):
				return nil, fmt.Errorf("%s: %q is not the name of a case of diag.ErrorCause", at, s.cause)
			case causes[s.cause]:
				return nil, fmt.Errorf("%s: the cause %s is named twice", at, s.cause)
			}
			causes[s.cause] = true
		default:
			return nil, fmt.Errorf("%s: want a %s row of %d tab-separated columns, a %s, %s or %s row of %d, or an %s, %s, %s or %s row of %d", at, maxonOnlyKind, maxonOnlyColumns, skipKind, testKind, manualKind, skipColumns, expectKind, runKind, firstKind, causeKind, codeListColumns)
		}
		if s.reason == "" || strings.ContainsAny(s.reason, reasonForbidden) {
			return nil, fmt.Errorf("%s: the reason is empty or holds a quote, a backslash or a brace, which Go and Maxon do not escape alike", at)
		}
		rows = append(rows, s)
	}
	if len(rows) == 0 {
		return nil, fmt.Errorf("%s has no skip rows", skipTableFile)
	}
	return rows, nil
}

// skipCodes resolves a comma-separated list to the Maxon expression of each code: a constant of the code table is
// diag.constant, and a code of maxon that has a `code` row is the code as a string.
func skipCodes(list string, constants, maxonOnly map[string]bool, at string) ([]string, error) {
	var out []string
	for name := range strings.SplitSeq(list, ",") {
		switch {
		case constants[name]:
			out = append(out, "diag."+lowerFirst(name))
		case maxonOnly[name]:
			out = append(out, fmt.Sprintf("%q", name))
		default:
			return nil, fmt.Errorf("%s: %q is neither a constant of %s nor a code that a %s row declares above", at, name, tableFile, maxonOnlyKind)
		}
	}
	return out, nil
}

func emitMaxonSkips(rows []skipRow) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\n", skipNote)
	b.WriteString("// codeSkipTable is the codes for which `fix specs` skips a test, from self/driver/skips.tsv.\n")
	b.WriteString("function codeSkipTable() returns CodeSkips\n\tvar skips = CodeSkips.create(0)\n")
	for _, r := range rows {
		marker := "skip"
		if r.kind == manualKind {
			marker = "manual"
		}
		line := fmt.Sprintf("%q", "<!-- "+marker+": "+r.reason+" -->\n")
		switch r.kind {
		case skipKind:
			for _, e := range r.expected {
				for _, p := range r.reported {
					fmt.Fprintf(&b, "\tskips.push(CodeSkip.make(%s, reported: %s, line: %s))\n", skipExpr(e), skipExpr(p), line)
				}
			}
		case expectKind:
			for _, e := range r.expected {
				fmt.Fprintf(&b, "\tskips.push(CodeSkip.expecting(%s, line: %s))\n", skipExpr(e), line)
			}
		case runKind:
			for _, p := range r.reported {
				fmt.Fprintf(&b, "\tskips.push(CodeSkip.refusing(%s, line: %s))\n", skipExpr(p), line)
			}
		case firstKind:
			for _, p := range r.reported {
				fmt.Fprintf(&b, "\tskips.push(CodeSkip.reportingFirst(%s, line: %s))\n", skipExpr(p), line)
			}
		case testKind:
			fmt.Fprintf(&b, "\tskips.push(CodeSkip.naming(%q, test: %q, line: %s))\n", r.file, r.test, line)
		case manualKind:
			fmt.Fprintf(&b, "\tskips.push(CodeSkip.byHand(%q, test: %q, line: %s))\n", r.file, r.test, line)
		case causeKind:
			fmt.Fprintf(&b, "\tskips.push(CodeSkip.causing(diag.ErrorCause.%s, line: %s))\n", r.cause, line)
		default:
			panic(fmt.Sprintf("diaggen: a skip row of kind %q", r.kind))
		}
	}
	b.WriteString("\treturn skips\nend 'codeSkipTable'\n")
	return b.String()
}

// skipExpr is the expression of a code as an argument that a CodeSkip constructor consumes: a constant is copied, a literal
// is not.
func skipExpr(code string) string {
	if strings.HasPrefix(code, "diag.") {
		return code + ".clone()"
	}
	return code
}
