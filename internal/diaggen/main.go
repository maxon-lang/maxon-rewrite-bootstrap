// Command diaggen generates the diagnostic code constants of self/diag from self/diag/codes.tsv, their message
// functions from self/diag/messages.tsv, and the table of code pairs that `fix specs` skips from self/driver/skips.tsv,
// which names codes of the first. `go generate ./internal/diaggen` runs it.
// With --maxon <maxon repository> it writes nothing and checks the table against maxon's ErrorCodeRegistry.maxon
// instead.
package main

//go:generate go run .

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const (
	tableFile    = "../../self/diag/codes.tsv"
	maxonFile    = "../../self/diag/codes_gen.maxon"
	registryFile = "maxon-bin/Compiler/ErrorCodeRegistry.maxon"

	messageTableFile = "../../self/diag/messages.tsv"
	messageMaxonFile = "../../self/diag/messages_gen.maxon"

	columns        = 4
	messageColumns = 3
	noMaxonName    = "-"
	generated      = "Code generated by internal/diaggen from self/diag/codes.tsv; DO NOT EDIT."
	messageNote    = "Code generated by internal/diaggen from self/diag/messages.tsv; DO NOT EDIT."
)

var (
	constantName = regexp.MustCompile(`^Err[A-Z][A-Za-z0-9]*$`)
	codeText     = regexp.MustCompile(`^E[0-9]{4}$`)
	maxonName    = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)
	registryCase = regexp.MustCompile(`^\s*([A-Za-z][A-Za-z0-9]*)\s*=\s*"(E[0-9]{4})"\s*$`)
	messageName  = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)
	placeholder  = regexp.MustCompile(`\{([^{}]*)\}`)
)

type row struct {
	constant string
	code     string
	maxon    string
	meaning  string
}

// message is one situation that a code reports, with the text maxon prints for it. Its placeholders, in the order of
// their first use, are the parameters of the function that makes the text.
type message struct {
	name     string
	constant string
	template string
	params   []string
}

type output struct {
	path string
	code []byte
}

func main() {
	maxonRepo := flag.String("maxon", "", "path of the maxon repository: check the table against its error code registry instead of generating")
	flag.Parse()
	src, err := os.ReadFile(tableFile)
	if err != nil {
		fail(err)
	}
	rows, err := parseTable(string(src))
	if err != nil {
		fail(err)
	}
	messageSrc, err := os.ReadFile(messageTableFile)
	if err != nil {
		fail(err)
	}
	messages, err := parseMessages(string(messageSrc), rows)
	if err != nil {
		fail(err)
	}
	skipSrc, err := os.ReadFile(skipTableFile)
	if err != nil {
		fail(err)
	}
	skips, err := parseSkips(string(skipSrc), rows)
	if err != nil {
		fail(err)
	}
	if *maxonRepo != "" {
		registry, err := os.ReadFile(filepath.Join(*maxonRepo, filepath.FromSlash(registryFile)))
		if err != nil {
			fail(err)
		}
		if err := checkRegistry(rows, string(registry)); err != nil {
			fail(err)
		}
		return
	}
	for _, o := range generate(rows, messages, skips) {
		if err := os.WriteFile(o.path, o.code, 0o644); err != nil {
			fail(err)
		}
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "diaggen:", err)
	os.Exit(1)
}

// parseTable reads the rows of the table. The codes ascend, so that a code is found by its place and a duplicate
// cannot hide.
func parseTable(src string) ([]row, error) {
	var rows []row
	constants := map[string]bool{}
	for i, line := range strings.Split(src, "\n") {
		line = strings.TrimSuffix(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		at := fmt.Sprintf("%s:%d", tableFile, i+1)
		cols := strings.Split(line, "\t")
		if len(cols) != columns {
			return nil, fmt.Errorf("%s: want %d tab-separated columns, found %d", at, columns, len(cols))
		}
		r := row{cols[0], cols[1], cols[2], cols[3]}
		switch {
		case !constantName.MatchString(r.constant):
			return nil, fmt.Errorf("%s: %q is not a constant name: it starts with Err and a capital", at, r.constant)
		case !codeText.MatchString(r.code):
			return nil, fmt.Errorf("%s: %q is not a code: write E and four digits", at, r.code)
		case r.maxon != noMaxonName && !maxonName.MatchString(r.maxon):
			return nil, fmt.Errorf("%s: %q is neither a case name of maxon's registry nor %s", at, r.maxon, noMaxonName)
		case r.meaning == "":
			return nil, fmt.Errorf("%s: %s has no meaning", at, r.constant)
		case constants[r.constant]:
			return nil, fmt.Errorf("%s: %s is declared twice", at, r.constant)
		case len(rows) > 0 && r.code <= rows[len(rows)-1].code:
			return nil, fmt.Errorf("%s: %s is not above the code before it; keep the codes in ascending order, each once", at, r.code)
		}
		constants[r.constant] = true
		rows = append(rows, r)
	}
	if len(rows) == 0 {
		return nil, fmt.Errorf("%s has no rows", tableFile)
	}
	return rows, nil
}

// parseMessages reads the message table. Each row names the code constant it reports under, which must be a row of the
// code table, and a template whose {placeholders} are the parameters of the generated function.
func parseMessages(src string, codes []row) ([]message, error) {
	known := map[string]bool{}
	for _, r := range codes {
		known[r.constant] = true
	}
	var messages []message
	names := map[string]bool{}
	for i, line := range strings.Split(src, "\n") {
		line = strings.TrimSuffix(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		at := fmt.Sprintf("%s:%d", messageTableFile, i+1)
		cols := strings.Split(line, "\t")
		if len(cols) != messageColumns {
			return nil, fmt.Errorf("%s: want %d tab-separated columns, found %d", at, messageColumns, len(cols))
		}
		m := message{name: cols[0], constant: cols[1], template: cols[2]}
		switch {
		case !messageName.MatchString(m.name):
			return nil, fmt.Errorf("%s: %q is not a function name: start with a lower-case letter", at, m.name)
		case names[m.name]:
			return nil, fmt.Errorf("%s: %s is declared twice", at, m.name)
		case !known[m.constant]:
			return nil, fmt.Errorf("%s: %s is not a constant of %s", at, m.constant, tableFile)
		case m.template == "":
			return nil, fmt.Errorf("%s: %s has no template", at, m.name)
		case strings.ContainsAny(m.template, "\"\\"):
			return nil, fmt.Errorf("%s: the template of %s holds a quote or a backslash, which Go and Maxon do not escape alike", at, m.name)
		}
		params, err := templateParams(m.template)
		if err != nil {
			return nil, fmt.Errorf("%s: %s: %w", at, m.name, err)
		}
		m.params = params
		names[m.name] = true
		messages = append(messages, m)
	}
	if len(messages) == 0 {
		return nil, fmt.Errorf("%s has no rows", messageTableFile)
	}
	return messages, nil
}

// templateParams is the placeholders of a template in the order of their first use. A brace that is not part of a
// placeholder is refused, since Maxon would read it as an interpolation.
func templateParams(template string) ([]string, error) {
	var params []string
	seen := map[string]bool{}
	for _, m := range placeholder.FindAllStringSubmatch(template, -1) {
		name := m[1]
		switch {
		case !messageName.MatchString(name):
			return nil, fmt.Errorf("{%s} is not a parameter name: write a lower-case identifier", name)
		case !seen[name]:
			seen[name] = true
			params = append(params, name)
		}
	}
	if strings.Count(template, "{")+strings.Count(template, "}") != 2*len(placeholder.FindAllString(template, -1)) {
		return nil, fmt.Errorf("a brace of the template is not part of a {placeholder}")
	}
	return params, nil
}

func generate(rows []row, messages []message, skips []skipRow) []output {
	return []output{
		{maxonFile, []byte(emitMaxon(rows))},
		{messageMaxonFile, []byte(emitMaxonMessages(messages))},
		{skipMaxonFile, []byte(emitMaxonSkips(skips))},
	}
}

func emitMaxon(rows []row) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n", generated)
	for _, r := range rows {
		fmt.Fprintf(&b, "\n// %s\nexport let %s = %q\n", r.meaning, lowerFirst(r.constant), r.code)
	}
	return b.String()
}

func emitMaxonMessages(messages []message) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n", messageNote)
	for _, m := range messages {
		fmt.Fprintf(&b, "\n// The text of %s for: %s\nexport function %s(", lowerFirst(m.constant), m.template, m.name)
		for i, p := range m.params {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%s String", p)
		}
		fmt.Fprintf(&b, ") returns String\n\treturn %q\nend '%s'\n", m.template, m.name)
	}
	return b.String()
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

// checkRegistry verifies the table against maxon's registry: a row with a maxon name has the number that name has, and
// a row of minimaxon's own has a number the registry does not use.
func checkRegistry(rows []row, registry string) error {
	byName := map[string]string{}
	used := map[string]string{}
	for line := range strings.SplitSeq(registry, "\n") {
		if m := registryCase.FindStringSubmatch(strings.TrimSuffix(line, "\r")); m != nil {
			byName[m[1]] = m[2]
			used[m[2]] = m[1]
		}
	}
	if len(byName) == 0 {
		return fmt.Errorf("%s has no error code cases", registryFile)
	}
	var problems []string
	for _, r := range rows {
		if r.maxon == noMaxonName {
			if name, taken := used[r.code]; taken {
				problems = append(problems, fmt.Sprintf("%s: %s is maxon's %s; give it a number maxon does not use, or its name", r.constant, r.code, name))
			}
			continue
		}
		switch code, known := byName[r.maxon]; {
		case !known:
			problems = append(problems, fmt.Sprintf("%s: maxon has no %s", r.constant, r.maxon))
		case code != r.code:
			problems = append(problems, fmt.Sprintf("%s: maxon's %s is %s, not %s", r.constant, r.maxon, code, r.code))
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("the table disagrees with maxon's registry:\n%s", strings.Join(problems, "\n"))
	}
	return nil
}
