// Command diaggen generates the diagnostic code constants of internal/diag and self/diag from internal/diag/codes.tsv.
// `go generate ./internal/diag` runs it in that directory. With --maxon <maxon repository> it writes nothing and checks
// the table against maxon's ErrorCodeRegistry.maxon instead.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const (
	tableFile    = "codes.tsv"
	goFile       = "codes_gen.go"
	maxonFile    = "../../self/diag/codes_gen.maxon"
	registryFile = "maxon-bin/Compiler/ErrorCodeRegistry.maxon"

	columns     = 4
	noMaxonName = "-"
	generated   = "Code generated by internal/diaggen from internal/diag/" + tableFile + "; DO NOT EDIT."
)

var (
	constantName = regexp.MustCompile(`^Err[A-Z][A-Za-z0-9]*$`)
	codeText     = regexp.MustCompile(`^E[0-9]{4}$`)
	maxonName    = regexp.MustCompile(`^[a-z][A-Za-z0-9]*$`)
	registryCase = regexp.MustCompile(`^\s*([A-Za-z][A-Za-z0-9]*)\s*=\s*"(E[0-9]{4})"\s*$`)
)

type row struct {
	constant string
	code     string
	maxon    string
	meaning  string
}

type output struct {
	path string
	code []byte
}

func main() {
	maxonRepo := flag.String("maxon", "", "path of the maxon repository: check the table against its error code registry instead of generating")
	flag.Parse()
	src, err := os.ReadFile(tableFile)
	if err != nil {
		fail(err)
	}
	rows, err := parseTable(string(src))
	if err != nil {
		fail(err)
	}
	if *maxonRepo != "" {
		registry, err := os.ReadFile(filepath.Join(*maxonRepo, filepath.FromSlash(registryFile)))
		if err != nil {
			fail(err)
		}
		if err := checkRegistry(rows, string(registry)); err != nil {
			fail(err)
		}
		return
	}
	outs, err := generate(rows)
	if err != nil {
		fail(err)
	}
	for _, o := range outs {
		if err := os.WriteFile(o.path, o.code, 0o644); err != nil {
			fail(err)
		}
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "diaggen:", err)
	os.Exit(1)
}

// parseTable reads the rows of the table. The codes ascend, so that a code is found by its place and a duplicate
// cannot hide.
func parseTable(src string) ([]row, error) {
	var rows []row
	constants := map[string]bool{}
	for i, line := range strings.Split(src, "\n") {
		line = strings.TrimSuffix(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		at := fmt.Sprintf("%s:%d", tableFile, i+1)
		cols := strings.Split(line, "\t")
		if len(cols) != columns {
			return nil, fmt.Errorf("%s: want %d tab-separated columns, found %d", at, columns, len(cols))
		}
		r := row{cols[0], cols[1], cols[2], cols[3]}
		switch {
		case !constantName.MatchString(r.constant):
			return nil, fmt.Errorf("%s: %q is not a constant name: it starts with Err and a capital", at, r.constant)
		case !codeText.MatchString(r.code):
			return nil, fmt.Errorf("%s: %q is not a code: write E and four digits", at, r.code)
		case r.maxon != noMaxonName && !maxonName.MatchString(r.maxon):
			return nil, fmt.Errorf("%s: %q is neither a case name of maxon's registry nor %s", at, r.maxon, noMaxonName)
		case r.meaning == "":
			return nil, fmt.Errorf("%s: %s has no meaning", at, r.constant)
		case constants[r.constant]:
			return nil, fmt.Errorf("%s: %s is declared twice", at, r.constant)
		case len(rows) > 0 && r.code <= rows[len(rows)-1].code:
			return nil, fmt.Errorf("%s: %s is not above the code before it; keep the codes in ascending order, each once", at, r.code)
		}
		constants[r.constant] = true
		rows = append(rows, r)
	}
	if len(rows) == 0 {
		return nil, fmt.Errorf("%s has no rows", tableFile)
	}
	return rows, nil
}

func generate(rows []row) ([]output, error) {
	code, err := format.Source([]byte(emitGo(rows)))
	if err != nil {
		return nil, fmt.Errorf("%s does not parse as Go: %w", goFile, err)
	}
	return []output{{goFile, code}, {maxonFile, []byte(emitMaxon(rows))}}, nil
}

func emitGo(rows []row) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage diag\n\nconst (\n", generated)
	for _, r := range rows {
		fmt.Fprintf(&b, "\t%s = %q // %s\n", r.constant, r.code, r.meaning)
	}
	b.WriteString(")\n")
	return b.String()
}

func emitMaxon(rows []row) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n", generated)
	for _, r := range rows {
		fmt.Fprintf(&b, "\n// %s\nexport let %s = %q\n", r.meaning, lowerFirst(r.constant), r.code)
	}
	return b.String()
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

// checkRegistry verifies the table against maxon's registry: a row with a maxon name has the number that name has, and
// a row of minimaxon's own has a number the registry does not use.
func checkRegistry(rows []row, registry string) error {
	byName := map[string]string{}
	used := map[string]string{}
	for line := range strings.SplitSeq(registry, "\n") {
		if m := registryCase.FindStringSubmatch(strings.TrimSuffix(line, "\r")); m != nil {
			byName[m[1]] = m[2]
			used[m[2]] = m[1]
		}
	}
	if len(byName) == 0 {
		return fmt.Errorf("%s has no error code cases", registryFile)
	}
	var problems []string
	for _, r := range rows {
		if r.maxon == noMaxonName {
			if name, taken := used[r.code]; taken {
				problems = append(problems, fmt.Sprintf("%s: %s is maxon's %s; give it a number maxon does not use, or its name", r.constant, r.code, name))
			}
			continue
		}
		switch code, known := byName[r.maxon]; {
		case !known:
			problems = append(problems, fmt.Sprintf("%s: maxon has no %s", r.constant, r.maxon))
		case code != r.code:
			problems = append(problems, fmt.Sprintf("%s: maxon's %s is %s, not %s", r.constant, r.maxon, code, r.code))
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("the table disagrees with maxon's registry:\n%s", strings.Join(problems, "\n"))
	}
	return nil
}
