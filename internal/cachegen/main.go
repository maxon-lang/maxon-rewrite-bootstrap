// Command cachegen generates the functions that store a module's checked state in the build cache and load it back, from
// the declarations of the types of that state in self/'s source: each record field by field, each union by its case,
// each enum by its ordinal, each array with its count. Its source of truth is the Maxon declarations themselves, so a field
// added to a stored type is stored without a word here, and a field of a type it cannot store fails generation, naming it.
// `go generate ./internal/cachegen` runs it.
package main

//go:generate go run .

import (
	"fmt"
	"os"
	"path/filepath"
)

const header = "Code generated by internal/cachegen from the type declarations of self/; DO NOT EDIT."

// selfDir is self/ from the generator's directory, and outputName each module's generated file.
const (
	selfDir    = "../../self"
	outputName = "cache_gen.maxon"
)

// roots are the types whose values the build cache stores, by the module that declares them: what the stages of a module
// after its constants publish (README, "Build cache").
var roots = map[string][]string{
	"ast":   {"TypeSlot", "FuncSlot", "ModuleTables", "Tree", "Typing"},
	"ir":    {"IrFunction"},
	"opt":   {"Leaves"},
	"check": {"ModuleChecked"},
}

// derived are the fields a stored value leaves out, each loaded as the value given here: an index that the value's module
// rebuilds from what is stored. A slot's index of shapes also takes in the shapes of the other slots its tasks waited on,
// as the compile that ran them made those, so it is no function of the module's key; the slot loaded indexes its own
// shapes (ast.indexOwnShapes) and a task of its module imports the rest as any task does. A tree's text is its module's
// source, which the parse of the module that loads it read already (ast.ModuleHome.loadChecked).
var derived = map[string]string{
	"ast.TypeSlot.shapeIndex": "ShapeIndex.new()",
	"ast.TypeSlot.imported":   "SlotList.create(0)",
	"ast.Tree.text":           `""`,
}

// generate is the text of each module's generated file, by module.
func generate() (map[string]string, error) {
	w := &world{decls: map[string]map[string]*decl{}}
	for _, m := range layers {
		ds, err := readDecls(selfDir, m)
		if err != nil {
			return nil, err
		}
		w.decls[m] = ds
	}
	return newGen(w).run(roots)
}

// outputPath is where module's generated file is.
func outputPath(module string) string {
	return filepath.Join(selfDir, module, outputName)
}

func main() {
	files, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "cachegen:", err)
		os.Exit(1)
	}
	for _, m := range layers {
		text, ok := files[m]
		path := outputPath(m)
		if !ok {
			if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
				fmt.Fprintln(os.Stderr, "cachegen:", err)
				os.Exit(1)
			}
			continue
		}
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "cachegen:", err)
			os.Exit(1)
		}
	}
}
