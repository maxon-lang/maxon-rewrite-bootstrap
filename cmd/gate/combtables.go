package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// combTablesFile is the library's file of the curves' fixed-base tables and Montgomery moduli: the values that maxon's
// library builds once per process and keeps in its registry (helpers/crypto/CombCache.maxon), which the conversion calls as
// combTable(curve) and combModuli(curve) (cmd/convert, registrycache.go). They are derived from the curves' public constants
// only, so the regeneration computes them once with maxon's own build code and writes them as constants of the module.
var combTablesFile = filepath.Join("stdlib", "curves", "CombTables.maxon")

// combTableValue is one value the build code gives: the constant's name, the curve it is for, and whether it is a table
// (WorkspaceLimbs) or the moduli of a curve (a CombModuli of two WorkspaceLimbs).
type combTableValue struct {
	curve  string
	moduli bool
	build  string
}

// combTableValues are the values combTable and combModuli give, each with the expression of maxon's library that builds it.
var combTableValues = []combTableValue{
	{curve: "p256", build: "NistCurve.of(EcdsaCurve.p256).buildGeneratorTable()"},
	{curve: "p384", build: "NistCurve.of(EcdsaCurve.p384).buildGeneratorTable()"},
	{curve: "ed25519", build: "ed25519BuildBaseTable()"},
	{curve: "p256", moduli: true, build: "NistCurve.squaredOf(EcdsaCurve.p256)"},
	{curve: "p384", moduli: true, build: "NistCurve.squaredOf(EcdsaCurve.p384)"},
}

// combNoModuli is the curve whose moduli no caller asks for: ed25519's arithmetic keeps its own.
const combNoModuli = "ed25519"

const combTablesHeader = "// Code generated by cmd/gate (combtables.go) from the build code of maxon's curves; DO NOT EDIT.\n"

// combTablesStub is the file while the values are computed: combTable and combModuli build each value with the build code,
// and printCombTables writes them, one value to a line, its name and its limbs.
func combTablesStub() string {
	var b strings.Builder
	b.WriteString(combTablesHeader)
	writeCombLookups(&b, func(v combTableValue) string { return v.build })
	b.WriteString("\npublic function printCombTables()\n")
	for _, v := range combTableValues {
		if v.moduli {
			fmt.Fprintf(&b, "\tlet %s = %s\n", combValueName(v), v.build)
			fmt.Fprintf(&b, "\tprintCombLimbs(\"%sPrime\", limbs: %s.prime)\n", combValueName(v), combValueName(v))
			fmt.Fprintf(&b, "\tprintCombLimbs(\"%sOrder\", limbs: %s.order)\n", combValueName(v), combValueName(v))
			continue
		}
		fmt.Fprintf(&b, "\tprintCombLimbs(\"%s\", limbs: %s)\n", combValueName(v), v.build)
	}
	b.WriteString("end 'printCombTables'\n")
	b.WriteString(`
function printCombLimbs(name String, limbs WorkspaceLimbs)
	print(name)
	for limb in limbs 'limbs'
		print(" {limb}")
	end 'limbs'
	print("\n")
end 'printCombLimbs'
`)
	return b.String()
}

// combValueName is the name of v's constant: p256CombTable, p256CombModuli.
func combValueName(v combTableValue) string {
	if v.moduli {
		return v.curve + "CombModuli"
	}
	return v.curve + "CombTable"
}

// writeCombLookups writes combTable and combModuli, which give for each curve the expression value gives for its value.
func writeCombLookups(b *strings.Builder, value func(combTableValue) string) {
	for _, moduli := range []bool{false, true} {
		name, result := "combTable", "WorkspaceLimbs"
		if moduli {
			name, result = "combModuli", "CombModuli"
		}
		fmt.Fprintf(b, "\nfunction %s(curve CombCurve) returns %s\n\treturn match curve 'curve'\n", name, result)
		for _, v := range combTableValues {
			if v.moduli == moduli {
				fmt.Fprintf(b, "\t\t%s gives %s\n", v.curve, value(v))
			}
		}
		if moduli {
			fmt.Fprintf(b, "\t\t%s gives panic(\"curves: %s keeps no Montgomery moduli\")\n", combNoModuli, combNoModuli)
		}
		fmt.Fprintf(b, "\tend 'curve'\nend '%s'\n", name)
	}
}

// combTablesConstants is the file of the values printed (printCombTables's output): each a constant of the module.
func combTablesConstants(printed string) (string, error) {
	limbs := map[string]string{}
	for line := range strings.SplitSeq(strings.ReplaceAll(printed, "\r\n", "\n"), "\n") {
		name, values, ok := strings.Cut(line, " ")
		if !ok {
			continue
		}
		limbs[name] = "WorkspaceLimbs from [" + strings.ReplaceAll(values, " ", ", ") + "]"
	}
	var b strings.Builder
	b.WriteString(combTablesHeader)
	for _, v := range combTableValues {
		name := combValueName(v)
		if v.moduli {
			prime, order := limbs[name+"Prime"], limbs[name+"Order"]
			if prime == "" || order == "" {
				return "", fmt.Errorf("the build of the curves' tables printed no %s: %s", name, printed)
			}
			fmt.Fprintf(&b, "\nlet %sPrime = %s\n\nlet %sOrder = %s\n", name, prime, name, order)
			continue
		}
		if limbs[name] == "" {
			return "", fmt.Errorf("the build of the curves' tables printed no %s: %s", name, printed)
		}
		fmt.Fprintf(&b, "\nlet %s = %s\n", name, limbs[name])
	}
	writeCombLookups(&b, func(v combTableValue) string {
		if v.moduli {
			return fmt.Sprintf("CombModuli.create(%sPrime, order: %sOrder)", combValueName(v), combValueName(v))
		}
		return combValueName(v)
	})
	return b.String(), nil
}

// generateCombTables writes combTablesFile: the stub, then the constants that a program calling the stub prints. The
// library must be the converted and fixed one but for this file (fix runs between writeCombTablesStub and this).
func generateCombTables(compiler string) error {
	scratch, err := scratchDir("minimaxon-combtables-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(scratch)
	program := filepath.Join(scratch, "main.maxon")
	main := "function main() returns ExitCode\n\tprintCombTables()\n\treturn 0\nend 'main'\n"
	if err := os.WriteFile(program, []byte(main), 0o644); err != nil {
		return err
	}
	printed, err := output(nil, scratch, compiler, "run", program)
	if err != nil {
		return fmt.Errorf("%s%w", printed, err)
	}
	text, err := combTablesConstants(printed)
	if err != nil {
		return err
	}
	if err := os.WriteFile(combTablesFile, []byte(text), 0o644); err != nil {
		return err
	}
	return quiet(nil, compiler, "fmt", combTablesFile)
}

// writeCombTablesStub writes the stub of combTablesFile, which the library's fix and the build of the values compile.
func writeCombTablesStub() error {
	return os.WriteFile(combTablesFile, []byte(combTablesStub()), 0o644)
}
